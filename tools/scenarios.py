#!/usr/bin/env python3
"""Разложение доходности по источникам и сценарии на предпосылках (не на параметрах).

Контрфактические прогоны: движок, правило, сигналы и издержки те же; меняется только
доходность, которую нога зарабатывает сверх ставки кэша. Сигналы оставлены
историческими — это фактическая картина включений, а не пересчёт под новый мир.
"""
import sys
from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'r32build'))
import sim_v13 as S, sim_v164 as S164


def variant(d, k_eq=1.0, k_bd=1.0):
    """k — множитель ПРЕМИИ ноги сверх ставки кэша. k=0 — нога даёт ровно кэш."""
    days, re, rb, rfv, spy, dref, se, sb = d
    return (days, rfv + k_eq*(re - rfv), rfv + k_bd*(rb - rfv), rfv, spy, dref, se, sb)


def met(r):
    eq = (1+r).cumprod(); yrs = (r.index[-1]-r.index[0]).days/365.25
    v = r.std()*np.sqrt(252)*100; c = (eq.iloc[-1]**(1/yrs)-1)*100
    return c, v, (eq/eq.cummax()-1).min()*100


if __name__ == '__main__':
    d = S.build_splice(); days = d[0]
    rf_cagr = ((1+pd.Series(d[3], index=days)).prod())**(365.25/(days[-1]-days[0]).days)
    print(f"окно {days[0]:%m.%Y}–{days[-1]:%m.%Y}\n")
    print("A. РАЗЛОЖЕНИЕ: что останется, если убрать премию ноги\n")
    print(f"{'вариант':<44}{'CAGR':>8}{'качка':>8}{'MaxDD':>9}{'вклад':>9}")
    base = met(S164.sim164(*d)[0])
    print(f"{'полная стратегия':<44}{base[0]:>7.2f}%{base[1]:>7.2f}%{base[2]:>8.1f}%{'—':>9}")
    rows = {}
    for lbl, ke, kb in [('нога облигаций даёт ровно кэш', 1.0, 0.0),
                        ('нога акций даёт ровно кэш', 0.0, 1.0),
                        ('обе ноги дают ровно кэш (только векселя)', 0.0, 0.0)]:
        m = met(S164.sim164(*variant(d, ke, kb))[0])
        rows[lbl] = m
        print(f"{lbl:<44}{m[0]:>7.2f}%{m[1]:>7.2f}%{m[2]:>8.1f}%{base[0]-m[0]:>+8.2f}п")
    print(f"\n  ставка кэша сама по себе: {(rf_cagr-1)*100:.2f}% годовых")

    print("\n\nB. ОТКУДА ВЗЯЛАСЬ ДОХОДНОСТЬ ОБЛИГАЦИЙ\n")
    y = pd.read_csv(ROOT/'r32build/data/dgs10.csv', parse_dates=['observation_date']
                    ).set_index('observation_date')['DGS10'].dropna()
    for a, b, lbl in [('1963-03-01','1981-09-30','1963–1981 ставки растут'),
                      ('1981-09-30','2020-08-04','1981–2020 ставки падают'),
                      ('2020-08-04','2026-08-05','2020–2026 ставки растут')]:
        ya, yb = y[y.index >= a].iloc[0], y[y.index <= b].iloc[-1]
        print(f"  {lbl:<26} доходность 10-летки {ya:5.2f}% → {yb:5.2f}%")
    print(f"  за всё окно: {y[y.index>='1963-03-01'].iloc[0]:.2f}% → {y.iloc[-1]:.2f}% "
          f"— то есть НЕТТО почти без изменения")

    print("\n\nC. СЦЕНАРИИ ВПЕРЁД (правило и издержки те же, меняется только премия)\n")
    print(f"{'сценарий':<44}{'CAGR':>8}{'качка':>8}{'MaxDD':>9}")
    for lbl, ke, kb in [('как в истории', 1.0, 1.0),
                        ('облигации без попутного ветра (премия 0)', 1.0, 0.0),
                        ('премия облигаций вдвое меньше', 1.0, 0.5),
                        ('премия акций на четверть меньше', 0.75, 1.0),
                        ('и то и другое: акции −25%, облигации 0', 0.75, 0.0)]:
        m = met(S164.sim164(*variant(d, ke, kb))[0])
        print(f"{lbl:<44}{m[0]:>7.2f}%{m[1]:>7.2f}%{m[2]:>8.1f}%")
