#!/usr/bin/env python3
"""Ежедневный пульс: короткое письмо «машина жива» с главными цифрами. Каждое утро, 7/7.

ЗАЧЕМ (решение заказчика 29.08.2026). Мёртвая машина не может сообщить о своей смерти, а
внешние сервисы-сторожа заказчик отверг как чужую зависимость. Остаётся одно: письмо
ДОЛЖНО приходить каждый день, и тогда его отсутствие — само по себе сигнал «машина лежит».
Окно слепоты — сутки вместо недели.

ПОЭТОМУ ГЛАВНОЕ ПРАВИЛО СКРИПТА: он обязан отправить письмо ПРИ ЛЮБОМ состоянии данных.
Не читается книга, порван журнал, нет файла — письмо всё равно уходит, с текстом «жив, но
данные не читаются: ...». Пульс доказывает жизнь машины, а не здоровье контура; здоровьем
занимаются наблюдатель и сторож. Единственное, что вправе убить пульс, — смерть самой
машины или почты, и ровно это его молчание и означает.

Лёгкий и без Claude: зависимость только от питона и trevoga_mail.py.
"""
import datetime
import json
import pathlib
import re
import subprocess
import sys
import time

ДОМ = pathlib.Path('~/.addfut').expanduser()
ПОЧТАЛЬОН = pathlib.Path(__file__).with_name('trevoga_mail.py')


def безопасно(что, иначе='?'):
    """Кусочек данных не смеет валить пульс: любая ошибка превращается в '?'."""
    try:
        return что()
    except Exception:
        return иначе


def собрать():
    строки = []

    def нлв():
        т = (ДОМ / 'autopilot.log').read_text(encoding='utf-8', errors='replace')
        м = re.findall(r'(\d{4}-\d{2}-\d{2})[^\n]*замкнуто: NLV закрытия ([\d,]+\.\d+)', т)
        if not м:
            м2 = re.findall(r'замкнуто: NLV закрытия ([\d,]+\.\d+)', т)
            return ('?', м2[-1]) if м2 else ('?', '?')
        return м[-1]

    дата_нлв, нлв_т = безопасно(нлв, ('?', '?'))

    def книга():
        к = json.loads((ДОМ / 'book-F.json').read_text(encoding='utf-8'))['payload']
        б = к['book']
        нога_а = (f"{б['es_held']} ES + {б['n_e'] - 10 * б['es_held']} MES {б['ser_a']}"
                  if б.get('unit_is_mes') else f"{б['n_e']} ед. {б['ser_a']}")
        нога_а = нога_а if б['n_e'] else 'выключена'
        нога_б = f"{б['n_b']} ZN {б['ser_b']}" if б['n_b'] else 'выключена'
        return (нога_а, нога_б, f"{б.get('prev_close_lev', 0):.4f}",
                к.get('session_no', '?'), б.get('last_session', '?'))

    нога_а, нога_б, плечо, сессия, посл = безопасно(книга, ('?', '?', '?', '?', '?'))

    тревоги = безопасно(lambda: [ф.name for ф in ДОМ.glob('ALARM*')
                                 if '.resolved' not in ф.name], ['?'])

    def пульс_тика():
        возраст = time.time() - float((ДОМ / 'tick-heartbeat').read_text().strip())
        return f'{возраст / 60:.0f} мин назад'

    тик = безопасно(пульс_тика)

    строки.append(f'Счёт: NLV закрытия {нлв_т} $ (сессия №{сессия}, {дата_нлв if дата_нлв != "?" else посл})')
    строки.append(f'Нога А: {нога_а};  нога Б: {нога_б};  плечо {плечо}')
    строки.append(f'Тревоги: {"нет" if тревоги == [] else тревоги}')
    строки.append(f'Последний тик контура: {тик}')
    return нлв_т, нога_б, тревоги, '\n'.join(строки)


def главная():
    сегодня = datetime.date.today().strftime('%d.%m.%Y')
    try:
        нлв_т, нога_б, тревоги, тело = собрать()
        чисто = (тревоги == [])
        тема = (f'ПУЛЬС {сегодня}: жив — NLV {нлв_т}, '
                f'{"тревог нет" if чисто else "ЕСТЬ ТРЕВОГИ"}')
        текст = (f'Ежедневный пульс машины. Есть письмо — машина жива; нет утреннего '
                 f'письма — машина или её интернет лежат, стоит посмотреть.\n\n{тело}\n\n'
                 f'Подробности о событиях — отдельными письмами наблюдателя; сводка — по '
                 f'понедельникам.')
    except Exception as ошибка:
        # Даже полностью сломанный сбор данных не отменяет пульса — см. докстринг.
        тема = f'ПУЛЬС {сегодня}: машина жива, но данные не читаются'
        текст = (f'Пульс отправлен аварийной веткой: сбор данных упал '
                 f'({type(ошибка).__name__}: {ошибка}).\nМашина и почта работают; '
                 f'состоянием контура должен заняться наблюдатель или ручной разбор.')
    ход = subprocess.run([sys.executable, str(ПОЧТАЛЬОН), тема],
                         input=текст, text=True, capture_output=True, timeout=180)
    print(ход.stdout, end='')
    if ход.returncode != 0:
        print(ход.stderr, end='', file=sys.stderr)
    return ход.returncode


if __name__ == '__main__':
    raise SystemExit(главная())
