#!/usr/bin/env python3
"""Рецензия кода, написанного после шестого круга.

Седьмой круг отличается тем, что вся проверочная машинерия шестого круга сама написана
за один заход и никем, кроме автора, не смотрена. Рецензенту это сообщается прямо: главная
цель — не код стратегии, а ДОКАЗАТЕЛЬНАЯ СИЛА проверок, которыми он объявлен верным.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import openai_review as R

# НОМЕР КРУГА — В ОДНОМ МЕСТЕ (15.08): метка джоба была захардкожена отдельно от брифа и
# разошлась с ним — джоб 23-го круга ушёл в реестр как «двадцать второго». Реестр джобов
# служит доказательством оплаты и очерёдности, поэтому расхождение здесь не косметика.
KRUG_N = 29                          # номер: имя файла рецензии
KRUG_IM = 'двадцать девятый'          # именительный: заголовок брифа
KRUG_ROD = 'двадцать девятого'       # родительный: метка джоба в реестре

BRIEF_TPL = r"""
Ты — враждебный рецензент кода торговой системы. Найди дефекты, способные стоить денег, и
ЛОЖНЫЕ ДОКАЗАТЕЛЬСТВА. Не пересказывай и не хвали. По-русски, файл и функция, по приоритету:
неверная позиция, поставка, рассинхронизация с брокером, порча состояния.

КОНТЕКСТ. Нога А — ES/MES (10 MES = 1 ES, единица 500 x SPY), нога Б — ZN (модельная единица
112000 x 0,88 x D). Сигнал §1 МЕСЯЧНЫЙ: решение закрытием месяца M действует в M+1; строка
ряда помечена месяцем ДЕЙСТВИЯ. Полоса 10%, кап 2,00 по фактическому закрытию (замыкание —
отдельный запуск), ролл за 3 сессии до конца фев/мая/авг/ноя по праздничной таблице. Маршрут
Е — CSPX/CBU0; переходный исполнитель, лимит непарной дельты 1%.

{KRUG_IM_UP} КРУГ. Прошлые: 20, 16, 17, 22, 27, 28, 14, 18, 28, 12, 10, 8, 10, 10,
7, 6, 16, 21, 22, 22, 20, 24, 26, 29, 19, 22, 23, 18. Двадцать восьмой разобран на 15 из 18.
ЦЕЛЬ — НОЛЬ. Каждое замечание обязано называть денежный путь или ложное доказательство.

ЧЕТЫРЕ НЕЗАКРЫТЫХ — НАЗВАНЫ ЧЕСТНО, НЕ ЗАГЛУШЕНЫ:
№1 сверка маршрута по двум источникам остаётся FAIL-OPEN. Строгий вариант требует
mr_engine.derive_state, которому нужен configure(), а тот ПИНУЕТ путь журнала и отвергает
чужой — конфликт с конфигурацией переходного исполнителя в том же процессе. Нужен способ
прочитать действующий маршрут из журнала БЕЗ перенастройки пина.
№3 отчёты дня не сопоставляются с заявками намерения. Сопоставить НЕЧЕМ: intent хранит
пары «инструмент-количество», а todays_executions отдаёт только permId — ни идентификаторов
заявок, ни инструментов. Нужна запись order_ids в намерение при подаче либо отчёты с
инструментом и объёмом. Заглушку не ставил намеренно: она не сработала бы никогда.
№4 разведение корня и полного имени не доведено до сквозного пути (load_registry и
смежные) — переработка, а не правка.
№7 день перехода не имеет штатного пути через автопилот — тоже переработка.

ЖИВОГО ПОДТВЕРЖДЕНИЯ НЕТ: торговля на бумажном счёте идёт, но переход Ф<->Е ни разу не
исполнялся вживую (замер маржи покрывает только U26 при реестре U26+Z26, переход
заблокирован воротами). Всё, что касается исполнителя перехода, проверено ТОЛЬКО стендами.
Замер обеих серий назначен на 17.08, 08:00 Чикаго; с 20.08 его отсутствие — провал выпуска.

СДЕЛАНО ПОСЛЕ 28-го: ADDFUT_REALTIME_MD=1 включает реальное время и доводит признак до
адаптера и выборки §7 (прежде путь после покупки подписки ОТСУТСТВОВАЛ, хотя был обещан).
Межпроцессный стоп-файл при невозможности записать ALARM (прежде останавливался только
текущий тик, следующий cron входил в торговлю). Ветка штатного повтора стала достижимой
(её перехватывала более ранняя ветка). Намерение проверяется у ОБОИХ маршрутов;
восстановимость d_fix — фактом, а не hasattr. Метки передачи ставятся ПОСЛЕ предполёта.
EMERGENCY_OVERRIDE пишется после сухих проверок. Резерв квоты и времени — на продажу,
покупку И компенсацию. Замыкание Е переживает длинные европейские праздники (сбор рынка
починили в 26-м, а замыкание звало ту же функцию БЕЗ календаря). WORM берёт маршрут через
active_route и сверяет blob с ПРОВЕРЕННЫМ телом, а не с файлом после hook. Наблюдение
О-3-Е не отключается тревогой: тревога запрещает действия, а не измерения. Замыкание —
по положительному признаку, а не чёрному списку.

ИЩИ ЧЕТЫРЕ КЛАССА: (1) проверка не на своём месте относительно необратимого шага;
(2) проверка на месте, но НЕДОСТИЖИМА (перехвачена более ранней веткой); (3) стенд
закрепляет дефект как норму; (4) исправлена ОДНА точка вызова из нескольких.
"""
BRIEF = BRIEF_TPL.replace("{KRUG_IM_UP}", KRUG_IM.upper())


if __name__ == '__main__':
    ROOT = Path(__file__).resolve().parent.parent
    items, sk = R.collect([ROOT / 'r33build/live', ROOT / 'r33build/transition.py',
                           ROOT / 'r33build/mr_engine.py', ROOT / 'r33build/sim_v13.py',
                           ROOT / 'r33build/sim_v164.py', ROOT / 'tools/release.py',
                           ROOT / 'r33build/selfcheck_v192.py',
                           ROOT / 'tools/autopilot.sh'])
    txt = BRIEF + '\n' + ''.join(f'\n===== ФАЙЛ: {n} =====\n{t}\n' for n, t in items)
    print(f'к отправке: файлов {len(items)}, знаков {len(txt):,}; пропущено {sk}')
    out, sec = R.ask(R._client(), txt, f'рецензия {KRUG_ROD} круга')
    # ИМЯ ФАЙЛА — ИЗ НОМЕРА КРУГА, И ЗАТИРАТЬ ЧУЖОЕ ЗАПРЕЩЕНО (15.08). Хардкод 'krug22'
    # пережил обновление брифа, и рецензия 23-го круга ЗАТЁРЛА текст 22-го — файл не был
    # под git, спасла только копия для выгрузки. Номер берётся из KRUG_N, а существующий
    # файл не перезаписывается молча.
    dst = ROOT / f'docs/kritika-krug{KRUG_N}.md'
    if dst.exists():
        raise SystemExit(f'{dst} уже существует — рецензия {KRUG_N}-го круга затёрла бы '
                         f'чужой текст; переименуйте старый файл или поправьте KRUG_N')
    dst.write_text(f'# Рецензия двадцать второго круга ред. 33 ({R.MODEL}, pro+max)\n\n{out}\n',
                   encoding='utf-8')
    print(f'\nзаписано: {dst} ({len(out):,} знаков) за {sec} с')
