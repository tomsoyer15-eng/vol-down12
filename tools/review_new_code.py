#!/usr/bin/env python3
"""Рецензия кода, написанного после шестого круга.

Седьмой круг отличается тем, что вся проверочная машинерия шестого круга сама написана
за один заход и никем, кроме автора, не смотрена. Рецензенту это сообщается прямо: главная
цель — не код стратегии, а ДОКАЗАТЕЛЬНАЯ СИЛА проверок, которыми он объявлен верным.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import openai_review as R

# НОМЕР КРУГА — В ОДНОМ МЕСТЕ (15.08): метка джоба была захардкожена отдельно от брифа и
# разошлась с ним — джоб 23-го круга ушёл в реестр как «двадцать второго». Реестр джобов
# служит доказательством оплаты и очерёдности, поэтому расхождение здесь не косметика.
KRUG_N = 28                          # номер: имя файла рецензии
KRUG_IM = 'двадцать восьмой'          # именительный: заголовок брифа
KRUG_ROD = 'двадцать восьмого'       # родительный: метка джоба в реестре

BRIEF_TPL = r"""
Ты — враждебный рецензент кода торговой системы. Найди дефекты, способные стоить денег, и
ЛОЖНЫЕ ДОКАЗАТЕЛЬСТВА. Не пересказывай и не хвали. По-русски, файл и функция, по приоритету:
неверная позиция, поставка, рассинхронизация с брокером, порча состояния.

КОНТЕКСТ. Нога А — ES/MES (10 MES = 1 ES, единица 500 x SPY), нога Б — ZN (модельная единица
112000 x 0,88 x D). Сигнал §1 МЕСЯЧНЫЙ: решение закрытием месяца M действует в M+1; строка
ряда помечена месяцем ДЕЙСТВИЯ. Полоса 10%, кап 2,00 по фактическому закрытию (замыкание —
отдельный запуск), ролл за 3 сессии до конца фев/мая/авг/ноя по праздничной таблице. Маршрут
Е — CSPX/CBU0; переходный исполнитель, лимит непарной дельты 1%.

{KRUG_IM_UP} КРУГ. Прошлые: 20, 16, 17, 22, 27, 28, 14, 18, 28, 12, 10, 8, 10, 10,
7, 6, 16, 21, 22, 22, 20, 24, 26, 29, 19, 22, 23. Двадцать седьмой разобран на 20 из 23.
ЦЕЛЬ — НОЛЬ. Каждое замечание обязано называть денежный путь или ложное доказательство.

НЕ ЗАКРЫТО В 27-м (назови, если найдёшь новое): №9 закрыт по существу разведением корня и
имени (маржа ключуется КОРНЕМ, инструмент — полным именем); №11 (замыкание Е в длинные
европейские праздники) НЕ сделано; №19 (миграция фикстур на поставочные серии) ОТКЛОНЕНО:
исполнитель пинует SHA-256 ПОСТАВЛЕННОГО реестра, подмена в стендах невозможна по
построению — требование серии сделано СВОЙСТВОМ активного реестра.

ЧЕСТНО О СОСТОЯНИИ: цены плана перехода задаёт вызывающий; execute() не имеет живого
вызывающего; замер маржи покрывает только U26 при реестре U26+Z26 (с 20.08 — провал
выпуска, замер назначен на 17.08 08:00 Чикаго); HOLIDAYS_EU только 2026; SHORT_SESSIONS
пуста намеренно; избыток оборота перекладки не списывается (ломает 1e-12); О-5 останавливает
контур до человека; ДАННЫЕ ТИПА 3 задержаны ~15 мин, поэтому §7 не наберёт выборку издержек
до подписки реального времени.

СДЕЛАНО ПОСЛЕ 27-го: активный маршрут сверяется по ДВУМ источникам (route.txt и журнал МР);
route() не выбирает Ф молча. Серия целей и восстановимость d_fix — в предполёте, до первой
заявки. Метки передачи — после всех сухих проверок. Резерв окна в ролле требуется ДО первой
заявки пары. cap-срез считает капитал заново от исходного на каждом шаге. touch traded-$day
проверяется; closed-$day только после резервной копии; праздничная вахта О-3-Е не глотает
сбой; reconcile на одном снимке; EMERGENCY_OVERRIDE после сухих проверок; cancel_order с
барьером отчётов; ликвидация в ноль требует отчётов. «Штатный повтор» — по положительному
признаку, а не чёрному списку. _machine_snapshot включает traded-/closed-/sigup-.
release.py под замком; живая пара не пакуется, проверка объявляет себя неприменимой.

ИЩИ ТРИ КЛАССА: (1) проверка не на своём месте относительно НЕОБРАТИМОГО шага; (2) стенд
закрепляет дефект как норму; (3) правка, не прогнанная по своему пути (область видимости,
половина правки, зелёный итог от непроверяющей проверки).
"""
BRIEF = BRIEF_TPL.replace("{KRUG_IM_UP}", KRUG_IM.upper())


if __name__ == '__main__':
    ROOT = Path(__file__).resolve().parent.parent
    items, sk = R.collect([ROOT / 'r33build/live', ROOT / 'r33build/transition.py',
                           ROOT / 'r33build/mr_engine.py', ROOT / 'r33build/sim_v13.py',
                           ROOT / 'r33build/sim_v164.py', ROOT / 'tools/release.py',
                           ROOT / 'r33build/selfcheck_v192.py',
                           ROOT / 'tools/autopilot.sh'])
    txt = BRIEF + '\n' + ''.join(f'\n===== ФАЙЛ: {n} =====\n{t}\n' for n, t in items)
    print(f'к отправке: файлов {len(items)}, знаков {len(txt):,}; пропущено {sk}')
    out, sec = R.ask(R._client(), txt, f'рецензия {KRUG_ROD} круга')
    # ИМЯ ФАЙЛА — ИЗ НОМЕРА КРУГА, И ЗАТИРАТЬ ЧУЖОЕ ЗАПРЕЩЕНО (15.08). Хардкод 'krug22'
    # пережил обновление брифа, и рецензия 23-го круга ЗАТЁРЛА текст 22-го — файл не был
    # под git, спасла только копия для выгрузки. Номер берётся из KRUG_N, а существующий
    # файл не перезаписывается молча.
    dst = ROOT / f'docs/kritika-krug{KRUG_N}.md'
    if dst.exists():
        raise SystemExit(f'{dst} уже существует — рецензия {KRUG_N}-го круга затёрла бы '
                         f'чужой текст; переименуйте старый файл или поправьте KRUG_N')
    dst.write_text(f'# Рецензия двадцать второго круга ред. 33 ({R.MODEL}, pro+max)\n\n{out}\n',
                   encoding='utf-8')
    print(f'\nзаписано: {dst} ({len(out):,} знаков) за {sec} с')
