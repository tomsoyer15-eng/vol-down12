#!/usr/bin/env python3
"""Решение сторожа по git-подкомандам. Оболочка передаёт команду, получает вердикт.

ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ НА ПИТОНЕ (правило 8д). Здесь одиннадцать развилок; в оболочке их
не видит ни один измеритель — ворота 8в-1 понимают только питон, поэтому 1427 строк
autopilot.sh простояли непокрытыми дольше всех. Новые решения пишутся там, где их видно.

ЧТО ИСПРАВЛЯЕТСЯ (28.08.2026, рецензия, находка №15). Прежнее правило в оболочке
запрещало ЛЮБУЮ строку со словом checkout — то есть создание ветки и переключение между
ветками, действия совершенно безобидные, — и при этом пропускало все современные
разрушительные написания: принудительное переключение, удаление ветки, снятие рабочего
дерева, удаление ссылки, чистку журнала ссылок и сборку мусора с обрезкой. Последние три
уничтожают ровно те точки восстановления, которые правило 11 называет запасным выходом
этого же сторожа. Перегиб и дыра жили вместе, потому что правило было одно на всё.

ОТКУДА СПИСОК: каждое написание проверено на установленном git 2.43.0 рецензентом и
воспроизведено здесь стендом tools/guard_probe.py. Список ПОПОЛНЯЕТСЯ, не сокращается.
"""
import re
import sys

# (шаблон, за что запрещено) — шаблон применяется к НОРМАЛИЗОВАННОЙ строке, где уже срезан
# путь к исполняемому файлу и сняты табуляции.
ЗАПРЕТЫ = [
    (r'reset\s+(--hard|--merge|--keep)', 'жёсткий сброс рабочего дерева'),
    (r'clean\s+-', 'удаление неотслеживаемых файлов'),
    (r'restore(\s|$)', 'восстановление файлов поверх правок'),
    # checkout: запрещаем то, что трогает ФАЙЛЫ, разрешаем то, что трогает ВЕТКИ.
    (r'checkout\s+(--(\s|$)|-f(\s|$)|--force|\.(\s|$)|[^\s-]*/)',
     'checkout поверх файлов рабочего дерева'),
    (r'switch\s+(-f(\s|$)|--force|--discard-changes)', 'принудительное переключение ветки'),
    (r'branch\s+(-D(\s|$)|--delete\s+--force|-d\s+-f)', 'удаление ветки без слияния'),
    (r'worktree\s+remove', 'снятие рабочего дерева'),
    (r'update-ref\s+(-d(\s|$)|--delete)', 'удаление ссылки на историю'),
    (r'reflog\s+expire', 'чистка журнала ссылок — теряется путь к утраченным коммитам'),
    (r'gc\s+--prune', 'сборка мусора с обрезкой — недостижимые коммиты исчезают'),
    (r'push\s+(--force|-f(\s|$)|--mirror|--delete)', 'перезапись или удаление на удалённом'),
]

ГРАНИЦА = r'(^|[^A-Za-z0-9_./-])git\s'


def вердикт(команда):
    """Вернуть причину отказа или None. Одна точка решения — одна точка мутации."""
    if not re.search(ГРАНИЦА, команда):
        return None
    for шаблон, за_что in ЗАПРЕТЫ:
        if re.search(ГРАНИЦА + r'.*' + шаблон, команда):
            return за_что
    return None


if __name__ == '__main__':
    _причина = вердикт(sys.stdin.read())
    if _причина:
        print(_причина, end='')
        raise SystemExit(1)
    raise SystemExit(0)
