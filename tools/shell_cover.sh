#!/usr/bin/env bash
# ПОКРЫТИЕ ОБОЛОЧКИ АВТОПИЛОТА: какие её строки исполняет вызов функции.
#
# ЗАЧЕМ. Ворота 8в-1 считают исполненные строки через sys.monitoring, а он видит только
# Python. Оболочка (live/autopilot.sh, 1427 строк, 84 точки ветвления) вне измерения, и
# ворота ни разу не сказали о ней ни слова — пробел был невидим ПО ПОСТРОЕНИЮ (§5б).
#
# КАК. bash -x с PS4='+${LINENO} ' пишет номер КАЖДОЙ исполненной строки в отдельный
# дескриптор; разбираем его и печатаем отсортированный список.
#
# ЧЕГО ЭТОТ ИНСТРУМЕНТ НЕ ДАЁТ, сказано прямо: он видит ИСПОЛНЕННЫЕ строки, но НЕ обе
# стороны ветвления — строка `if` попадает в след и при истинном, и при ложном условии.
# Для «взято в обе стороны» нужен стенд: вырезание функции и прогон боевого текста, как
# сделано для o3e_probe и для env_guard. Инструмент даёт КАРТУ, а не доказательство.
#
# ТРИ ГРАБЛИ, КАЖДАЯ СТОИЛА ЗАХОДА (26.08.2026):
#  1. Имена переменных ЛАТИНИЦЕЙ. Правило 10 требует русского в комментариях и документах,
#     но bash не поддерживает нелатинские ИДЕНТИФИКАТОРЫ: присваивание кириллическим
#     именем он не считает присваиванием — печатает имя буквально и мерит мусор.
#  2. Плюсов в следе СТОЛЬКО, КАКОВА ГЛУБИНА ВЛОЖЕННОСТИ ('++1', '+++18'). Шаблон
#     `^\+[0-9]+` не видит почти ничего; нужен `^\++[0-9]+`.
#  3. ГЛАВНОЕ И НЕОЧЕВИДНОЕ: ДЕСКРИПТОР 9 ЗАНЯТ САМИМ БОЕВЫМ ФАЙЛОМ. autopilot.sh:418
#     делает `exec 9>"$ST/autopilot.lock"` — это его замок, а :417 держит копию stderr в
#     fd 8. Черновик отдал под BASH_XTRACEFD ровно девятку, и с 418-й строки след уходил
#     В НАСТОЯЩИЙ ФАЙЛ ЗАМКА: измеритель молча мерил 13 строк вместо всей функции, а пять
#     РАЗНЫХ функций давали одинаковое число. Записанная тогда догадка («подключение
#     обрывается рано») была НЕВЕРНА — обрывался не source, а дескриптор. Поэтому здесь
#     дескриптор не выбирается руками, а выделяется bash'ем: `exec {TF}>` даёт свободный
#     (>=10), и столкнуться с боевыми 8 и 9 невозможно ПО ПОСТРОЕНИЮ, а не по внимательности.
#
# ИЗОЛЯЦИЯ — ЧЕРЕЗ HOME, А НЕ ЧЕРЕЗ ADDFUT_* (26.08.2026, разбор живой остановки контура).
# Правило 5 велит стендам уводить состояние на временные пути, и для ПИТОНОВСКОГО слоя это
# ADDFUT_DIR/ADDFUT_LOCK_DIR/ADDFUT_BOOK_PATH. Для ОБОЛОЧКИ этот рычаг не просто не
# работает — он вреден: autopilot.sh:22 задаёт `ST=$HOME/.addfut` жёстко и ADDFUT_DIR не
# читает, а env_guard на любую ADDFUT_* пишет ДОЛГОВЕЧНУЮ датированную тревогу в БОЕВОЙ
# каталог и останавливает контур. Именно так 26.08 зонды слоя 1 остановили живой пилот:
# ALARM-env-2026-08-26.txt написан не cron'ом, а стендом. Рычаг оболочки — HOME; он же
# используется обвязкой _PREFIX в invariants.py. Окружение здесь строится с нуля (env -i),
# чтобы ни одна ADDFUT_* из сессии не просочилась в измеряемый прогон.
set -u
FILE="${1:?первый аргумент — путь к autopilot.sh (или --самопроверка)}"

# СЛЕДЫ УБИРАЮТСЯ ЗА СОБОЙ (рецензия 27.08). Прежняя редакция плодила по файлу следа на
# каждый вызов и по каталогу временного дома на прогон — за один день накопилось 56 и 44.
# Переполнение /tmp — это остановка автопилота, такой инцидент в проекте уже был, то есть
# измеритель слоя 1 сам стал бы источником отказа слоя 1.
#
# УБОРКА БЕЗ -r, БЕЗ -f И БЕЗ ИМЁН. Три свойства, и каждое осмысленно.
#  * без -r и -f — правило 11 запрещает рекурсивное и принудительное удаление;
#  * поимённо снимаются ФАЙЛЫ, каталоги снимает rmdir — если во временном доме заведётся
#    неожиданный подкаталог, rmdir откажет и оставит след, вместо того чтобы молча снести
#    незнакомое. Инструмент, убирающий за собой рекурсивно, однажды уберёт лишнее;
#  * имя каталога состояния (.addfut) здесь НЕ ПИШЕТСЯ вовсе: dotglob раскрывает скрытые
#    имена сам. Так уборка не зависит от того, как боевой файл назвал свой каталог, и
#    физически не может указать на машинное состояние — корень взят из mktemp.
TRACE=$(mktemp /tmp/addfut-xtrace-XXXXXX)
HOMEDIR=$(mktemp -d /tmp/addfut-cover-home-XXXXXX)
KEEP=${ADDFUT_COVER_KEEP:-}          # оставить следы для разбора: ADDFUT_COVER_KEEP=1
_убрать() {
    if [ -n "$KEEP" ]; then echo "следы оставлены: $TRACE* $HOMEDIR"; return; fi
    shopt -s dotglob nullglob
    rm "$TRACE"* 2>/dev/null
    # ДВА УРОВНЯ, И ОБА НУЖНЫ: во временном доме лежат и файлы каталога состояния
    # ("$HOMEDIR"/*/*), и файлы самого дома — заглушка питона и журнал попыток
    # ("$HOMEDIR"/*). Первая редакция снимала только вложенные, и rmdir дома отказывал на
    # непустом каталоге: следы убирались, дома копились. Поймано счётом каталогов ДО и
    # ПОСЛЕ прогона, а не чтением.
    rm "$HOMEDIR"/*/* 2>/dev/null
    rm "$HOMEDIR"/* 2>/dev/null
    rmdir "$HOMEDIR"/* "$HOMEDIR" 2>/dev/null
    shopt -u dotglob nullglob
}
trap _убрать EXIT INT TERM

измерить() {           # $1 — файл, $2 — функция, дальше аргументы; печатает номера строк
    local _f="$1" _fn="$2"; shift 2
    # ИМЯ СЛЕДА ДЕТЕРМИНИРОВАНО, А НЕ СЛУЧАЙНО: самопроверке нужно заглянуть в СЫРОЙ
    # след (глубина вложенности), а `измерить` зовётся через $( ), то есть в подоболочке —
    # переменную наружу не вернуть.
    local _t="$TRACE.$_fn" _base="${_f##*/}"
    env -i HOME="$HOMEDIR" PATH="$PATH" TERM=dumb bash -c '
        mkdir -p "$HOME/.addfut"
        exec {TF}>"'"$_t"'"
        # ДОЛЛАР ЭКРАНИРОВАН: строка живёт внутри одинарных кавычек `bash -c`, то есть
        # разбирается ПОДОБОЛОЧКОЙ как обычный скрипт. Без обратной косой ${LINENO}
        # раскрылось бы В МОМЕНТ ПРИСВАИВАНИЯ, и весь след получил бы один номер строки.
        #
        # ИМЯ ФАЙЛА В PS4 — ПО РЕЦЕНЗИИ 27.08. Без него в след шли И строки боевого файла,
        # И строки самой обёртки, неотличимо: строки 14-17 обёртки выдавались за строки
        # 14-17 autopilot.sh, где лежат КОММЕНТАРИИ. Четыре фантома из тридцати двух,
        # всегда в одном диапазоне, и самопроверка их не видела, потому что смотрела на
        # РАЗМЕР множества, а не на его происхождение. Номер строки без имени файла — не
        # адрес, а совпадение.
        export BASH_XTRACEFD=$TF PS4="+\${BASH_SOURCE##*/}:\${LINENO} "
        set -x
        # ВЕТКА `*)` БОЕВОГО DISPATCH ЗОВЁТ exit — на время подключения подменяем его,
        # иначе подоболочка умирает до вызова функции и след содержит только преамбулу.
        exit() { return 0; }
        source "$1" __измерение__ >/dev/null 2>&1
        unset -f exit
        # ПУТИ НАРУЖУ ОБРУБАЮТСЯ ПОСЛЕ ПОДКЛЮЧЕНИЯ — ГЛАВНАЯ ПРАВКА ПО РЕЦЕНЗИИ 27.08.
        # HOME уводил только $ST, то есть СОСТОЯНИЕ. А ROOT, PY и LIVE в autopilot.sh
        # АБСОЛЮТНЫ. На env_guard это ничем не грозило, и потому прошло незамеченным, — но
        # следующие по плану tick и run_trade ходят через "$PY" в session.py и поднимают
        # шлюз из "$LIVE/ibgw". То есть измеритель слоя 1 на СЛЕДУЮЩЕМ ЖЕ шаге подключился
        # бы к живому бумажному счёту и мог подать заявки: инструмент, написанный после
        # остановки контура собственным зондом, воспроизвёл бы её крупнее.
        # Питон подменяется заглушкой, которая ничего не делает, отдаёт заведомо нештатный
        # код и ЗАПИСЫВАЕТ попытку: видно, куда боевой код тянулся, и при этом он никуда
        # не дотянулся. Прямую пробу порта (/dev/tcp) это не закрывает — она лишь смотрит,
        # жив ли шлюз, и без питона всё равно ничем не торгует.
        PY="$HOME/py-заглушка"; ROOT="$HOME"; LIVE="$HOME"
        printf "%s\n" "#!/bin/sh" "echo \"python \$*\" >> \"$HOME/попытки\"" "exit 97" > "$PY"
        chmod +x "$PY"
        "$2" "${@:3}" >/dev/null 2>&1
        set +x
    ' _ "$_f" "$_fn" "$@" 2>/dev/null
    # НАРУЖУ — ТОЛЬКО СТРОКИ ИЗМЕРЯЕМОГО ФАЙЛА.
    grep -oE "^\++${_base}:[0-9]+" "$_t" | sed 's/.*://' | sort -n | uniq
}

функция_есть() {       # $1 — файл, $2 — имя; НЕуспех, если после подключения функции нет
    # ОПЕЧАТКА В ИМЕНИ ДАВАЛА ПРАВДОПОДОБНОЕ ЧИСЛО (рецензия 27.08): несуществующая
    # функция просто не вызывалась, след состоял из строк подключения, инструмент печатал
    # «исполнено строк 28» и выходил с нулём. Ровно тот класс, о котором предупреждает
    # заголовок этого файла: измерение, не измеряющее ничего, но выглядящее рабочим.
    env -i HOME="$HOMEDIR" PATH="$PATH" TERM=dumb bash -c '
        exit() { return 0; }
        source "$1" __измерение__ >/dev/null 2>&1
        unset -f exit
        declare -F "$2" >/dev/null
    ' _ "$1" "$2" 2>/dev/null
}

if [ "$FILE" = --самопроверка ]; then
    # ЗОНД РАЗЛИЧЕНИЯ — ПРИЁМКА САМОГО ИЗМЕРИТЕЛЯ, А НЕ УКРАШЕНИЕ. Оба прошлых захода
    # выглядели работающими: инструмент печатал правдоподобное число. Поймало ошибку не
    # чтение кода, а требование «разные функции обязаны давать разные множества строк».
    # Пока этот зонд не зелёный, числу инструмента верить нельзя — и он говорит это сам,
    # ненулевым кодом, а не примечанием в документе.
    SH="$(dirname "$0")/../r33build/live/autopilot.sh"
    a=$(измерить "$SH" env_guard)
    b=$(измерить "$SH" chicago %F)
    echo "env_guard: строк $(echo "$a" | grep -c .) ; chicago: строк $(echo "$b" | grep -c .)"
    if [ -z "$a" ] || [ -z "$b" ]; then
        echo "САМОПРОВЕРКА: ОТКАЗ — след пуст, измеритель не меряет ничего"; exit 1
    fi
    if [ "$a" = "$b" ]; then
        echo "САМОПРОВЕРКА: ОТКАЗ — две разные функции дали ОДИНАКОВЫЙ след"; exit 1
    fi
    # СЛЕД ОБЯЗАН СОДЕРЖАТЬ СТРОКИ САМОЙ ФУНКЦИИ, а не только преамбулу подключения:
    # ровно этим отличался сломанный дескриптор — множества были разными по длине, но обе
    # состояли из строк подключения. Границы env_guard берутся из файла, а не вписаны.
    # ИМЕНА ЛАТИНИЦЕЙ — ГРАБЛЯ 1 ИЗ ЗАГОЛОВКА ЭТОГО ЖЕ ФАЙЛА, В КОТОРУЮ Я ВСТУПИЛ
    # ПОВТОРНО, НАПИСАВ ЕЁ ДЕСЯТЬЮ СТРОКАМИ ВЫШЕ. Кириллическое `н=498` bash считает
    # не присваиванием, а КОМАНДОЙ — «command not found», пустая подстановка, и
    # проверка молча меряет пустоту. Выправлено грепом ПО КЛАССУ (правило 8в-5), а не
    # по названному месту: разбором найдены все 12 попаданий в трёх видах написания.
    beg=$(grep -n '^env_guard() {' "$SH" | cut -d: -f1)
    end=$(awk -v s="$beg" 'NR>s && /^}/ {print NR; exit}' "$SH")
    if [ -z "$beg" ] || [ -z "$end" ]; then
        echo "САМОПРОВЕРКА: ОТКАЗ — границы env_guard в файле не найдены"; exit 1
    fi
    own=$(echo "$a" | awk -v s="$beg" -v e="$end" '$1>=s && $1<=e' | grep -c .)
    echo "строк ВНУТРИ env_guard ($beg..$end): $own"
    [ "$own" -ge 2 ] || { echo "САМОПРОВЕРКА: ОТКАЗ — тело функции в след не попало"; exit 1; }
    # ЧЕТВЁРТАЯ ПРОВЕРКА — ГЛУБИНА, И ЗАВЕДЕНА ОНА ПО ОТКАЗУ ВОРОТ 8в-2. Мутация
    # «одинарный плюс» (грабля 2, уже стоившая захода) три прежние проверки ПРОХОДИЛА:
    # следы оставались разными (7 против 5), строк внутри env_guard оставалось 3, порога
    # `>=2` хватало. Терялись при этом строки ВЛОЖЕННЫХ уровней, где живёт большая часть
    # тела любой функции.
    # ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ ПРОВЕРКИ БЫЛА НЕДОСТИЖИМА И ЗЕЛЕНЕЛА ВСЕГДА: она считала '++'
    # в СЫРОМ следе, а мутация сидит в РАЗБОРЩИКЕ — сырой след от неё не меняется вовсе.
    # То есть я проверил не то место, ровно как предупреждает правило 8а. Наблюдать надо
    # то, что мутация ломает: ВЫЖИВАНИЕ вложенной строки ПОСЛЕ разбора. Берём номер,
    # который в сыром следе встречается ТОЛЬКО на глубине >=2, и требуем его в разобранном
    # множестве. Если таких номеров нет — отказ: проверка, которой нечего наблюдать, врёт
    # зелёным опаснее, чем отсутствует.
    # СОРТИРОВКА ЛЕКСИЧЕСКАЯ, А НЕ ЧИСЛОВАЯ: comm сверяет строки и на `sort -n` ругается
    # «input is not in sorted order», выдавая при этом ПРАВДОПОДОБНЫЙ результат — то есть
    # молча врёт. Числовой порядок нужен человеку в списке строк, а не этой сверке.
    # ФОРМАТ СЛЕДА ИЗМЕНИЛСЯ ВМЕСТЕ С PS4: теперь это «+файл:номер», и прежние шаблоны
    # без имени файла не совпадали НИ С ЧЕМ — проверка честно отказала «наблюдать нечего»
    # вместо того, чтобы позеленеть на пустоте. Ровно так ворота и должны себя вести.
    base=${SH##*/}
    deep=$(grep -oE "^\+\++${base}:[0-9]+" "$TRACE.env_guard" | sed 's/.*://' | sort -u)
    flat=$(grep -oE "^\+${base}:[0-9]+" "$TRACE.env_guard" | sed 's/.*://' | sort -u)
    only=$(comm -23 <(echo "$deep") <(echo "$flat"))
    echo "номеров только на глубине >=2: $(echo "$only" | grep -c .)"
    [ -n "$only" ] || { echo "САМОПРОВЕРКА: ОТКАЗ — вложенных номеров нет, проверке нечего наблюдать"; exit 1; }
    survived=$(comm -12 <(echo "$only") <(echo "$a" | sort -u))
    [ -n "$survived" ] || { echo "САМОПРОВЕРКА: ОТКАЗ — вложенные строки не пережили разбор"; exit 1; }
    # ПЯТАЯ ПРОВЕРКА — ИЗОЛЯЦИЯ, И ОНА ЗДЕСЬ ГЛАВНАЯ ПО ЦЕНЕ ОШИБКИ. Измеритель подключает
    # боевой autopilot.sh целиком: тот при сорсинге берёт замок, пишет сердцебиение, а при
    # любой ADDFUT_* в окружении — ДОЛГОВЕЧНУЮ датированную тревогу, которая останавливает
    # контур до ручного разбора. Ровно это и случилось 26.08.2026: ALARM-env-2026-08-26.txt
    # написан не cron'ом, а зондом слоя 1. Поэтому проверяется не намерение, а ФАКТ —
    # следы прогона обязаны лежать во ВРЕМЕННОМ доме.
    #
    # ПАРНАЯ МУТАЦИЯ ЭТОЙ ПРОВЕРКИ — `HOME="$HOME"` — НАМЕРЕННО НЕ ПРОГОНЯЕТСЯ НИ РАЗУ:
    # она по определению пишет в боевой каталог, то есть воспроизводит ту самую аварию.
    # Наблюдаемость обеспечена безопасным суррогатом того же класса (подмена HOME на
    # заведомо другой временный путь) — он убивает проверку, не касаясь ~/.addfut.
    # Молчать об этом нельзя: непрогнанная мутация, о которой не сказано, читается как
    # прогнанная.
    if [ ! -s "$HOMEDIR/.addfut/tick-heartbeat" ]; then
        echo "САМОПРОВЕРКА: ОТКАЗ — следы прогона не легли во временный дом $HOMEDIR"; exit 1
    fi
    echo "изоляция: следы во временном доме, ~/.addfut не затронут"
    # ШЕСТАЯ ПРОВЕРКА — ОПЕЧАТКА В ИМЕНИ ОБЯЗАНА БЫТЬ ОТКАЗОМ, А НЕ ЧИСЛОМ (рецензия 27.08).
    if функция_есть "$SH" env_guard_ОПЕЧАТКА; then
        echo "САМОПРОВЕРКА: ОТКАЗ — несуществующая функция признана существующей"; exit 1
    fi
    функция_есть "$SH" env_guard || {
        echo "САМОПРОВЕРКА: ОТКАЗ — существующая функция не опознана"; exit 1; }
    echo "опечатка в имени: отвергается, настоящее имя опознаётся"
    # СЕДЬМАЯ — ФАНТОМНЫХ СТРОК НЕТ. Обёртка коротка (её строки — единицы и десятки), а
    # boевой файл длинный; после метки файла в PS4 наружу не должно уходить НИ ОДНОЙ
    # строки, которой в измеряемом файле не существует. Проверяем по верхней границе:
    # номер строки не может превышать длину файла — и не может указывать на комментарий
    # в диапазоне 14..17, куда падали фантомы.
    total=$(grep -c "" "$SH")
    maxln=$(echo "$a" | sort -n | tail -1)
    if [ "$maxln" -gt "$total" ]; then
        echo "САМОПРОВЕРКА: ОТКАЗ — в следе строка $maxln, а в файле их $total"; exit 1
    fi
    phantom=$(echo "$a" | awk '$1>=14 && $1<=17' | grep -c .)
    if [ "$phantom" -gt 0 ]; then
        echo "САМОПРОВЕРКА: ОТКАЗ — в следе строки 14..17, это строки обёртки, не файла"; exit 1
    fi
    echo "фантомных строк нет (максимум $maxln при длине файла $total)"
    echo "САМОПРОВЕРКА: пройдена"
    exit 0
fi

