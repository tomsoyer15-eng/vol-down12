#!/usr/bin/env python3
"""Проверка замечания рецензента: не круговой ли тест чувствительности к коэффициенту 0,88.

ЗАМЕЧАНИЕ. Число контрактов N обратно пропорционально коэффициенту: замена 0,88 на 0,50
обязана увеличить книгу примерно на 76%. Спецификация же утверждает, что подстановка
0,50 / 0,72 / 0,88 / 1,00 почти не меняет результат. Одно из двух: либо формула не
управляет позицией, либо тест проверяет не то.

РАЗБОР. В модели экспозиция ноги Б = N x q, где q = 112 000 x c — принятая стоимость
контракта. N выбирается так, чтобы N x q = цель. Значит экспозиция от c не зависит, и
модельный P&L тоже. Тест чувствительности показывает ВНУТРЕННЮЮ СОГЛАСОВАННОСТЬ модели,
а не безразличие результата к c: в бою P&L даёт биржа, а не наша константа, и он
пропорционален ЧИСЛУ контрактов, то есть 1/c.

ИЗМЕРЕНИЕ. По фактическому ряду ZN считается доход на один контракт и сопоставляется с
модельным при разных c. Тот c, при котором наклон регрессии факта на модель равен единице,
и есть стоимость контракта, согласующая книгу с намерением спецификации.
"""
import sys, pickle
from pathlib import Path
import numpy as np, pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'r32build'))
import sim_v13 as S

ZN_MULT = 1000.0

if __name__ == '__main__':
    D = pickle.load(open(ROOT / 'data/norgate/full_history.pkl', 'rb'))
    d = S.build_splice()
    days, rb, rfv = d[0], d[2], d[3]
    rf = pd.Series(rfv, index=days)
    model_b = pd.Series(rb, index=days) - rf
    adj = D['continuous']['ZN']['adj']['Close']
    j = adj.index.intersection(days)
    pnl = (ZN_MULT * adj.diff()).reindex(j).dropna()      # доллары на контракт, факт
    mb = model_b.reindex(pnl.index)
    ok = pnl.notna() & mb.notna()
    pnl, mb = pnl[ok], mb[ok]

    print(f'окно {pnl.index[0]:%d.%m.%Y}–{pnl.index[-1]:%d.%m.%Y}, {len(pnl)} дней\n')
    print(f"{'коэффициент c':<16}{'q = 112000c':>13}{'наклон факт/модель':>21}"
          f"{'качка факт/модель':>20}{'накопл. факт':>15}{'накопл. модель':>16}")
    slope_at = {}
    for c in (0.50, 0.72, 0.787, 0.88, 1.00):
        q = S.ZN_MODEL_PX_EQ * c
        real = pnl / q
        b, _ = np.polyfit(mb, real, 1)
        slope_at[c] = b
        print(f"{c:<16.3f}{q:>13,.0f}{b:>21.3f}{real.std()/mb.std():>20.3f}"
              f"{((1+real).prod()-1)*100:>14.1f}%{((1+mb).prod()-1)*100:>15.1f}%")

    # наклон обратно пропорционален c, поэтому согласующий c находится точно
    c_star = 0.88 * slope_at[0.88]
    print(f'\nсогласующий коэффициент (наклон = 1): c* = {c_star:.3f}')
    # N пропорционально 1/c, поэтому при большем c контрактов МЕНЬШЕ. Прежняя редакция
    # печатала (1 - c*/c) и давала знак плюс, противореча собственному тексту строкой ниже.
    print(f'принятый в спецификации c = {S.CTD_RATIO:.2f} даёт книгу на '
          f'{(c_star/S.CTD_RATIO - 1)*100:+.1f}% по числу контрактов относительно согласующей,')
    print(f'то есть фактическая экспозиция ноги Б составляет {slope_at[0.88]*100:.1f}% '
          f'от намеченной спецификацией.')

    # что это стоит: подстановка фактической ноги Б в ядро при разных c
    print('\nподстановка фактической ноги Б в ядро (спред с неё снят, чтобы не считать дважды):')
    import rebal as R  # noqa
    sys.path.insert(0, str(ROOT / 'tools'))
    print(f"{'c':<10}{'CAGR':>9}{'MaxDD':>9}{'дельта к модели':>18}")
    base = None
    for c in (0.72, 0.787, 0.88, 1.00):
        q = S.ZN_MODEL_PX_EQ * c
        real = (pnl / q).reindex(days).fillna(0.0)
        m = days >= pnl.index[0]
        # ВОЗВРАТ СПРЕДА. Движок вычитает из каждой ноги ставку и спред. Фактический ряд
        # фьючерса уже есть избыточный доход, поэтому и ставка, и спред возвращаются в него,
        # иначе спред считается дважды и подстановка выглядит хуже, чем она есть.
        sd = 0.5 / 100 / 252
        dd = (days[m], d[1][m], (real + rf + sd)[m].values, rfv[m], d[4][m], d[5][m],
              d[6][m], d[7][m])
        r, _, _ = S.sim(*dd, spread_pp=0.5)
        eq = (1 + r).cumprod(); yrs = (dd[0][-1] - dd[0][0]).days / 365.25
        cg = (eq.iloc[-1] ** (1 / yrs) - 1) * 100
        mx = (eq / eq.cummax() - 1).min() * 100
        if base is None:
            rm, _, _ = S.sim(days[m], d[1][m], d[2][m], rfv[m], d[4][m], d[5][m], d[6][m], d[7][m])
            em = (1 + rm).cumprod(); base = (em.iloc[-1] ** (1 / yrs) - 1) * 100
            print(f"{'модель':<10}{base:>8.2f}%{(em/em.cummax()-1).min()*100:>8.1f}%{0.0:>17.2f}")
        print(f"{c:<10.3f}{cg:>8.2f}%{mx:>8.1f}%{cg-base:>17.2f}")
