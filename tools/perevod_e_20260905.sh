#!/usr/bin/env bash
# Одноразовый запуск безголового исполнителя перевода Ф->Е (акт заказчика 29.08.2026).
# Оболочка — запускалка (правило 8д): вся задача в perevod_e_20260905-prompt.md.
# Сторожевая дата зашита: cron-строка «51 16 4 9 *» сработала бы и через год — скрипт
# исполняется ТОЛЬКО 2026-09-05, в любой другой день выходит молча. После события строка
# из crontab снимается (отмечено в PROJECT-STATE).
set -u
[ "$(date +%F)" = "2026-09-05" ] || exit 0
DIR="/home/alex/claude-projects/vol-down12"
LOG="$HOME/.addfut/nablyudatel.log"
export PATH="$HOME/.local/bin:$PATH"
cd "$DIR" || { echo "$(date '+%F %T') перевод-Е: нет каталога проекта" >> "$LOG"; exit 3; }
echo "$(date '+%F %T') перевод-Е: старт безголового исполнителя" >> "$LOG"
timeout 3000 claude -p --dangerously-skip-permissions "$(cat "$DIR/tools/perevod_e_20260905-prompt.md")" \
  >> "$LOG" 2>&1
RC=$?
# Формат строки совпадает с наблюдательским: почтовый сторож ловит ненулевой код и шлёт
# письмо «наблюдатель завершился с ошибкой», то есть провал самого исполнителя тоже громкий.
echo "$(date '+%F %T') наблюдатель: завершён, код $RC (перевод-Е)" >> "$LOG"
exit "$RC"
