#!/usr/bin/env python3
"""Наблюдение за монетарным флагом H19 — ВПЕРЁД, без внедрения в стратегию.

ЗАЧЕМ (решение заказчика 02.09.2026). Исследование улучшений 01.09 нашло единственного
кандидата — H19: «ставка 3-мес. T-bill на конце месяца выше своей 12-мес. средней -> обе
ноги ×0.75 в следующем месяце». Внедрять его автор не рекомендует: на 1983-2026 эффект
статистически неотличим от нуля (ΔSharpe +0.019, P=0.18), доходности не добавляет, держится
на нескольких эпизодах 1970-х и 1987 года. Рекомендация — наблюдать вперёд по ЗАФИКСИРОВАННОМУ
определению и вернуться к вопросу через годы. Заказчик согласился: «записывать эти данные,
через годик посмотрим».

ПОЭТОМУ ЭТО НЕ ЧАСТЬ КОНТУРА. Скрипт ничего не решает, никуда не подаёт заявок, не читает и
не пишет торгового состояния (кроме ЧТЕНИЯ NAV из журнала §7) и на поведение автопилота
влиять не может. Его единственный продукт — строка в docs/nablyudenie/h19-monitor.csv.

ПИШУТСЯ ТРИ РЯДА СРАЗУ, А НЕ ОДИН ВЫБРАННЫЙ. Проверка 02.09 показала, что состояние правила
у порога ЗАВИСИТ ОТ РЯДА: на DGS3MO флаг включён с июня (перевес 1 б.п.), на DTB3 июнь и июль
выключены, на TB3MS свой третий ответ. Выбери я один ряд молча — наблюдение мерило бы выбор
ряда, а не рынок. Пишем все три и отдельным столбцом их СОГЛАСИЕ: как часто определение
вообще однозначно — тоже наблюдение, и ради него год ждать не нужно.

ЗАПИСАННЫЙ МЕСЯЦ НЕ ПЕРЕПИСЫВАЕТСЯ. FRED задним числом уточняет ряды; журнал наблюдения
обязан хранить то, что было ВИДНО в своё время, иначе через год мы сравним не наблюдение,
а сегодняшнее представление о прошлом. Та же дисциплина, что у сайдкара уровней сигнала.

ВЫЗОВ:  python3 h19_nablyudenie.py            — дописать недостающие месяцы
        python3 h19_nablyudenie.py --показать — напечатать хвост журнала, ничего не писать
Идемпотентен: месяц, который уже записан, не трогается, поэтому запускать можно хоть ежедневно.
"""
import csv
import datetime
import io
import os
import pathlib
import sys
import tempfile
import urllib.request

РЯДЫ = ('DGS3MO', 'DTB3', 'TB3MS')     # купонный эквивалент / дисконтная база / среднемесячная
ОКНО = 12                              # месяцев в средней — как в правиле H19
НАЧАЛО = '2026-08'                     # первый месяц наблюдения: пилот начался 12.08.2026
ЖУРНАЛ = (pathlib.Path(__file__).resolve().parent.parent
           / 'docs' / 'nablyudenie' / 'h19-monitor.csv')
СТОЛБЦЫ = (['месяц'] + [c for р in РЯДЫ for c in (р.lower(), f'{р.lower()}_sma12',
                                                  f'{р.lower()}_флаг')]
           + ['согласие', 'nav_конца_месяца', 'маршрут', 'записано'])


def ряд_fred(имя, с='2019-01-01'):
    """Месячные значения ряда FRED на КОНЕЦ месяца и его 12-месячная средняя."""
    сегодня = datetime.date.today().isoformat()
    url = (f'https://fred.stlouisfed.org/graph/fredgraph.csv?id={имя}'
           f'&cosd={с}&coed={сегодня}')
    текст = urllib.request.urlopen(url, timeout=60).read().decode('utf-8')
    помесячно = {}
    for строка in csv.DictReader(io.StringIO(текст)):
        поля = list(строка.values())
        дата, знач = поля[0], поля[1]
        if not знач or знач.strip() in ('.', ''):
            continue
        d = datetime.date.fromisoformat(дата.strip())
        помесячно[f'{d:%Y-%m}'] = float(знач)      # последнее значение месяца
    месяцы = sorted(помесячно)
    итог = {}
    for i, m in enumerate(месяцы):
        if i + 1 < ОКНО:
            continue
        окно = [помесячно[x] for x in месяцы[i + 1 - ОКНО:i + 1]]
        итог[m] = (помесячно[m], sum(окно) / ОКНО)
    return итог


def nav_конца_месяца(месяц):
    """NAV последней ИТОГ-строки месяца из журнала §7. Отсутствие — не ошибка: до начала
    пилота его нет вовсе, а текущий месяц ещё не закрыт."""
    дом = pathlib.Path('~/.addfut').expanduser()
    найдено = None
    for ж in sorted(дом.glob('journal-*.csv')):
        try:
            for строка in csv.DictReader(ж.read_text(encoding='utf-8').splitlines()):
                if (строка.get('instrument') == 'ИТОГ'
                        and str(строка.get('date', '')).startswith(месяц)):
                    найдено = строка.get('nav') or найдено
        except OSError:
            continue
    return найдено or ''


def маршрут():
    п = pathlib.Path('~/.addfut/route.txt').expanduser()
    try:
        return п.read_text(encoding='utf-8').strip() or '?'
    except OSError:
        return '?'


def прочитать():
    if not ЖУРНАЛ.exists():
        return []
    return list(csv.DictReader(ЖУРНАЛ.read_text(encoding='utf-8').splitlines()))


def дописать(строки):
    """Атомарная перезапись: читатель видит либо старый файл целиком, либо новый."""
    ЖУРНАЛ.parent.mkdir(parents=True, exist_ok=True)
    fd, врем = tempfile.mkstemp(dir=str(ЖУРНАЛ.parent), suffix='.tmp')
    with os.fdopen(fd, 'w', encoding='utf-8', newline='') as f:
        писарь = csv.DictWriter(f, fieldnames=СТОЛБЦЫ)
        писарь.writeheader()
        писарь.writerows(строки)
        f.flush()
        os.fsync(f.fileno())
    os.chmod(врем, 0o644)      # mkstemp даёт 600; файл лежит в репозитории, не секрет
    os.replace(врем, ЖУРНАЛ)


def главная():
    прежние = прочитать()
    записанные = {с['месяц'] for с in прежние}
    данные = {}
    for имя in РЯДЫ:
        try:
            данные[имя] = ряд_fred(имя)
        except Exception as ошибка:                # сеть, разбор, что угодно
            print(f'H19: ряд {имя} не получен ({type(ошибка).__name__}: {ошибка}) — '
                  f'запись отложена до следующего запуска', file=sys.stderr)
            return 1
    общие = sorted(set.intersection(*(set(d) for d in данные.values())))
    новые = [m for m in общие if m >= НАЧАЛО and m not in записанные]
    # ТЕКУЩИЙ МЕСЯЦ НЕ ПИШЕТСЯ: он ещё не кончился, и его «конец месяца» — сегодняшняя точка,
    # а не решение. Тот же принцип, что у живого сигнального ряда.
    текущий = f'{datetime.date.today():%Y-%m}'
    новые = [m for m in новые if m < текущий]
    if not новые:
        print(f'H19: новых завершённых месяцев нет (записано {len(прежние)})')
        return 0
    for m in новые:
        строка = {'месяц': m}
        флаги = []
        for имя in РЯДЫ:
            знач, сма = данные[имя][m]
            флаг = 'ВКЛ' if знач > сма else 'выкл'
            флаги.append(флаг)
            строка[имя.lower()] = f'{знач:.2f}'
            строка[f'{имя.lower()}_sma12'] = f'{сма:.2f}'
            строка[f'{имя.lower()}_флаг'] = флаг
        строка['согласие'] = 'да' if len(set(флаги)) == 1 else 'НЕТ'
        строка['nav_конца_месяца'] = nav_конца_месяца(m)
        строка['маршрут'] = маршрут()
        строка['записано'] = datetime.date.today().isoformat()
        прежние.append(строка)
        print(f'H19: записан {m}: ' + ', '.join(
            f'{и.lower()} {строка[и.lower()]}/{строка[f"{и.lower()}_sma12"]} '
            f'{строка[f"{и.lower()}_флаг"]}' for и in РЯДЫ)
            + f'; согласие {строка["согласие"]}')
    прежние.sort(key=lambda с: с['месяц'])
    дописать(прежние)
    return 0


if __name__ == '__main__':
    if '--показать' in sys.argv:
        строки = прочитать()
        print(f'записей: {len(строки)}; файл: {ЖУРНАЛ}')
        for с in строки[-14:]:
            print('  ' + '  '.join(f'{к}={с[к]}' for к in СТОЛБЦЫ if с.get(к)))
        raise SystemExit(0)
    raise SystemExit(главная())
