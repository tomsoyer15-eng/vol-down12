def call(model, text):
    body = {'model': model, 'input': text, 'reasoning': {'effort': 'high'}}
    req = Request('https://api.openai.com/v1/responses',
                  data=json.dumps(body).encode(),
                  headers={'Authorization': f'Bearer {KEY}', 'Content-Type': 'application/json'})
    for attempt in range(12):
        try:
            with urlopen(req, timeout=5400) as f:
                return json.load(f)
        except Exception as e:
            detail = getattr(e, 'read', lambda: b'')().decode('utf-8', 'replace')
            if '429' in str(e) or 'rate_limit' in detail:
                m = _re.search(r'try again in ([\d.]+)s', detail)
                w = max(float(m.group(1)) + 20, 70) if m else 70
                print(f'лимит, попытка {attempt+1}, жду {w:.0f} с', flush=True)
                time.sleep(w); continue
            print('ОШИБКА:', e, detail[:800], flush=True)
            raise SystemExit(1)
    raise SystemExit('не удалось после 12 попыток')


if __name__ == '__main__':
    d = call(MODEL, BRIEF.replace('%%SPEC%%', SPEC))
    out = []
    for item in d.get('output', []):
        for c in item.get('content', []) or []:
            if c.get('type') in ('output_text', 'text'):
                out.append(c.get('text', ''))
    st = d.get('status'); inc = (d.get('incomplete_details') or {}).get('reason')
    if st != 'completed':
        print(f'[статус {st}, причина {inc}]', flush=True)
    txt = '\n'.join(out).strip() or json.dumps(d)[:2000]
