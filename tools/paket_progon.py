#!/usr/bin/env python3
"""Прогон батареи и мутаций В КОПИИ ПАКЕТА, а не в рабочем дереве.

ЗАЧЕМ. Три выпуска подряд 27-28.08 упали по одной причине: проверочный код читает файлы,
которых в пакете нет (tools/backup_push.sh, tools/branch_cover.py, live/instruments_live.csv).
В рабочем дереве всё зелёное, потому что рядом лежит весь проект. Узнавал я об этом от
release.py — то есть через сорок минут после коммита, и чинил по одному месту за раз.

Здесь то же самое стоит полторы минуты и делается ДО коммита. Класс закрывается целиком:
не «я вспомнил проверить», а команда, которая либо зелёная, либо называет файл.

ЧТО ЭТО НЕ ЗАМЕНЯЕТ: release.py собирает настоящий архив, считает манифест, сверяет
норматив и PDF. Здесь только один вопрос — переживёт ли проверочный код отсутствие
рабочего дерева.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПАКЕТ = КОРЕНЬ / 'r33build'


def собрать_копию(куда):
    """Разложить файлы РОВНО по манифесту — как их увидит распаковавший архив."""
    имена = [s.split()[-1] for s in
             (ПАКЕТ / 'MANIFEST-192.txt').read_text(encoding='utf-8').splitlines()
             if s.strip() and not s.startswith('#')]
    нет = []
    for имя in имена:
        источник = ПАКЕТ / имя
        if not источник.exists():
            нет.append(имя)
            continue
        (куда / имя).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(источник, куда / имя)
    return len(имена), нет


def прогнать(копия, файл):
    """Запустить проверку так же, как это делает selfcheck: отдельным процессом из копии."""
    ход = subprocess.run([sys.executable, str(копия / 'live' / файл)],
                         capture_output=True, text=True, cwd=str(копия))
    пропуски = [s for s in ход.stdout.splitlines() if s.startswith('[ПРОПУСК]')]
    # ХВОСТ STDERR ПЕЧАТАЕТСЯ ВСЕГДА, А НЕ ТОЛЬКО ПРИ ОТКАЗЕ. Именно его selfcheck НЕ
    # показывает, и потому падение процесса выглядело там как отказ по существу: три
    # выпуска подряд сообщали «все мутации пойманы», когда прогон просто умирал.
    хвост = '\n'.join(ход.stderr.splitlines()[-12:])
    return ход.returncode, пропуски, хвост, ход.stdout


def главная():
    with tempfile.TemporaryDirectory(prefix='addfut-paket-') as врем:
        копия = Path(врем)
        всего, нет = собрать_копию(копия)
        print(f'копия по манифесту: {всего} файлов'
              + (f'; НЕТ В ДЕРЕВЕ: {нет}' if нет else ''))
        плохо = bool(нет)
        for файл in ('invariants.py', 'mutation.py'):
            код, пропуски, хвост, вывод = прогнать(копия, файл)
            отказы = [s for s in вывод.splitlines() if '[FAIL]' in s]
            print(f'\n=== {файл}: код возврата {код} ===')
            for s in пропуски:
                print(' ', s)
            for s in отказы[:8]:
                print(' ', s[:200])
            if код != 0:
                плохо = True
                # Причина падения живёт в stderr, и без неё отказ неотличим от
                # содержательного провала проверки.
                print('  ХВОСТ STDERR:\n' + (хвост or '  (пусто)'))
        print('\nИТОГ: ' + ('ПАКЕТ НЕ САМОДОСТАТОЧЕН' if плохо else
                            'пакет самодостаточен — проверки живут без рабочего дерева'))
        return 1 if плохо else 0


if __name__ == '__main__':
    raise SystemExit(главная())
