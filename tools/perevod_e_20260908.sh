#!/usr/bin/env bash
# Одноразовый запуск безголового исполнителя перевода Ф->Е (акт заказчика 29.08.2026,
# подтверждён 04.09.2026). Оболочка — запускалка (правило 8д): вся задача в
# perevod_e_20260908-prompt.md.
# СТРОКА CRONTAB (единственное место, где она названа в самом файле; сверено с PROJECT-STATE):
#   50 16 8 9 * /bin/bash /home/alex/claude-projects/vol-down12/tools/perevod_e_20260908.sh
# Сторожевая дата зашита: строка сработала бы и через год — скрипт исполняется ТОЛЬКО
# 2026-09-08, в любой другой день выходит молча. После события строка снимается.
set -u
DIR="/home/alex/claude-projects/vol-down12"
LOG="$HOME/.addfut/nablyudatel.log"
TASKFILE="$DIR/tools/perevod_e_20260908-prompt.md"
export PATH="$HOME/.local/bin:$PATH"

# ЛЮБОЙ ОТКАЗ ДО ЗАПУСКА ОБЯЗАН БЫТЬ ГРОМКИМ (рецензия 04.09.2026). Почтовый сторож ищет в
# журнале ПОДСТРОКУ «завершён, код» и смотрит хвост; сообщение без неё он не видит вовсе,
# и пропущенный перевод оставался бы совершенно молчаливым. Поэтому все выходы идут через
# эту функцию, а не через голый echo.
finish() {                    # $1 — код возврата, $2 — причина
    echo "$(date '+%F %T') перевод-Е: $2" >> "$LOG" 2>/dev/null || true
    echo "$(date '+%F %T') наблюдатель: завершён, код $1" >> "$LOG" 2>/dev/null || true
    exit "$1"
}

[ "$(date +%F)" = "2026-09-08" ] || exit 0      # чужой день — молча, это страховка cron
cd "$DIR" || finish 3 "нет каталога проекта $DIR"
# ЗАДАНИЕ ПРОВЕРЯЕТСЯ ДО ЗАПУСКА (рецензия 04.09.2026). `set -u` сторожит переменные, но не
# подстановку команд: при пропавшем файле $(cat …) даёт ПУСТУЮ строку, агент стартовал бы
# без задачи, а прогон записался бы как успех. Ошибка cat к тому же ушла бы в stderr самой
# оболочки, а не в журнал: перенаправление относится к timeout, а подстановка раскрывается
# раньше. Проверено зондом с подставным claude: argc=3, код 0, в журнале «код 0».
[ -s "$TASKFILE" ] || finish 4 "нет файла задания $TASKFILE — исполнитель НЕ запущен"

echo "$(date '+%F %T') перевод-Е: старт безголового исполнителя" >> "$LOG"
# ЗАПАС ПО ВРЕМЕНИ БОЛЬШЕ, ЧЕМ У САМОГО ПЕРЕХОДА (рецензия 04.09.2026). Прежние 3000 с
# (50 мин) короче собственного бюджета перехода: план из восьми лотов при 15 минутах на
# пару в пределе идёт дольше, и SIGTERM мог прийти ПОСРЕДИ пары — журнал с открытым
# TRANSITION_OPEN и непарная позиция на ночь. Ставим 6600 с (110 мин): старт 16:50 по
# машине, общее окно LSE/CME кончается в 10:30 Чикаго = 18:40 по машине, то есть переход
# сам остановится по окну раньше, чем сработает этот предохранитель.
timeout 6600 claude -p --dangerously-skip-permissions "$(cat "$TASKFILE")" >> "$LOG" 2>&1
RC=$?
# ФОРМАТ СТРОКИ — В ТОЧНОСТИ КАК У НАБЛЮДАТЕЛЯ, БЕЗ ПРИПИСОК (рецензия 04.09.2026).
# Сторож проверяет `endswith('код 0')`; приписка «(перевод-Е)» ломала проверку, и УСПЕХ
# уходил заказчику письмом «завершился с ошибкой» — случилось живьём 04.09 в 17:00. Хуже
# того, ложное письмо занимает единственную на дату метку и глушит настоящий отказ того же
# дня. Пояснение — отдельной строкой ВЫШЕ, она сторожу не мешает.
echo "$(date '+%F %T') перевод-Е: исполнитель завершён" >> "$LOG"
echo "$(date '+%F %T') наблюдатель: завершён, код $RC" >> "$LOG"
exit "$RC"
