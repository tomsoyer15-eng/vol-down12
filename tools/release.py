#!/usr/bin/env python3
"""Выпуск пакета: манифест -> архив -> РАСПАКОВКА В ЧИСТЫЙ КАТАЛОГ -> selfcheck.

Порядок замкнут намеренно. Прежде архив собирался из списка и на самом архиве не
запускался — и оказалось, что он не запускался вовсе: ни замороженного ядра sim_v13.py, ни
исходных рядов data/*.csv внутри не было. Строка «ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ» имеет смысл только
если получена на РАСПАКОВАННОМ архиве, где недостающий файл неоткуда подхватить.
"""
import hashlib, os, re, shutil, subprocess, sys, tempfile, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R, PY = ROOT / 'r33build', ROOT / '.venv/bin/python'
Z = ROOT / 'paket-ADD-FUT-v1_6_0-r33.zip'
MAN = R / 'MANIFEST-192.txt'
_SRC_BEFORE = ''


def _git_base():
    """СЛЕД ПРОИСХОЖДЕНИЯ ВЫПУСКА (девятнадцатый круг, №22). Манифест пересчитывается по
    текущему дереву и потому аттестует лишь САМОСОГЛАСОВАННОСТЬ архива — внешнего эталона
    до коммита не существует (порядок «выпуск -> коммит» нормативен после инцидента 14-го
    круга). Записываются git-база и число изменённых относительно неё файлов: пересчёт
    становится ВИДИМЫМ пост-фактум и сверяемым с историей git/releases/WORM — предел
    признан в §12, след обязателен."""
    r = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return '# git-base: недоступна (выпуск вне репозитория)'
    head = r.stdout.strip()
    d = subprocess.run(['git', '-C', str(ROOT), 'status', '--porcelain', '--', 'r33build'],
                       capture_output=True, text=True)
    dirty = len([l for l in d.stdout.splitlines() if l.strip()])
    return (f'# git-base {head} (+{dirty} изменённых файлов r33build относительно HEAD '
            f'на момент выпуска)')


def refresh_manifest():
    out, miss = [], []
    for ln in MAN.read_text(encoding='utf-8').splitlines():
        # СЛЕД ПРОШЛОГО ВЫПУСКА СНИМАЕТСЯ ПО СУТИ, А НЕ ПО ТОЧНОМУ НАБОРУ ПРОБЕЛОВ
        # (рецензия 19.08). Условие `startswith('# git-base')` не совпадало с формой
        # `#  git-base` — а её писал сам этот инструмент: строка пережила все выпуски и
        # застряла в корне доверия навсегда. Аудитор, распаковав пакет, читал ДВА взаимно
        # исключающих происхождения и не мог определить, каким коммитом собран архив.
        _st = ln.lstrip()
        if _st.startswith('#') and 'git-base' in _st:
            continue                       # след прошлого выпуска заменяется свежим
        m = re.match(r'^([0-9a-f]{64})\s+(\S+)$', ln.strip())
        if not m:
            out.append(ln); continue
        f = R / m.group(2)
        if not f.exists():
            miss.append(m.group(2)); out.append(ln); continue
        out.append(f'{hashlib.sha256(f.read_bytes()).hexdigest()}  {m.group(2)}')
    if miss:
        sys.exit(f'НЕТ ФАЙЛОВ ИЗ МАНИФЕСТА: {miss}')
    MAN.write_text('\n'.join([_git_base()] + out) + '\n', encoding='utf-8')
    return [l.split(None, 1)[1] for l in out if re.match(r'^[0-9a-f]{64}\s', l)]


def _snapshot(names):
    # МАНИФЕСТ ТОЖЕ (№21): он часть архива и меняется вместе с ним.
    """Хэши упаковываемых файлов — чтобы поймать правку дерева ВО ВРЕМЯ выпуска."""
    return {n: hashlib.sha256((R / n).read_bytes()).hexdigest() for n in names}


def main():
    # ОДИН ВЫПУСК НА МАШИНУ (двадцать седьмой круг, №20). Перехэширование архива перед
    # публикацией ловит подмену, но не защищает от параллельного прогона: два выпуска
    # пишут ОДИН И ТОТ ЖЕ paket-*.zip, и второй может заменить байты между проверкой и
    # копированием. Замок снимает саму возможность гонки.
    import fcntl
    _lk = open(ROOT / '.release.lock', 'w')
    try:
        fcntl.flock(_lk, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        print('ВЫПУСК НЕ СОСТОЯЛСЯ: другой release.py уже идёт на этой машине')
        return 1
    return _main_locked()


def _sverit_normativ():
    """ДВЕ КОПИИ НОРМАТИВА ОБЯЗАНЫ СОВПАДАТЬ, И ЭТО ПРОВЕРЯЕТ ВЫПУСК, А НЕ ЧЕЛОВЕК.

    Основание измерено 26.08.2026. Нормативный текст живёт в двух местах:
    docs/addfut-v1.6.0-r33.txt — источник (его получает внешний рецензент, в него пишется
    §12) и r33build/ADD-FUT-v1_6_0-r33.txt — копия, которую хэширует манифест и заверяет
    корень доверия. Копии разошлись 18.08 и не сверялись НИЧЕМ: СЕМЬ выпусков подряд
    заверяли текст на 1199 строк короче источника, без §12 от 19.08 и позже. Дефект
    молчаливый по устройству — каждый отдельный выпуск проходил selfcheck честно, потому
    что selfcheck сверяет архив с манифестом, а манифест считался от той же отставшей
    копии. Замкнутая на себя проверка не видит, что заверяет не тот текст.

    PDF СВЕРЯЕТСЯ ПО СОДЕРЖАНИЮ, А НЕ ПО ДАТЕ. Побайтового равенства с txt быть не может —
    это рендер; сравнивать mtime бессмысленно (копирование обновляет его, не меняя сути).
    Наблюдаемый признак «PDF собран из ЭТОГО текста» — последняя содержательная строка
    норматива обязана извлекаться из PDF. Она меняется с каждой записью в §12, то есть
    отставший PDF ловится сразу же, а не через семь выпусков.
    """
    src = ROOT / 'docs/addfut-v1.6.0-r33.txt'
    dst = R / 'ADD-FUT-v1_6_0-r33.txt'
    pdf = R / 'ADD-FUT-v1_6_0-r33.pdf'
    if not src.exists():
        sys.exit(f'ВЫПУСК НЕ СОСТОЯЛСЯ: нет источника норматива {src}')
    a, b = src.read_bytes(), dst.read_bytes()
    if a != b:
        sys.exit('ВЫПУСК НЕ СОСТОЯЛСЯ: копии норматива РАСХОДЯТСЯ — пакет заверил бы не тот '
                 f'текст.\n  {src}: {len(a.splitlines())} строк, sha {hashlib.sha256(a).hexdigest()[:16]}'
                 f'\n  {dst}: {len(b.splitlines())} строк, sha {hashlib.sha256(b).hexdigest()[:16]}'
                 '\n  синхронизировать и пересобрать PDF (tools/make_spec_pdf.py)')
    # ПОСЛЕДНЯЯ СОДЕРЖАТЕЛЬНАЯ СТРОКА — не просто последняя: хвост может кончаться пустой
    # строкой или служебным маркером страницы, и тогда проверка сравнивала бы пустоту.
    хвост = [s.strip() for s in a.decode('utf-8').splitlines()
             if s.strip() and not s.startswith('=====')]
    if not хвост:
        sys.exit('ВЫПУСК НЕ СОСТОЯЛСЯ: в нормативном тексте нет ни одной содержательной строки')
    метка = хвост[-1][:40]
    r = subprocess.run([str(PY), str(ROOT / 'tools/pdf_text.py'), str(pdf)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f'ВЫПУСК НЕ СОСТОЯЛСЯ: текст из PDF не извлекается: {(r.stderr or "")[:200]}')
    if метка not in r.stdout:
        sys.exit('ВЫПУСК НЕ СОСТОЯЛСЯ: PDF собран НЕ из этого текста — последней строки '
                 f'норматива в нём нет.\n  искали: {метка!r}'
                 '\n  пересобрать: tools/make_spec_pdf.py docs/addfut-v1.6.0-r33.txt '
                 'r33build/ADD-FUT-v1_6_0-r33.pdf "ADD-FUT v1.6.0 ред. 33"')
    print(f'норматив сверён: копии совпали ({len(a.splitlines())} строк), '
          f'PDF несёт последнюю строку текста')


def _main_locked():
    _sverit_normativ()
    names = refresh_manifest()
    # ДЕРЕВО НЕ ДОЛЖНО МЕНЯТЬСЯ ВО ВРЕМЯ ВЫПУСКА (инцидент 15.08). Прогон длится около
    # часа; правка файла в это время НЕ ЛОМАЕТ selfcheck — он проверяет распакованный
    # архив, — но корень доверия начинает указывать на пакет, которого в дереве уже нет.
    # Обнаружить это можно было только сверкой хэшей вручную, что и произошло: пакет
    # 93a2505b прошёл все проверки, не содержа правки, сделанной за минуту до конца.
    _before = _snapshot(names + [MAN.name])
    # Хэш ИСТОЧНИКА норматива запоминается наравне с файлами манифеста: он вне
    # r33build, поэтому _snapshot его не видит, а расхождение с ним и есть тот дефект,
    # ради которого заведена _sverit_normativ.
    global _SRC_BEFORE
    _SRC_BEFORE = hashlib.sha256((ROOT / 'docs/addfut-v1.6.0-r33.txt').read_bytes()).hexdigest()
    with zipfile.ZipFile(Z, 'w', zipfile.ZIP_DEFLATED) as f:
        for n in names + [MAN.name]:
            f.write(R / n, n)
    h = hashlib.sha256(Z.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory() as t:
        zipfile.ZipFile(Z).extractall(t)
        # НЕЗАВИСИМАЯ СВЕРКА ХЭШЕЙ ДО ЗАПУСКА ПРОВЕРЯЮЩЕГО (двенадцатый круг, №8):
        # selfcheck сам исключает себя из уровня 0б, и изменённый проверяющий код мог бы
        # заверить сам себя. Здесь release, а не selfcheck, сверяет КАЖДЫЙ файл архива —
        # включая selfcheck_v192.py — с манифестом, и только затем исполняет его.
        man = Path(t) / 'MANIFEST-192.txt'
        bad = []
        for ln in man.read_text(encoding='utf-8').splitlines():
            mm = re.match(r'^([0-9a-f]{64})\s+(\S+)$', ln.strip())
            if not mm:
                continue
            fp = Path(t) / mm.group(2)
            if not fp.exists():
                bad.append(f'{mm.group(2)}: отсутствует'); continue
            if hashlib.sha256(fp.read_bytes()).hexdigest() != mm.group(1):
                bad.append(f'{mm.group(2)}: хэш не совпал')
        if bad:
            sys.exit('ВЫПУСК НЕ СОСТОЯЛСЯ: архив расходится с манифестом ДО запуска '
                     'проверяющего: ' + '; '.join(bad[:6]))
        # ОКРУЖЕНИЕ ПРОВЕРЯЮЩЕГО ЧИСТИТСЯ (двадцать третий круг, №11): унаследованный
        # ADDFUT_BOOK_PATH или ADDFUT_DIR увёл бы стенды на ЖИВЫЕ пути, и lstat-снимок
        # ~/.addfut этого не заметил бы — он сторожит каталог, а не переопределение.
        _env = {k: v for k, v in os.environ.items() if not k.startswith('ADDFUT_')}
        r = subprocess.run([str(PY), 'selfcheck_v192.py'], cwd=t, capture_output=True,
                           text=True, env=_env)
        tail = (r.stdout or r.stderr).strip().splitlines()[-1:]
    ok = r.returncode == 0 and 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' in (r.stdout or '')
    print(f'{Z.name}: {len(names) + 1} файлов, {Z.stat().st_size / 1048576:.2f} МБ')
    print(f'SHA-256: {h}')
    print(f'распакованный архив: {tail[0] if tail else "нет вывода"}')
    if not ok:
        # ПРИЧИНА ПРОВАЛА ПОКАЗЫВАЕТСЯ ЦЕЛИКОМ (двадцать второй круг; наблюдение 14.08.2026).
        # Прежде печатались последние 3000 знаков stdout — а провалы уровня 0 и падения
        # проверяющего лежат ВЫШЕ этого хвоста, stderr не печатался вовсе. Диагностика шла
        # вслепую: «архив не проходит selfcheck» без единого слова о том, что именно.
        _fails = [l for l in (r.stdout or '').splitlines()
                  if l.startswith('[FAIL]') or l.startswith('ИТОГ:')]
        if _fails:
            print('ПРОВАЛЫ ПРОВЕРЯЮЩЕГО:')
            for _l in _fails:
                print('  ' + _l)
        if r.stderr and r.stderr.strip():
            print('STDERR ПРОВЕРЯЮЩЕГО (хвост):')
            print('  ' + '\n  '.join(r.stderr.strip().splitlines()[-15:]))
        if not _fails and not (r.stderr or '').strip():
            print((r.stdout or '')[-3000:])
        sys.exit('ВЫПУСК НЕ СОСТОЯЛСЯ: архив не проходит selfcheck')
    # СВЕРКА ДЕРЕВА — ДО ПУБЛИКАЦИИ В ИСТОРИИ (двадцать четвёртый круг, №21). Прежде она
    # стояла ПОСЛЕ копирования в releases/ и записи INDEX.txt: отвергнутый пакет успевал
    # попасть в датированную историю и в индекс как состоявшийся выпуск.
    # СВЕРКА НОРМАТИВА ПОВТОРЯЕТСЯ ПЕРЕД ПУБЛИКАЦИЕЙ, А НЕ ТОЛЬКО В НАЧАЛЕ.
    # ОСНОВАНИЕ — ПРОВАЛ ЭТОЙ ЖЕ ЗАЩИТЫ НА ПЕРВОМ БОЕВОМ ПРОГОНЕ, 27.08.2026. Сверка стояла
    # ОДИН РАЗ в начале (строка 132), выпуск идёт больше часа, а сторож неподвижности дерева
    # `_snapshot` перечисляет только файлы МАНИФЕСТА, то есть r33build. Источник норматива
    # лежит в docs/ и в снимок не попадал. Хронология: выпуск стартовал 08:26:47 и сверку
    # прошёл на 4216 строках; коммит 7cdc582 в 09:14 дописал в docs/ 44
    # строки §12; публикация в 09:39 заверила корнем доверия 177b26db архив со СТАРЫМ
    # текстом. Защита, заведённая ровно против расхождения копий, пропустила расхождение,
    # потому что смотрела не в тот момент и не на тот каталог.
    # ДВА ЛЕЧЕНИЯ, И НУЖНЫ ОБА: (а) источник норматива добавлен в снимок неподвижности —
    # тогда правка docs/ во время прогона видна как «дерево изменилось»; (б) сама сверка
    # повторяется ЗДЕСЬ, после selfcheck и до записи корня доверия, потому что снимок ловит
    # изменение, а сверка ловит РАСХОЖДЕНИЕ — например если docs/ и r33build правили оба.
    _sverit_normativ()
    _after = _snapshot(names + [MAN.name])
    _moved = sorted(n for n in (names + [MAN.name]) if _before.get(n) != _after.get(n))
    _src_now = hashlib.sha256((ROOT / 'docs/addfut-v1.6.0-r33.txt').read_bytes()).hexdigest()
    if _src_now != _SRC_BEFORE:
        print('ВЫПУСК НЕ СОСТОЯЛСЯ: ИСТОЧНИК НОРМАТИВА (docs/) изменился во время прогона — '
              f'было {_SRC_BEFORE[:12]}, стало {_src_now[:12]}. Корень доверия указывал бы на '
              'архив с устаревшим текстом; ни история, ни корень НЕ обновлены. '
              'Синхронизировать r33build-копию, пересобрать PDF и повторить.')
        return 1
    if _moved:
        print(f'ВЫПУСК НЕ СОСТОЯЛСЯ: дерево изменилось ВО ВРЕМЯ прогона — {_moved[:6]}'
              f'{" и ещё " + str(len(_moved) - 6) if len(_moved) > 6 else ""}. '
              f'Архив проверен, но корень доверия указывал бы на устаревший пакет; '
              f'ни история выпусков, ни корень НЕ обновлены — повторить на неподвижном дереве.')
        return 1
    # ИСТОРИЯ ВЫПУСКОВ: архив прежде перезаписывался на месте, и предыдущий корень доверия
    # исчезал физически. Каждый выпуск теперь остаётся датированной копией.
    import datetime
    rel = ROOT / 'releases'
    rel.mkdir(exist_ok=True)
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%d-%H%M%S')
    # ПУБЛИКУЮТСЯ ИМЕННО ПРОВЕРЕННЫЕ БАЙТЫ (двадцать пятый круг, №19). SHA считался ДО
    # часового selfcheck, а копировался архив, перечитанный ПОСЛЕ: параллельный release.py
    # мог заменить Z, и в имя с индексом ушёл бы старый хэш при других байтах. Хэшируем
    # заново и сверяем; расхождение — выпуск не состоялся.
    _h_now = hashlib.sha256(Z.read_bytes()).hexdigest()
    if _h_now != h:
        print(f'ВЫПУСК НЕ СОСТОЯЛСЯ: архив изменился после проверки '
              f'(было {h[:12]}, стало {_h_now[:12]}) — вероятен параллельный выпуск; '
              f'ни история, ни корень доверия не тронуты')
        return 1
    keep = rel / f'paket-r33-{stamp}-{h[:8]}.zip'
    # КОРЕНЬ ДОВЕРИЯ — ДО ИСТОРИИ (№19): прежде releases/ и INDEX.txt обновлялись раньше
    # docs/r33-sha256.txt, и сбой последней записи оставлял пакет опубликованным и
    # проиндексированным без корня — тот же ложный выпуск, что закрывали в 24-м круге.
    (ROOT / 'docs/r33-sha256.txt').write_text(
        f'Корень доверия ADD-FUT v1.6.0 ред. 33\n\nАрхив {Z.name}\nSHA-256  {h}\n\n'
        f'Внутри — MANIFEST-192.txt на {len(names)} файлов: код, нормативный текст и '
        f'ИСХОДНЫЕ РЯДЫ.\nПроверка: распаковать в пустой каталог и выполнить  '
        f'python selfcheck_v192.py\nХэш получен ПОСЛЕ такой проверки, а не до неё.\n',
        encoding='utf-8')
    shutil.copy2(Z, keep)
    with open(rel / 'INDEX.txt', 'a', encoding='utf-8') as f:
        f.write(f'{stamp}  {h}  {keep.name}\n')
    return 0


if __name__ == '__main__':
    # КОД ВОЗВРАТА ОБЯЗАТЕЛЕН (двадцать четвёртый круг, №21). main() возвращал 1 при
    # изменении дерева, но вызывался без sys.exit — процесс завершался НУЛЁМ, и автоматика
    # получала «успешный выпуск» с пакетом, который сам скрипт объявил устаревшим.
    sys.exit(main())
