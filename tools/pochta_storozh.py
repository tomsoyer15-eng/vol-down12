#!/usr/bin/env python3
"""Почтовый сторож: письмо заказчику, когда с контуром что-то не так. Каждые 15 минут из cron.

ЧТО СЧИТАЕТСЯ «НЕ ТАК» (список закрыт, не расширяется без решения заказчика):
  1. АКТИВНЫЙ ALARM — файл ~/.addfut/ALARM*.txt без суффикса .resolved*: автопилот заперт.
  2. МЁРТВЫЙ ТИК — tick-heartbeat старше 65 минут: контур молчит, а молчание и отказ
     обязаны различаться (тик идёт каждые 10 минут круглосуточно).
  3. ПРОВАЛ НАБЛЮДАТЕЛЯ — последняя строка nablyudatel.log «завершён, код N» с N != 0.

БЕЗ ПОВТОРОВ: на каждое событие — одно письмо; отметка в ~/.addfut/mail-marks/ по имени
события. Снятое и вновь возникшее событие (новый ALARM, новая дата провала) — новое письмо.
Восстановление отметок не чистим автоматически: их разбор — часть разбора инцидента.

ЧЕГО СТОРОЖ НЕ ДЕЛАЕТ: не лечит, не трогает состояние контура, не читает торговых решений.
Только смотрит и пишет письмо. Отказ почты (нет настройки, нет сети) — строка в свой
журнал; сторож не падает и не глушит следующие проверки.
"""
import datetime
import pathlib
import subprocess
import sys
import time

ДОМ = pathlib.Path('~/.addfut').expanduser()
ОТМЕТКИ = ДОМ / 'mail-marks'
ЖУРНАЛ = ДОМ / 'pochta-storozh.log'
ПОЧТАЛЬОН = pathlib.Path(__file__).with_name('trevoga_mail.py')
ПРЕДЕЛ_ТИКА_СЕК = 65 * 60


def в_журнал(текст):
    метка = datetime.datetime.now().strftime('%F %T')
    with ЖУРНАЛ.open('a', encoding='utf-8') as ф:
        ф.write(f'{метка} {текст}\n')


def письмо(ключ, тема, тело):
    """Одно письмо на событие: отметка ставится ТОЛЬКО после успешной отправки —
    иначе отказ сети навсегда съедал бы тревогу."""
    ОТМЕТКИ.mkdir(exist_ok=True)
    отметка = ОТМЕТКИ / ключ
    if отметка.exists():
        return
    ход = subprocess.run([sys.executable, str(ПОЧТАЛЬОН), тема],
                         input=тело, text=True, capture_output=True, timeout=120)
    if ход.returncode == 0:
        отметка.write_text(datetime.datetime.now().isoformat())
        в_журнал(f'ОТПРАВЛЕНО: {тема}')
    else:
        в_журнал(f'ПОЧТА НЕ УШЛА (код {ход.returncode}): {тема}: '
                 f'{(ход.stderr or ход.stdout).strip()[:200]}')


def главная():
    # 1. активные тревоги
    for ф in sorted(ДОМ.glob('ALARM*')):
        if '.resolved' in ф.name:
            continue
        письмо(f'alarm-{ф.name}', f'ТРЕВОГА: {ф.name} — автопилот остановлен',
               f'Файл тревоги: {ф}\n\n{ф.read_text(encoding="utf-8", errors="replace")[:2000]}\n\n'
               f'Автопилот заперт до ручного разбора (О-5). Правка кода — только после '
               f'карточки дефекта.')

    # 2. мёртвый тик
    сердце = ДОМ / 'tick-heartbeat'
    if сердце.exists():
        try:
            возраст = time.time() - float(сердце.read_text().strip())
        except ValueError:
            возраст = None
        if возраст is not None and возраст > ПРЕДЕЛ_ТИКА_СЕК:
            письмо(f'dead-tick-{datetime.date.today()}',
                   'Тик автопилота молчит',
                   f'tick-heartbeat не обновлялся {возраст / 60:.0f} минут при шаге 10 мин.\n'
                   f'Контур, вероятно, не работает: cron, машина или зависший запуск.\n'
                   f'Это письмо шлётся раз в день; следующее — при новой дате.')
    else:
        письмо(f'no-heartbeat-{datetime.date.today()}', 'Нет файла tick-heartbeat',
               'Файл сердцебиения отсутствует — контур не тикал ни разу либо каталог '
               'состояния недоступен.')

    # 3. провал наблюдателя
    жн = ДОМ / 'nablyudatel.log'
    if жн.exists():
        хвост = [с for с in жн.read_text(encoding='utf-8').splitlines()
                 if 'завершён, код' in с]
        if хвост and not хвост[-1].rstrip().endswith('код 0'):
            письмо(f'nabl-fail-{хвост[-1][:10]}', 'Наблюдатель завершился с ошибкой',
                   f'Последний запуск: {хвост[-1]}\nОтчёт этого дня мог не появиться; '
                   f'журнал: {жн}')


if __name__ == '__main__':
    try:
        главная()
    except Exception as ошибка:
        в_журнал(f'ОШИБКА СТОРОЖА: {type(ошибка).__name__}: {ошибка}')
        raise
