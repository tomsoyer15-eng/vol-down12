#!/bin/bash
# СТОРОЖ РАЗРУШИТЕЛЬНЫХ КОМАНД (17.08.2026, по требованию заказчика).
#
# ЗАЧЕМ. Правило 11 CLAUDE.md («никаких rm -rf и массовых удалений») до сих пор было
# ОБЕЩАНИЕМ, а не механизмом: его исполнение зависело от того, что модель о нём помнит.
# В этой же сессии риск реализовался в мягком виде — соседняя сессия выполнила
# ошибочный откат и вернула два файла, которые никто не собирался трогать.
# Сторож переводит правило из памяти в код: он стоит ПЕРЕД выполнением каждой Bash-команды
# и отказывает, не спрашивая модель.
#
# КАК РАБОТАЕТ. Хук PreToolUse получает на stdin JSON вызова. Если команда попадает под
# запрет, печатается решение "deny" — команда не выполняется вовсе. Всё прочее проходит
# молча (печатается пустой ответ), чтобы сторож не мешал обычной работе.
#
# КАЛИТКА ДЛЯ ЗАКОННЫХ УДАЛЕНИЙ. Правило 11 разрешает удалять файлы проекта поштучно и с
# явного согласия заказчика. Такое согласие оформляется меткой в самой команде:
#     rm docs/staroe.md   # РАЗРЕШЕНО-ЗАКАЗЧИКОМ
# Метка видна в переписке и в журнале — то есть согласие остаётся доказуемым, а не устным.
#
# ЧЕГО СТОРОЖ НЕ ДЕЛАЕТ. Он не защищает от порчи файла записью (Edit/Write), от ошибок в
# коде и от удалений, сделанных не через Bash. Это первая линия, а не единственная:
# внешние копии (GitHub, зеркало, Google Drive, releases/, ~/.addfut-backups) остаются
# способом ВОССТАНОВИТЬ, тогда как сторож — способ НЕ ДОПУСТИТЬ.
#
# ЧЕГО ОН НЕ МОЖЕТ В ПРИНЦИПЕ, И ЭТО НАДО ЗНАТЬ (27.08.2026). Он сопоставляет ТЕКСТ, а не
# разбирает оболочку, поэтому неизбежны обе ошибки: пропуск экзотической записи и ложный
# отказ на безобидной строке, где опасный литерал стоит внутри кавычек или в комментарии.
# Вторая ошибка наблюдалась в тот же день трижды подряд и стоит дешевле первой: она видна
# сразу и снимается меткой согласия. Поэтому при сомнении сторож ЗАПРЕЩАЕТ.
# СЛЕДСТВИЕ ДЛЯ ПРАВКИ САМОГО СТОРОЖА: его исходник содержит опасные литералы, значит
# редактировать его через Bash нельзя — сторож заблокирует запись собственного текста.
# Правится он файловым инструментом; проверяется прогоном tools/guard_probe.py.
set -u

CMD="$(jq -r '.tool_input.command // empty' 2>/dev/null)"
# ОТСУТСТВИЕ jq ИЛИ ЧУЖАЯ ФОРМА ВЫЗОВА — ЭТО ОТКАЗ, А НЕ РАЗРЕШЕНИЕ (27.08.2026).
# Прежде здесь стоял `exit 0`: без jq, при переименованном поле или пустой команде сторож
# молча пропускал ВСЁ, и его отсутствие было неотличимо от «возражений нет». Защита,
# которая исчезает бесшумно, хуже отсутствующей.
if ! command -v jq >/dev/null 2>&1; then
  printf '%s\n' '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Сторож правила 11 не может работать: в PATH нет jq. Команда не выполнена. Установите jq или снимите хук осознанно."}}'
  exit 0
fi
[ -z "$CMD" ] && exit 0

deny() {
  # permissionDecision=deny — Claude Code не выполняет команду и показывает причину.
  jq -nc --arg r "$1" '{hookSpecificOutput:{hookEventName:"PreToolUse",
                        permissionDecision:"deny", permissionDecisionReason:$r}}'
  exit 0
}

# ЯВНОЕ СОГЛАСИЕ ЗАКАЗЧИКА СНИМАЕТ ЗАПРЕТ (правило 11: поштучно и с согласия).
case "$CMD" in
  *РАЗРЕШЕНО-ЗАКАЗЧИКОМ*) exit 0 ;;
esac

# НОРМАЛИЗАЦИЯ ТЕКСТА ПЕРЕД РАЗБОРОМ (27.08.2026). Обойти сторожа удавалось не хитростью,
# а обычными записями: табуляция вместо пробела, кавычка от обёртки `sh -c "..."`, обратная
# косая перед именем команды (типовая идиома «мимо алиасов»). Приводим табуляции к пробелам
# и снимаем обратную косую, чтобы граница слова ниже видела то же, что увидит оболочка.
_N="$(printf '%s' "$CMD" | tr '\t' ' ' | sed -E 's/\\(rm|git|find|mv|shred|unlink)/\1/g')"

# ГРАНИЦА СЛОВА — ЛЮБОЙ НЕ-ИМЕННОЙ СИМВОЛ. Прежний класс (^|[;&|(]| ) не включал кавычку,
# табуляцию и обратную косую, поэтому обёртка с кавычкой проходила насквозь. Теперь перед
# именем допускается что угодно, кроме букв, цифр, подчёркивания и знаков пути, — так
# `norm`, `firm`, `./confirm` по-прежнему не считаются командой удаления.
_B='(^|[^[:alnum:]_./-])'

# ВРЕМЕННЫЕ КАТАЛОГИ — ВНЕ ОХРАНЫ, НО ТОЛЬКО ДЛЯ ПРАВИЛА 1 (исправлено 27.08.2026).
# Прежде калитка делала `exit 0` и снимала ВСЕ ЧЕТЫРЕ запрета разом: достаточно было
# приписать слева безобидное удаление во временном каталоге, и рядом проходил любой откат
# дерева или массовое удаление по шаблону. Проверено исполнением — девять обходов из
# девяти. Теперь калитка лишь помечает, что рекурсивное удаление здесь законно; правила
# 2, 3 и 4 исполняются ВСЕГДА.
# ПУТЬ С «..» КАЛИТКОЙ НЕ СЧИТАЕТСЯ: он начинается под /tmp, но ведёт наружу — это был
# отдельный обход, тоже подтверждённый исполнением.
_tmp_only=0
_targets="$(printf '%s' "$_N" | grep -oE "${_B}rm [^|;&]*" | sed -E 's/^[^r]*rm //; s/--[a-z-]+//g; s/-[a-zA-Z]+//g')"
if [ -n "$_targets" ]; then
  _outside=0
  for _t in $_targets; do
    case "$_t" in
      *..*)   _outside=1 ;;            # выход из-под /tmp обратным переходом
      /tmp/*) ;;                       # временный каталог прогонов
      *)      _outside=1 ;;
    esac
  done
  [ "$_outside" = 0 ] && _tmp_only=1
fi

# 1. Рекурсивное/принудительное удаление — в любом виде.
# ДЛИННЫЕ КЛЮЧИ GNU ЛОВЯТСЯ НАРАВНЕ С КОРОТКИМИ: форма с полными именами ключей сносила
# каталог проекта и проходила, потому что шаблон разбирал только односимвольные ключи.
if [ "$_tmp_only" = 0 ] && printf '%s' "$_N" | grep -Eq "${_B}rm( +-[a-zA-Z-]*)* +(-[a-zA-Z]*[rRf]|--(recursive|force|dir))"; then
  deny 'Правило 11 CLAUDE.md: рекурсивное или принудительное удаление (rm -r/-f) запрещено. Удалять файлы проекта можно только ПОШТУЧНО, после git-коммита текущего состояния и с явного согласия заказчика — тогда добавьте в команду метку «# РАЗРЕШЕНО-ЗАКАЗЧИКОМ».'
fi

# 2. Удаление чего угодно в машинном состоянии счёта и в точках восстановления.
if printf '%s' "$_N" | grep -Eq "${_B}(rm|shred|unlink) .*(\.addfut|addfut-backups|state-mirror|git-mirrors|releases/|anchors/)"; then
  deny 'Правило 11 CLAUDE.md: это машинное состояние счёта или точка восстановления (~/.addfut, ~/.addfut-backups, ~/state-mirror, ~/git-mirrors, releases/, anchors/). Удаление запрещено без явного согласия заказчика — метка «# РАЗРЕШЕНО-ЗАКАЗЧИКОМ».'
fi

# 3. Массовый откат рабочего дерева. Именно так пострадали docs/ 16.08: файлы вернулись к
#    состоянию HEAD вместе с несохранёнными правками, и заметили это не сразу.
#    ПОДКОМАНДА ИЩЕТСЯ ЧЕРЕЗ КЛЮЧИ (27.08.2026): форма с ключом каталога перед подкомандой
#    проходила насквозь, потому что шаблон требовал имя и подкоманду вплотную. И откат
#    рабочего дерева теперь ловится с ЛЮБЫМ путём, а не только с точкой или двумя дефисами:
#    путь без «--» откатывает ровно так же, и именно так были потеряны правки 16.08.
if printf '%s' "$_N" | grep -Eq "${_B}git( +-[a-zA-Z-]+( +[^ ]+)?)* +(checkout|restore|reset|clean)"; then
  case "$_N" in
    *'reset --hard'*|*'clean -'*|*'checkout '*|*'restore '*)
      deny 'Откат рабочего дерева (reset --hard / clean / checkout / restore) уничтожает несохранённые правки. 16.08 ровно этим были потеряны правки docs/. Сначала зафиксируйте состояние (git commit или git stash), затем повторите с меткой «# РАЗРЕШЕНО-ЗАКАЗЧИКОМ».' ;;
  esac
fi

# 4. Массовое удаление через find и перемещение корневых каталогов.
if printf '%s' "$_N" | grep -Eq "${_B}find .*-(delete|exec +rm)"; then
  deny 'Массовое удаление через find запрещено (правило 11): оно не различает, что именно попадёт под шаблон. Перечислите файлы поимённо.'
fi
if printf '%s' "$_N" | grep -Eq "${_B}mv +[^|;&]*(\.addfut|vol-down12|git-mirrors)[^|;&]* +/"; then
  deny 'Перемещение каталога проекта или машинного состояния равносильно его потере для всех путей, которые на него смотрят (cron, автопилот, книга). Запрещено без явного согласия заказчика.'
fi

exit 0
