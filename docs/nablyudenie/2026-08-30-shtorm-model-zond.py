"""Моделирование ШТОРМОВЫХ дней на живой книге пилота (вопрос заказчика 30.08.2026).

Ничего не трогает: книга читается копией, решения считает ЗАМОРОЖЕННЫЙ движок daily.step —
тот же код, что торгует каждый день. Показываем, что робот РЕШИТ в крайних состояниях.
Опорные цифры вчерашнего замыкания: SPY 769,35, NLV 994 888, книга 2 ES + 6 MES (Z26),
нога Б выключена, плечо 1,0053.
"""
import sys

sys.path.insert(0, 'r33build/live')
sys.path.insert(0, 'r33build')
import daily as DL
import pandas as pd

СПЯ = 769.35
НЛВ = 994_888.13
ДРЕФ = 7.91
книга = DL.Book(d_fix=7.9291443970797975, n_e=26, n_b=0, unit_is_mes=True,
                prev_st_eq=True, prev_st_bd=False, ser_a='Z26', ser_b='Z26', es_held=2,
                prev_close_lev=1.0053, last_session='2026-08-28')

def сессия(имя, спя_вчера, нлв, плечо_вчера=None, книга_=None, st_eq=True):
    б = книга_ or книга
    if плечо_вчера is not None:
        б = DL.replace(б, prev_close_lev=плечо_вчера)
    м = DL.Market(date=pd.Timestamp('2026-08-31'), px_eq_prev=спя_вчера, dref_prev=ДРЕФ,
                  dref_today=ДРЕФ, px_eq_today=спя_вчера, roll_today=False,
                  st_eq=st_eq, st_bd=False, roll_passed=True)
    р = DL.step(б, м, нлв, check_guards=False)
    заявки = DL.book_to_orders(р, б)
    экспо = sum(р.exposure.values()) if isinstance(р.exposure, dict) else 0
    print(f'\n=== {имя} ===')
    print(f'  вход: SPY {спя_вчера:.2f}, NLV {нлв:,.0f}, плечо накануне '
          f'{б.prev_close_lev:.4f}, книга {б.n_e} ед. ноги А')
    print(f'  решение: торговать={р.trade}; книга после: {р.book_after.n_e} ед. '
          f'(было {б.n_e}); кап-срез={"ДА" if р.cap_correction else "нет"}')
    if заявки:
        print('  заявки: ' + ', '.join(f'{и} {ч:+.10g}' for и, ч in заявки))
    else:
        print('  заявки: НЕТ (внутри полосы)')
    for пр in (р.reasons or [])[:3]:
        print(f'  причина: {пр[:100]}')
    for от in (р.refusals or [])[:3]:
        print(f'  ОТКАЗ: {от[:100]}')
    print(f'  плечо на закрытие: {р.leverage:.4f}' if р.leverage else '', end='')
    print(f'; экспозиция {экспо:,.0f}' if экспо else '')

# 1. ЧЁРНЫЙ ПОНЕДЕЛЬНИК: −20,5% как 19.10.1987. Экспозиция ~1×NLV -> NAV падает вместе с
# рынком, плечо почти не растёт — но полоса и решение пересчитываются от нового NAV.
сессия('КРАХ −20,5% (повтор 19.10.1987)', СПЯ * 0.795, НЛВ * (1 - 0.205 * 1.0053))

# 2. Взлёт +10% за день.
сессия('ВЗЛЁТ +10%', СПЯ * 1.10, НЛВ * (1 + 0.10 * 1.0053))

# 3. Тот же крах, но книга стояла НА ПОТОЛКЕ плеча 2,00 (гипотетическая): NAV −41%,
# плечо взлетает к ~2,7 — обязан сработать кап-срез.
книга_кап = DL.Book(d_fix=книга.d_fix, n_e=52, n_b=0, unit_is_mes=True, prev_st_eq=True,
                    prev_st_bd=False, ser_a='Z26', ser_b='Z26', es_held=5,
                    prev_close_lev=2.0, last_session='2026-08-28')
сессия('КРАХ −20,5% ПРИ ПЛЕЧЕ 2,00', СПЯ * 0.795, НЛВ * (1 - 0.205 * 2.0),
       книга_=книга_кап)

# 4. Крах + сигнал выключил ногу А (закрытие месяца ниже SMA): полный выход.
сессия('КРАХ + СИГНАЛ ВЫКЛЮЧИЛ НОГУ А', СПЯ * 0.795, НЛВ * (1 - 0.205 * 1.0053),
       st_eq=False)

# 5. Экстремальный гэп −35% за сессию (хуже 1987) при плече 2,00.
сессия('ГЭП −35% ПРИ ПЛЕЧЕ 2,00', СПЯ * 0.65, НЛВ * (1 - 0.35 * 2.0), книга_=книга_кап)
print()
