def _atomic_write(path, body):
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix='.worm-')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(body)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


