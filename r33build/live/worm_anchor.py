def _git_commit_verified(out, body=None):
    """add+commit якоря с ПРОВЕРКОЙ (№18): '|| true' прятал отказ, и «WORM создан»
    относился к файлу, не существующему нигде, кроме локального диска.

    СРАВНИВАЕТСЯ СОДЕРЖИМОЕ, А НЕ ИМЯ (девятнадцатый круг, №19): ls-tree --name-only
    подтверждал лишь присутствие пути — pre-commit hook или конкурентный процесс могли
    подменить blob, и «якорь в HEAD» относился к другому тексту. Сверяется git-объект
    HEAD с хэшем ФАЙЛА на диске (тем самым, чей текст проверен)."""
    rel = out.relative_to(ROOT)
    r1 = subprocess.run(['git', '-C', str(ROOT), 'add', str(rel)],
                        capture_output=True, text=True)
    if r1.returncode != 0:
        raise RuntimeError(f'git add отказал: {r1.stderr.strip()[:120]}')
    # КОММИТ ТОЛЬКО ЯКОРЯ (двадцать четвёртый круг, №26). Обычный `git commit` захватывал
    # ВСЁ, что уже лежало в index: незавершённая или непроверенная правка торгового кода
    # молча уезжала вместе с WORM-якорем и выглядела частью ЗАВЕРЕННОЙ истории, хотя
    # проверяется потом только blob якоря. `--only <путь>` коммитит ровно один файл и не
    # трогает остальной индекс.
    r2 = subprocess.run(['git', '-C', str(ROOT), 'commit', '-q', '--only', str(rel), '-m',
                         f'WORM-якорь {out.stem}'], capture_output=True, text=True)
    if r2.returncode != 0:
        raise RuntimeError(f'git commit отказал: {(r2.stderr or r2.stdout).strip()[:120]}')
    r3 = subprocess.run(['git', '-C', str(ROOT), 'ls-tree', 'HEAD', '--', str(rel)],
                        capture_output=True, text=True)
    if r3.returncode != 0 or not r3.stdout.strip():
        raise RuntimeError('якорь не виден в HEAD после коммита — заверение ложно')
    try:
        blob_head = r3.stdout.split()[2]
    except IndexError:
        raise RuntimeError(f'ls-tree вернул неразбираемое: {r3.stdout[:80]!r}')
    # СВЕРКА С ПРОВЕРЕННЫМ ТЕЛОМ, А НЕ С ФАЙЛОМ ПОСЛЕ HOOK (двадцать восьмой круг, №17).
    # hash-object считал хэш файла НА ДИСКЕ уже после коммита: pre-commit hook или чужой
    # процесс могли переписать и файл, и blob согласованно — сверка совпадала бы, заверяя
    # чужой текст. Хэшируем ТО ТЕЛО, которое проверено и записано, не перечитывая диск.
    import subprocess as _sp2
    # ХЭШИРУЕТСЯ ПРОВЕРЕННОЕ ТЕЛО (двадцать девятый круг, №16). Прежний вариант читал файл
    # с диска — пусть и через stdin, но ПОСЛЕ коммита: pre-commit hook или чужой процесс
    # могли согласованно переписать и файл, и blob, и сверка совпала бы, заверяя чужой
    # текст. Сравнивать надо с тем, что мы ПРОВЕРИЛИ, а не с тем, что сейчас лежит рядом.
    _payload = (body.encode('utf-8') if isinstance(body, str)
                else (body if body is not None else out.read_bytes()))
    r4 = _sp2.run(['git', '-C', str(ROOT), 'hash-object', '--stdin'],
                  input=_payload, capture_output=True)
    _blob_body = r4.stdout.decode().strip() if r4.returncode == 0 else ''
    if not _blob_body:
        raise RuntimeError(f'git hash-object отказал: {r4.stderr.decode()[:120]}')
    if blob_head != _blob_body:
        raise RuntimeError('содержимое якоря в HEAD НЕ СОВПАДАЕТ с записанным файлом '
                           '(подмена между add и commit) — заверение ложно')


def _tar_state(day, bdir):
    st = _state_root()               # действующий каталог (девятнадцатый круг, №18)
    bdir = _as_path(bdir)
    bdir.mkdir(parents=True, exist_ok=True)
    import datetime as _dt
    # ВРЕМЯ В ИМЕНИ — В ТОЙ ЖЕ ЗОНЕ, ЧТО И ДАТА (сорок третий круг, №10). Дата приходит
    # чикагская (биржевой день), а время бралось UTC — и в 18:00 CST / 19:00 CDT UTC
    # переходит через полночь, тогда как чикагская дата ещё прежняя. Поздний архив получал
    # ...-000100 и становился лексикографически СТАРШЕ раннего ...-235900. Это ломает ровно
    # то, что я чинил в 42-м круге: ротация могла удалить более НОВЫЙ снимок, а выбор
    # «последнего» якоря — промахнуться мимо свежего .pending. Имя обязано быть монотонным
    # внутри своего дня, иначе «поколение из имени» не лучше mtime.
    import zoneinfo as _zi
    stamp = _dt.datetime.now(_zi.ZoneInfo('America/Chicago')).strftime('%H%M%S')
    tmp = bdir / f'.addfut-{day}-{stamp}.tmp'
    # АРХИВ ПУБЛИКУЕТСЯ ПОД РАБОЧИМ ИМЕНЕМ ТОЛЬКО ПОСЛЕ ЗАВЕРЕНИЯ (36-й круг, №11). Прежде
    # он сразу получал имя addfut-*.tgz, а якорь и git-коммит создавались позже: SIGKILL или
    # потеря питания между этими шагами оставляли НЕЗАВЕРЕННЫЙ архив под штатной маской, и
    # следующий backup_push (или ручное восстановление) считал его обычной копией. Ветка
    # except помечает .rejected только при ЛОВИМОМ исключении. Промежуточное имя .pending
    # закрывает окно: под рабочим именем лежит только то, что заверено.
    dst = bdir / f'addfut-{day}-{stamp}.tgz.pending'
    skip = {'ibgw.env'}                      # секреты не копируются
    with tarfile.open(tmp, 'w:gz') as tf:
        for p in sorted(st.rglob('*')):
            rel = p.relative_to(st)
            if rel.parts[0] in skip or rel.parts[0] == 'zoneinfo' \
               or p.suffix == '.lock':
                continue
            # РАЗЫМЕНОВАНИЕ И ЗДЕСЬ (сорок третий круг, №9). Внешние заверенные файлы я
            # научил класться байтами (`resolve()`), а содержимое каталога состояния
            # оставил как было: при dereference=False символическая ссылка попадает в архив
            # ССЫЛКОЙ. journal-*.csv, signals_live.csv, signals_levels.csv, account.txt или
            # route.txt, будучи ссылками, дали бы зелёный архив — якорь хэширует байты цели,
            # а копия несёт лишь путь к ней, и после потери машины восстанавливать нечего.
            # Проверка типа членов смотрела только attested/, так что и она молчала.
            tf.add(p.resolve() if p.is_symlink() else p,
                   arcname=str(Path('.addfut') / rel), recursive=False)
        # ЗАВЕРЕННОЕ ОБЯЗАНО БЫТЬ ВОССТАНОВИМО (сорок первый круг, №10; решение заказчика
        # 17.08 — включить). Якорь хэшировал реестр контрактов, замер маржи, журнал МР и
        # конфигурацию развёртывания, а в архив шёл только каталог состояния: хэши
        # доказывали отсутствие подмены, но после потери машины восстановить эти файлы было
        # НЕЧЕМ. Заверение без байтов — половина резервирования, и худшая половина: оно
        # выглядит полным. Кладём их под attested/, чтобы имя в архиве не спорило с .addfut.
        for _lbl, _pp, _arc, _must in _attested_paths():
            if _pp.exists() and _pp.is_file():
                # РАЗЫМЕНОВАНИЕ: кладём БАЙТЫ, а не ссылку (№8). Resolve() даёт цель, и в
                # архив попадает содержимое — иначе после потери машины ссылка битая.
                tf.add(_pp.resolve(), arcname=_arc, recursive=False)
    with open(tmp, 'rb') as f:
        os.fsync(f.fileno())
    os.replace(tmp, dst)
    # FSYNC КАТАЛОГА АРХИВА (тридцать четвёртый круг, №12): дальше хэш архива уходит в
    # git-якорь, backup_state объявляет успех и ставит closed-*. При потере питания запись
    # каталога может исчезнуть, тогда как WORM-якорь и диспетчерское состояние уже
    # утверждают наличие КОНКРЕТНОЙ проверенной копии — ложное доказательство резервирования
    # ровно в тот момент, когда восстановление и понадобится.
    _dfd = os.open(str(dst.parent), os.O_DIRECTORY)
    try:
        os.fsync(_dfd)
    finally:
        os.close(_dfd)
    return dst


def reject_archive(dst):
    """Пометить отвергнутый архив (двадцатый круг, №22). Отдельной функцией — под парную
    мутацию. Возвращает '' при успехе, иначе текст предупреждения."""
    try:
        dst.rename(dst.with_suffix(dst.suffix + '.rejected'))
        # ПЕРЕИМЕНОВАНИЕ ДОЛГОВЕЧНО (тридцать пятый круг, №8): без fsync каталога после
        # потери питания запись может вернуть СТАРОЕ рабочее имя .tgz, хотя код уже
        # установил, что архив разных поколений либо не имеет подтверждённого якоря.
        # Следующий backup_push подхватит его как штатную копию, и восстановление даст
        # старую книгу при другой позиции брокера — ложное доказательство резервирования
        # ровно там, где оно и опасно.
        _dfd = os.open(str(dst.parent), os.O_DIRECTORY)
        try:
            os.fsync(_dfd)
        finally:
            os.close(_dfd)
        return ''
    except OSError as ex:
        return (f' | ВНИМАНИЕ: отклонённый архив {dst.name} НЕ переименован ({ex}) — '
                f'убрать вручную, иначе им можно восстановиться')


