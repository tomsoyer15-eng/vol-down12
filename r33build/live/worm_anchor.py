def attested_missing_from_archive(tgz):
    """ЗАВЕРЕННОЕ ЛЕЖИТ В АРХИВЕ — ПРОВЕРЯЕТСЯ ПО СОДЕРЖИМОМУ (сорок первый круг, №10).

    Раньше здесь была ОПИСЬ: она перечисляла заверенное, что лежит вне каталога состояния, и
    доказывала лишь расположение файлов на диске. Это не доказательство резервирования —
    доказательство в том, что байты ЕСТЬ В АРХИВЕ. Открываем .tgz и сверяем имена членов со
    списком _attested_paths(); отсутствующее называем поимённо. Проверка читает то, что
    получилось, а не то, что задумано, — иначе она снова подтверждала бы намерение.
    Возвращает список описаний; пустой — всё заверенное восстановимо из этого архива.
    """
    bad = []
    try:
        with tarfile.open(tgz, 'r:gz') as tf:
            members = {m.name: m for m in tf.getmembers()}
    except Exception as _ex:
        return [f'архив {tgz} не читается ({_ex}) — покрытие заверенного недоказуемо']
    # ТИП ЧЛЕНА ПРОВЕРЯЕТСЯ ВО ВСЁМ АРХИВЕ, А НЕ ТОЛЬКО В attested/ (№9): ссылка вместо
    # байтов одинаково бесполезна и в .addfut.
    for _nm_m, _m_m in sorted(members.items()):
        if _m_m.issym() or _m_m.islnk():
            bad.append(f'{_nm_m}: в архиве лежит ССЫЛКА, а не байты — после потери машины '
                       f'восстановить нечем')
    for _lbl, _p, _arc, _must in _attested_paths():
        if not _p.exists():
            if _must:
                bad.append(f'{_lbl}: {_p} ОБЯЗАТЕЛЕН и отсутствует на диске — это утрата '
                           f'перед резервированием, а не «никогда не было»')
            continue
        _m = members.get(_arc)
        if _m is None:
            bad.append(f'{_lbl}: {_p} заверен якорем, но в архиве ({_arc}) его НЕТ — '
                       f'после потери машины восстановить нечем')
            continue
        # ЧЛЕН ОБЯЗАН БЫТЬ ФАЙЛОМ, А НЕ ССЫЛКОЙ (№8). Если путь реестра или замера —
        # symlink, Path.is_file() проходит, tarfile при dereference=False кладёт ССЫЛКУ, и
        # getnames() зелёный: после потери машины ссылка битая, байтов нет.
        if not _m.isfile():
            bad.append(f'{_lbl}: в архиве ({_arc}) лежит не файл, а '
                       f'{"ссылка" if _m.issym() or _m.islnk() else "объект типа " + str(_m.type)}'
                       f' — байтов в копии нет')
    return bad


def anchors_without_archive(bdir):
    """ЯКОРЬ, ОБЕЩАЮЩИЙ АРХИВ, КОТОРОГО НЕТ (тридцать девятый круг, №13).

    Порядок «сначала коммит якоря, потом публикация архива» выбран сознательно: коммит
    заверяет СОДЕРЖИМОЕ, и публиковать незаверенный архив под штатным именем нельзя — это
    дефект 37-го круга, №11. Но между этими шагами есть зазор: SIGKILL или потеря питания
    оставляют долговечный якорь, называющий `addfut-*.tgz`, которого никогда не было, —
    ложное заверение, которое следующий backup_push выгрузит наружу как доказательство.
    Отменить уже опубликованный коммит нельзя, поэтому лечение здесь одно и оно НЕ
    самолечение (О-5): состояние обязано быть найдено и названо, а не исправлено молча.
    Возвращает список описаний расхождений; пустой список — всё сходится.

    ГРАНИЦА, НАЗВАННАЯ ЯВНО (найдена вторым проходом саморецензии): проверка смотрит ТОЛЬКО
    на якоря, несущие имя архива (строка «sha256 архива (имя)» появилась позже 14.08.2026).
    Три исторических якоря её не имеют, поэтому на них проверка молчит — и это правильно,
    но «0 расхождений» на такой истории НЕ доказывает, что архивы за те дни существуют.
    Доказательством оно становится начиная с первого якоря нового формата.
    """
    import re as _re
    # ИМЕННО ЗДЕСЬ БЫЛ ОТКАЗ 18.08.2026 (§12): bdir приходит строкой из argv.
    bdir = _as_path(bdir)
    bad = []
    try:
        # ПРОВЕРЯЕТСЯ ТОЛЬКО ПОСЛЕДНИЙ ЯКОРЬ (сороковой круг, №3). Первая редакция требовала
        # локального архива для КАЖДОГО якоря — и это была мина замедленного действия:
        # backup_state оставляет 60 архивов (`ls -1t | tail -n +61 | xargs rm -f`), а якоря
        # не удаляются никогда. На 61-м снимке штатная ротация убрала бы самый старый архив,
        # и эта проверка стала бы отказывать НАВСЕГДА: книга замкнута, но closed-* не
        # ставится, поднимается тревога, следующие сессии и РОЛЛ запрещены — детерминированный
        # отказ примерно после 62 замыканий, а не аварийный край. Я закрыл один разрыв и
        # завёл другой, хуже.
        # Обнаруживаемый дефект относится ровно к ПОСЛЕДНЕМУ снимку: «коммит якоря прошёл, а
        # переименование .pending -> .tgz не состоялось». Старые архивы отсутствуют законно.
        # «ПОСЛЕДНИЙ» ОПРЕДЕЛЯЕТСЯ ПОКОЛЕНИЕМ, А НЕ mtime (сорок первый круг, №9). Сначала
        # тут стоял max(st_mtime) — изменяемая величина: touch, checkout, восстановление
        # каталога или простое копирование переставляют порядок. Если якорь с ОТСУТСТВУЮЩИМ
        # архивом старше по mtime, чем якорь с существующим, разрыв молча пропускался.
        # Моя же траекторная проверка этого не поймала: там 65 файлов писались подряд, и
        # mtime случайно совпал с порядком поколений — проверка подтвердила ровно то
        # совпадение, которое сама и создала.
        # Поколение читается из ИМЕНИ: worm-ГГГГ-ММ-ДД[-суффикс].txt, а внутри дня — из имени
        # самого архива (addfut-ГГГГ-ММ-ДД-ЧЧММСС.tgz). Обе величины неизменяемы.
        _cands = []
        for _a in sorted((ROOT / 'anchors').glob('worm-*.txt')):
            try:
                _txt = _a.read_text(encoding='utf-8')
            except OSError:
                continue
            _nms = sorted(set(_re.findall(r'addfut-[0-9A-Za-z\-]+\.tgz', _txt)))
            if _nms:
                _cands.append((max(_nms), _a.name, _a, _nms))
        if _cands:
            _gen, _nm0, _a, _nms = max(_cands, key=lambda x: (x[0], x[1]))
            for _nm in _nms:
                if (bdir / _nm).exists():
                    continue
                # РАЗРЫВ ОТЛИЧАЕТСЯ ОТ ЧУЖОГО КАТАЛОГА ПО .pending (сорок второй круг,
                # найдено собственной батареей). Первая редакция сверяла боевые якоря с
                # ЛЮБЫМ переданным каталогом копий и отказывала, когда архива там просто
                # нет, — а это ровно случай стенда или другого каталога резервирования:
                # снимок падал на ровном месте. Различимый признак разрыва один: рядом
                # лежит .pending, то есть публикация началась и не завершилась. Нет ни
                # .tgz, ни .pending — сказать нечего, и молчать здесь честнее, чем ронять.
                # ПРЕДЕЛ НАЗВАН: якорь не записывает КАТАЛОГ копий, поэтому «архив утрачен
                # вместе с .pending» неотличимо от «архив в другом каталоге». Закрыть это
                # можно только записью каталога в тело якоря — отдельное решение.
                _pend = bdir / (_nm + '.pending')
                if not _pend.exists():
                    continue
                bad.append(f'{_a.name} (последний якорь): заверен архив {_nm}, которого НЕТ '
                           f'— лежит {_pend.name}, публикация не состоялась')
    except _STce.CODE_ERRORS:
        # ОШИБКА КОДА НЕ ПЕРЕОДЕВАЕТСЯ В ВЕРДИКТ (инцидент 19.08.2026, §12). Именно здесь
        # TypeError от `строка / строка` стал доменным «считать недоказанной»: контур встал
        # с чужим диагнозом, а настоящий не сохранился нигде. Реальные беды (каталог не
        # читается) остаются мягкими — они ниже; ошибка кода обязана падать громко, потому
        # что молчащая проверка снимает вопрос, а падающая его ставит.
        raise
    except Exception as _ex:
        bad.append(f'проверка якорей не выполнена ({_ex}) — считать недоказанной')
    return bad


def snap(day, bdir):
    import state as STm
    bdir = _as_path(bdir)            # argv отдаёт строку (инцидент 19.08.2026, §12)
    # РАЗРЫВ «ЯКОРЬ ЕСТЬ, АРХИВА НЕТ» ОБНАРУЖИВАЕТСЯ ДО НОВОЙ КОПИИ (№13): иначе следующее
    # замыкание тихо накроет его свежим якорем, и ложное заверение останется в истории.
    _orph = anchors_without_archive(bdir)
    if _orph:
        raise RuntimeError('WORM: якорь заверяет отсутствующий архив — прошлое замыкание '
                           'оборвалось между коммитом и публикацией; ручной разбор (О-5):\n  '
                           + '\n  '.join(_orph))
    # ОДИН ЗАХВАТ ЗАМКА КНИГИ (№19): архив и якорь снимаются с ОДНОГО поколения состояния —
    # переход не может заменить книгу и маршрут посреди копии.
    with STm.hold_book_lock():
        body = _anchor_body(day)
        dst = _tar_state(day, bdir)
        # ЗАВЕРЕННОЕ ОБЯЗАНО ЛЕЖАТЬ В ЭТОМ АРХИВЕ (№10, решение заказчика 17.08). Проверяем
        # по СОДЕРЖИМОМУ только что собранного файла: список кладущего и список проверяющего
        # один и тот же (_attested_paths), но факт попадания читается из tar.
        _miss = attested_missing_from_archive(dst)
        if _miss:
            reject_archive(dst)
            raise RuntimeError('WORM: якорь заверял бы файлы, которых в архиве нет — '
                               'резервирование неполно, снимок отвергнут:\n  '
                               + '\n  '.join(_miss))
        # ОДНО ПОКОЛЕНИЕ ДОКАЗЫВАЕТСЯ ПОВТОРНЫМ ХЭШЕМ (девятнадцатый круг, №18): замок
        # книги не держат ни signal_update, ни first_connect — их файлы могли смениться
        # между вычислением тела якоря и попаданием в tar. Совпадение тел до и после
        # архивации гарантирует, что якорь и архив описывают одни и те же байты;
        # расхождение — отказ (следующее замыкание повторит попытку).
        # ИСКЛЮЧЕНИЕ ВТОРОГО ЧТЕНИЯ — ТОЖЕ ОТКАЗ (двадцать пятый круг, №18). Прежде второй
        # _anchor_body стоял ВНЕ защиты: если он не возвращал другой текст, а ПАДАЛ —
        # например, видел оборванный или повреждённый журнал после первого чтения, —
        # архив оставался под рабочим именем addfut-*.tgz, и следующий backup_push мог
        # выгрузить копию, которую сам сниматель не смог аттестовать.
        try:
            body2 = _anchor_body(day)
        except Exception as _ex2:
            _mark2 = reject_archive(dst)
            raise RuntimeError(f'повторное вычисление тела якоря не удалось ({_ex2}) — '
                               f'архив не аттестован; помечен .rejected{_mark2}')
        if body2 != body:
            # ОТВЕРГНУТЫЙ АРХИВ НЕ ОСТАЁТСЯ ПОД РАБОЧИМ ИМЕНЕМ (двадцатый круг, №22).
            # _tar_state публикует addfut-*.tgz ДО повторного вычисления тела; прежде при
            # расхождении поколений исключение поднималось, а файл оставался лежать — и
            # следующий backup_push или ручное восстановление могли взять архив, про
            # который сам код установил, что книга, маршрут, сигнал и реестр сняты из
            # РАЗНЫХ поколений. ALARM его обратно во временный не превращал.
            # Файл не удаляется, а помечается: доказательство инцидента сохраняется, но
            # под именем, которое восстановление не подхватывает.
            _mark = reject_archive(dst)
            raise RuntimeError('файлы состояния изменились во время снимка — якорь и '
                               'архив были бы разных поколений; снимок отклонён, архив '
                               'помечен .rejected' + _mark)
    # ЛЮБОЙ ПРОВАЛ ПОСЛЕ ПУБЛИКАЦИИ АРХИВА ПОМЕЧАЕТ ЕГО (двадцать первый круг, №15).
    # Прежде .rejected ставился ТОЛЬКО при расхождении поколений; если падали запись
    # якоря или git-заверение, addfut-*.tgz оставался под рабочей маской без
    # подтверждённого якоря — и следующий backup_push подхватывал его как обычную копию,
    # то есть в зеркале лежала бы копия, которую никто не заверил.
    # ЯКОРЬ ПРИВЯЗЫВАЕТСЯ К АРХИВУ (двадцать первый круг, №14): без sha256 самого
    # addfut-*.tgz по якорю нельзя проверить КОНКРЕТНУЮ копию после выгрузки в зеркало
    # или восстановления — заверялось состояние, но не то, что из него сделано.
    # ЯКОРЬ НЕСЁТ ИТОГОВОЕ ИМЯ, А НЕ ПРОМЕЖУТОЧНОЕ (тридцать шестой круг, №11): архив
    # публикуется под рабочим именем только после заверения, но заверяется он ДО
    # переименования — значит в тексте обязано стоять то имя, под которым копия и будет
    # лежать. Байты от переименования не меняются, поэтому sha256 остаётся тем же.
    _pub = dst.with_suffix('') if dst.name.endswith('.pending') else dst
    body_full = body + (f'sha256 архива ({_pub.name}): '
                        f'{_sha(dst, required=True)}\n')
    try:
        out = _write_anchor(day, body_full)
        # СВЕРЯЕТСЯ ТО ТЕЛО, КОТОРОЕ ЗАПИСАНО (тридцатый круг, №11). Здесь стояло `body` —
        # тело БЕЗ строки sha256 архива, тогда как в файл уходит body_full. Хэши не могли
        # совпасть НИКОГДА: каждое замыкание помечало бы архив .rejected, поднимало ALARM,
        # не ставило closed-* и останавливало автопилот до ручного разбора. Дефект внесён
        # моей же правкой двадцать девятого круга (№16 двадцать восьмого), когда сверку
        # перевели с файла на диске на проверенное тело — и передали не то тело.
        _git_commit_verified(out, body_full)
    except BaseException as ex:
        _m = reject_archive(dst)
        raise RuntimeError(f'якорь не подтверждён ({ex}) — архив {dst.name} помечен '
                           f'.rejected, заверенной копии за {day} НЕТ{_m}')
    # ЗАВЕРЕНО — ТОЛЬКО ТЕПЕРЬ ПУБЛИКУЕМ (тридцать шестой круг, №11): переименование
    # .tgz.pending -> .tgz атомарно, и каталог fsync'ится, иначе имя может не пережить сбой.
    _final = dst.with_suffix('') if dst.name.endswith('.pending') else dst
    try:
        os.replace(dst, _final)
        _dfd2 = os.open(str(_final.parent), os.O_DIRECTORY)
        try:
            os.fsync(_dfd2)
        finally:
            os.close(_dfd2)
    except OSError as _exp:
        raise RuntimeError(f'якорь подтверждён, но архив не опубликован под рабочим именем '
                           f'({_exp}): заверенной копии за {day} нет — ручной разбор (О-5)')
    print(f'копия: {_final.name}; якорь: {out.name} (в HEAD)')
    return 0


def main(day):
    """Официальный путь создания якоря (двадцать шестой круг, №22).

    Согласованный захват и двойное чтение были ТОЛЬКО в snap(): обычный запуск
    `worm_anchor.py <день>` читал маршрут, книгу, журнал и внешние файлы в разные моменты
    БЕЗ книжного замка и сразу коммитил текст. Переход, случившийся между этими чтениями,
    давал валидный git-якорь из НЕСКОЛЬКИХ поколений состояния — ложное доказательство,
    которое ничем не помечалось. Здесь тот же замок и та же сверка двух чтений: якорь либо
    описывает одно поколение, либо не создаётся вовсе.
    """
    import state as STm
    with STm.hold_book_lock():
        body = _anchor_body(day)
        body2 = _anchor_body(day)
        if body2 != body:
            raise RuntimeError('файлы состояния изменились во время снятия якоря — '
                               'текст описывал бы два поколения; якорь не создан')
        out = _write_anchor(day, body)
        _git_commit_verified(out, body)
    print(f'якорь: {out.name} (в HEAD)')
    return 0


