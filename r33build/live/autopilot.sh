cls = daily.BookE if route == 'E' else daily.Book
b, _, _ = ST.load(ST.book_path(route), cls)
sys.stdout.write('1' if (b is not None and b.last_session == sys.argv[1]) else '0')
BKT
    )" = "1" ]
}
close_after() {
    # Маршрут Е: ворота ДИНАМИЧЕСКИЕ (семнадцатый круг, №5) — из того же feed.e_close_gate,
    # что у замыкателя; фиксированное 1040 в недели рассинхронизации DST давало отказ
    # «рано» и тревогу вместо ожидания. Сбой вычисления — тревога и недостижимое время.
    if [ "$(route)" = E ]; then
        local g
        g=$(cd "$LIVE" && "$PY" -c 'import feed; print(f"{feed.e_close_gate():%H%M}")' 2>/dev/null)
        case "$g" in
            [0-9][0-9][0-9][0-9]) echo "$g"; return;;
        esac
        # ЗАПИСЬ ТРЕВОГИ ПРОВЕРЯЕТСЯ (тридцать четвёртый круг, №10):
        # голый echo при ENOSPC/ACL оставлял ветку без тревоги и без STOP.
        alarm_write "$ST/ALARM-calendar-e.txt" "ворота Е не вычислены (ответ: '$g')" \
            || : > "$ST/autopilot.STOP" 2>/dev/null || true
        (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-calendar-e.txt" >> "$ST/ALARM-calendar-e.txt" 2>&1) || true
        echo 2359
    else
        echo 1605
    fi
}

# Свой замок В САМОМ СКРИПТЕ: строка crontab с flock — внешняя договорённость, её можно
# потерять при правке crontab; повторный вход должен быть невозможен независимо от неё.
# ОТКАЗ ОТКРЫТЬ ЗАМОК — ГРОМКИЙ (двадцатый круг, №12). Прежде здесь стояло `|| true`, и оно
# проглатывало ВСЁ: отсутствующий каталог состояния, права, read-only FS, ENOSPC. Дальше
# `flock -n 9` получал «Bad file descriptor», то есть НЕуспех, скрипт считал замок занятым
# и выходил с кодом 0 — а при отсутствующем сердцебиении даже без тревоги. Контур слеп
# ровно так же, как при декоративном cron (§12, семнадцатый круг): позиция стоит без
# торговли и без ролла вплоть до поставочной зоны.
# ФУНКЦИИ ОПРЕДЕЛЯЮТСЯ ДО ПЕРВОГО ИХ ВЫЗОВА (тридцать седьмой круг, №11). alarm_write и
# log стояли НИЖЕ сторожа занятого замка, а тот их зовёт: bash задним числом
# определения не подхватывает, и при замке старше часа выполнялись «alarm_write:
# command not found» и «log: command not found». То есть многоступенчатая долговечная
# запись тревоги там не работала НИКОГДА — оставалась случайная попытка создать STOP по
# ветке «||» и строка в stderr для cron. Это ровно тот путь, ради которого сторож
# заведён: зависший владелец замка делает контур слепым и пропускает ролл.
alarm_write() {
    # ЗАПИСЬ ТРЕВОГИ ОБЯЗАНА УДАТЬСЯ (двадцать четвёртый круг, №8). Прежде «echo > ALARM»
    # не проверялся и set -e нет: после ENOSPC, ACL «менять можно, создавать нельзя» или
    # ошибки каталога функция просто заканчивала тик. Следующий cron не видел ALARM и снова
    # входил в торговлю — дубль поверх неизвестного исхода. Не удалось записать файл —
    # пробуем запасное имя, затем syslog, и в любом случае возвращаем НЕуспех.
    local f=$1; shift
    if printf '%s\n' "$*" > "$f" 2>/dev/null && [ -s "$f" ]; then
        return 0
    fi
    local alt="${ST}/ALARM-fallback-$$.txt"
    if printf '%s\n' "$*" > "$alt" 2>/dev/null && [ -s "$alt" ]; then
        log "ТРЕВОГА записана в запасной файл $alt (основной $f недоступен)"
        return 0
    fi
    logger -t addfut "КРИТИЧНО: не удалось записать тревогу $f: $*" 2>/dev/null || true
    log "КРИТИЧНО: тревога НЕ записана ни в $f, ни в $alt — контур останавливается"
    # МЕЖПРОЦЕССНЫЙ СТОП (двадцать восьмой круг, №9): return 1 останавливает ТЕКУЩИЙ тик,
    # но следующий cron о нём не знает — файлов-тревог нет, и он снова входит в торговлю.
    if ! : > "$ST/autopilot.STOP" 2>/dev/null; then
        # УДАЛЯТЬ ОТМЕТКИ НЕЛЬЗЯ (двадцать девятый круг, №13). Прежде здесь стоял
        # `rm -f traded-* closed-*` — и это делало ХУЖЕ: день начинал выглядеть
        # НЕотторгованным, и следующий тик торговал бы его ЗАНОВО, поверх уже
        # исполненных заявок. Ровно противоположно замыслу. Если записать нельзя ничего,
        # остаётся только кричать в syslog: разрушать состояние — не выход.
        logger -t addfut "КРИТИЧНО: не удалось поставить autopilot.STOP" 2>/dev/null || true
    fi
    return 1
}

alarm_keep() {
    # ОБЩАЯ ТРЕВОГА НЕ ЗАТИРАЕТ ЧАСТНУЮ (инцидент 19.08.2026, §12). backup_state пишет в
    # ALARM-backup-$day.txt ПРИЧИНУ отказа снимка ($wa) и приписывает разбор diagnose.py, а
    # вызывающий следом писал в ТОТ ЖЕ файл общее «копия не снята» — через `>`, то есть
    # затирал единственное место, где причина вообще существовала: в журнал она не попадает
    # (log зовётся только при успехе). Так и вышло 18.08: контур встал, а почему — в
    # состоянии не осталось, разбор занял час на воспроизведение того, что уже было
    # напечатано и стёрто. Дописываем, а не заменяем; повтор той же строки не копится,
    # иначе тик каждые десять минут раздувал бы файл тревоги.
    # СВЕРКА ПОВТОРА — ПО ПЕРВОЙ СТРОКЕ, А НЕ ПО ВСЕМУ ТЕКСТУ (рецензия 20.08): grep -F с
    # многострочным шаблоном считает совпадением ЛЮБУЮ одну строку, поэтому новая, по сути
    # другая тревога, у которой совпала хоть одна строка, молча отбрасывалась, а вызывающий
    # получал успех. Первая строка сообщения — его опознавательный знак.
    # И ГЛАВНОЕ: ПРИ ОТКАЗЕ ДОПИСЫВАНИЯ НЕЛЬЗЯ ПАДАТЬ В alarm_write (рецензия 20.08). Тот
    # открывает файл через `>`, то есть УСЕЧЕНИЕМ, и на самом вероятном отказе дописывания —
    # ENOSPC, ровно той причине, по которой backup_state и не снял копию, — усечение
    # освобождает блоки и уничтожает причину. Это инцидент 19.08, воспроизведённый внутри
    # правки для него. Причину не трогаем: пишем общее сообщение в СОСЕДНИЙ файл.
    local f=$1; shift
    local _first; _first=$(printf '%s' "$*" | head -1)
    if [ -s "$f" ]; then
        grep -qF -- "$_first" "$f" 2>/dev/null && return 0
        if printf '%s\n' "$*" >> "$f" 2>/dev/null; then
            return 0
        fi
        alarm_write "${f%.txt}-общее.txt" "$*"
        return $?
    fi
    alarm_write "$f" "$*"
}

log() { echo "$(date '+%F %T %Z') | $*" >> "$LOG"; }

# ЧТЕНИЕ СЧЁТЧИКА НЕ ДОВЕРЯЕТ СОДЕРЖИМОМУ (сорок первый круг, №11). Значения счётчиков
# читались ПРЯМО в арифметику: `n=$(( $(cat файл) + 1 ))`. При мусоре в файле (обрыв записи,
# подмена, «x») bash под `set -u` падает с фатальной ошибкой ДО alarm_write и до STOP — тик
# умирает молча, следующие тики умирают так же, и шлюз, копии или вахта О-3-Е остаются
# мёртвыми без единой долговечной тревоги вплоть до поставочной зоны. Проверялась ЗАПИСЬ
# числа, но не будущее ЧТЕНИЕ повреждённого состояния: та же слепота к траектории, что и в
# сороковом круге. Нечисловое содержимое читается как 0 — счётчик начнёт заново, но контур
# останется живым и способным поднять тревогу.
counter_read() {
    local f=$1 v
    v=$(cat "$f" 2>/dev/null || echo 0)
    case "$v" in
        ''|*[!0-9]*) echo 0 ;;
        *)
            # ВОСЬМЕРИЧНАЯ ЛОВУШКА (сорок второй круг, №7): «08» и «09» состоят из цифр и
            # проходили фильтр, но bash разбирает такие литералы как ВОСЬМЕРИЧНЫЕ и падает
            # «value too great for base» — снова фатально, до alarm_write и STOP. Ведущие
            # нули срезаем; пустой остаток означает ноль.
            # ПЕРЕНОСИМО, БЕЗ extglob: скрипт сам выключает расширенные шаблоны, и
            # ${v##+(0)} там не срезает ничего — проверено прогоном, «08» снова падало.
            v=$(printf '%s' "$v" | sed 's/^0*//')
            [ -n "$v" ] || v=0
            echo "$v" ;;
    esac
}


