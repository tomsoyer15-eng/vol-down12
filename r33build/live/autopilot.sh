        # и тут же замыкать — значит оставить рыночные GTC на ночь; вместо этого тревога.
        # ЗАПИСЬ ПРОВЕРЯЕТСЯ (№14, тот же класс): голый echo при ENOSPC/ACL оставлял тик
        # без тревоги, и следующий день начинался как ни в чём не бывало.
        alarm_write "$ST/ALARM-missed-$day.txt" "тики торгового окна $day пропущены (первый после $hm)" \
            || log "КРИТИЧНО: тревога пропущенного окна не записана"
        (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-missed-$day.txt" >> "$ST/ALARM-missed-$day.txt" 2>&1) || true
        log "ТРЕВОГА: торговое окно $day пропущено — сессии не будет"
        return 0
    fi
    # ЗДЕСЬ ФАЙЛ — НАМЕРЕННО, А НЕ НЕДОЧИНЕННАЯ СЕМЬЯ (сорок третий круг, №2, разбор).
    # Всюду, где решается «был ли день отторгован», спрашивается КНИГА (traded_today).
    # Но это ВХОДНЫЕ ворота торговли, и у них противоположная задача: если книга уже
    # несёт сегодняшнюю дату, а отметки нет (смерть между ST.save и touch), войти НУЖНО —
    # чтобы run_trade дошёл до ветки штатного повтора и ВОССТАНОВИЛ отметку. Поставь тут
    # traded_today — и повтор не запустится никогда, маркер не вернётся, а вахта О-3-Е и
    # замыкание останутся без него. Асимметрия названа, чтобы её не «исправили».
    if [ "$hm" -ge "$(trade_from)" ] && [ "$hm" -lt "$(trade_till)" ] && [ ! -e "$ST/traded-$day" ]; then
        ensure_gw || return 0
        # МЕСЯЧНЫЙ СИГНАЛ ПЕРЕД ПЕРВОЙ ТОРГОВЛЕЙ МЕСЯЦА: строка месяца действия обязана
        # существовать до сделки; сбой обновления — тревога, торговли нет.
        local mon; mon=$(chicago %Y-%m)
        if [ ! -e "$ST/sigup-$mon" ]; then
            local sout
            # ФИЛЬТР СНЯТ И ЗДЕСЬ (44-й круг, №14, найдено грепом по семье): тихий
            # успешный прогон обновлятора после фильтра не оставлял ни строки, grep
            # возвращал 1 при pipefail — и обновление сигнала объявлялось отказом.
            if sout=$(cd "$LIVE" && timeout -k 30 300 "$PY" signal_update.py 2>&1); then
                echo "$sout" >> "$LOG"
                if touch "$ST/sigup-$mon" 2>/dev/null && [ -e "$ST/sigup-$mon" ]; then
                    log "сигнал $mon: обновлён/сверен"
                else
                    # ТО ЖЕ ИМЯ МИМО NAMESPACE — И ХУЖЕ (№14): после сбоя отметки код
                    # шёл ДАЛЬШЕ, в run_trade. Торговля продолжалась при повреждённом
                    # состоянии маркеров, а обновлятор сигнала повторялся бы каждым тиком.
                    alarm_write "$ST/ALARM-sigup-marker-$mon.txt" "сигнал $mon обновлён, но отметку sigup-$mon записать НЕ удалось — обновлятор повторялся бы каждым тиком, торговля остановлена" \
                        || : > "$ST/autopilot.STOP" 2>/dev/null || true
                    log "КРИТИЧНО: отметка sigup-$mon не записана — торговли не будет"
                    return 0
                fi
            else
                # ЗАПИСЬ ТРЕВОГИ ПРОВЕРЯЕТСЯ (№14, соседний случай того же класса):
                # голый echo при ENOSPC/ACL оставлял тик без тревоги.
                alarm_write "$ST/ALARM-signal-$mon.txt" "$sout" \
                    || log "КРИТИЧНО: тревога сигнала не записана"
                (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-signal-$mon.txt" >> "$ST/ALARM-signal-$mon.txt" 2>&1) || true
                log "ТРЕВОГА сигнала $mon — торговли не будет до ручного разбора"
                return 0
            fi
        fi
        # ОКНО ПЕРЕПРОВЕРЯЕТСЯ ПОСЛЕ ПОДГОТОВКИ (семнадцатый круг, №13): подъём шлюза и
        # месячный сигнал занимают минуты — заявка, поданная за краем окна, висела бы GTC
        # до чужой сессии. Пропущенное окно поймает штатный механизм ALARM-missed.
        hm=$(chicago %H%M)
        if [ "$hm" -ge "$(trade_till)" ]; then
            log "окно ушло за время подготовки (сейчас $hm) — торговля не начинается"
        else
            run_trade "$day"
        fi
    fi
    # ТРЕВОГА, ПОЯВИВШАЯСЯ В ЭТОМ ЖЕ ТИКЕ, ОСТАНАВЛИВАЕТ ЕГО (тридцать шестой круг, №3).
    # Проверка ALARM-*.txt стояла ТОЛЬКО в начале tick. run_trade может завершиться нулём и
    # ОДНОВРЕМЕННО создать ALARM-o3e-* колбэком изнутри сессии; shell шёл дальше во
    # внутридневную вахту и при LOW запускал второй автоматический срез — под уже
    # действующей тревогой, иногда прямо после сообщения «норматив не достигнут, ручной
    # разбор». Заявление «после ALARM больше не торгуем» было ложным ВНУТРИ процесса.
    # STOP — ВТОРОЙ МЕЖПРОЦЕССНЫЙ БАРЬЕР, И ОН ТОЖЕ ПЕРЕЧИТЫВАЕТСЯ (тридцать седьмой круг,
    # №12). Правка 36-го круга закрыла ровно один из двух: перечитывался ALARM-*.txt, а
    # autopilot.STOP — нет. Но STOP ставится ИМЕННО ТОГДА, когда запись тревоги НЕ УДАЛАСЬ
    # (см. alarm_write): то есть в самом опасном исходе — «тревога есть, файла тревоги нет» —
    # тот же процесс спокойно шёл дальше в вахту О-3-Е и замыкание. Барьер, закрытый
    # наполовину, хуже отсутствующего: он выглядит закрытым.
    if ls "$ST"/ALARM-*.txt >/dev/null 2>&1 || [ -e "$ST/autopilot.STOP" ]; then
        log "тревога или STOP появились в этом тике — новые заявки остановлены до разбора"
        # НО ЗАМЫКАНИЕ ОТТОРГОВАННОГО ДНЯ НЕ ЗАПИРАЕТСЯ (двадцать второй круг, №7): оно не
        # подаёт заявок, а без него книга уходит в ночь без триггера капа §1 и следующая
        # сессия отказывает по «незамкнутой предыдущей». Глухой return 0 отменил бы это
        # правило и создал тупик ровно на опасной книге.
        # ALARM И STOP — РАЗНЫЕ ВЕЩИ, И РАЗЛИЧАТЬ ИХ НАДО ЗДЕСЬ (тридцать девятый круг,
        # №10). В 38-м круге я добавил различение НИЖЕ по тику и объявил вопрос закрытым —
        # а эта ветка делает `return 0`, то есть нижняя проверка НЕДОСТИЖИМА на самом важном
        # пути: STOP, появившийся во время run_trade. Хуже: мой собственный прогон-зонд
        # «доказал» правку, потому что вставлял STOP уже ПОСЛЕ этой ветки — я проверил не то
        # место. Обычная тревога замыкание разрешает (правило 22-го круга, №7); STOP
        # означает, что барьер поставить НЕ УДАЛОСЬ, то есть состояние контура недоказуемо,
        # и заверять его финальной книгой, backup и WORM-якорем нельзя.
        if [ -e "$ST/autopilot.STOP" ]; then
            log "STOP: состояние контура недоказуемо — замыкание НЕ выполняется до разбора"
            return 0
        fi
        if [ "$hm" -ge "$(close_after)" ] && traded_today "$day" && [ ! -e "$ST/closed-$day" ]; then
            log "тревога стоит, но день $day отторгован и не замкнут — выполняю ТОЛЬКО замыкание"
            ensure_gw && run_close "$day"
        fi
        return 0
    fi
    # ВАХТА О-3-Е МЕЖДУ ТОРГОВЛЕЙ И ЗАМЫКАНИЕМ (двадцать второй круг, №6): прежде запас
    # наблюдался ровно один раз — при заявках; после traded-* тики его не смотрели, и
    # провал ниже 1,40 позже в сессии (или на дне без ребаланса) не давал ни тревоги, ни
    # сокращения. Только маршрут Е (О-3-Е — его ворота), только пока день не замкнут.
    # С ТРИДЦАТЬ ПЕРВОГО КРУГА (№1) ВАХТА НЕ ТОЛЬКО СМОТРИТ: при провале запаса она внутри
    # окна выполняет предписанное §8 сокращение до L=1 (session.py --o3e) — это норма, а не
    # самолечение. Тревога ставится в ЛЮБОМ исходе, торговля дальше не идёт: разбор причины
    # по-прежнему за человеком (О-5), и никакое РАСХОЖДЕНИЕ автоматика не чинит.
    # ФАКТ ТОРГОВЛИ — ЧЕРЕЗ traded_today И ЗДЕСЬ (сорок третий круг, №2). Вчера я
    # провёл эту правку в ветку пропущенного окна и остановился: вахта О-3-Е осталась
    # на физическом файле. Связка страшная: после смерти между ST.save и touch, если
    # машина вернулась уже ПОСЛЕ trade_till, run_trade не перезапускается, маркер не
    # восстанавливается, ветка missed считает день отторгованным (она-то книгу
    # спрашивает), а вахта пропускается ЦЕЛИКОМ. Книга Е может остаться около 2x при
    # запасе ниже 1,40 — без среза и даже без тревоги. Семья снова была исправлена
    # наполовину, и именно та половина, что стоит денег.
    if [ "$(route)" = E ] && traded_today "$day" && [ ! -e "$ST/closed-$day" ] \
       && [ ! -e "$ST/ALARM-o3e-blind-$day.txt" ]; then
        local _cw
        _cw=$(o3e_probe 94)
        case "$(verdict "$_cw")" in
            # ПУСТАЯ КНИГА — ЗАКОННОЕ СОСТОЯНИЕ (45-й круг, №6): счётчик слепоты
            # обнуляется, тревоги нет, сокращать нечего. ИМЯ СЧЁТЧИКА — ТО ЖЕ, ЧТО У
            # ВЕТКИ `*)` (разбор /code-review): здесь стояло `: > o3e-intraday-fail-$day`,
            # имя, которого во всём скрипте больше нет, — счётчик слепоты не обнулялся
            # вовсе, последовательность SKIP,SKIP,EMPTY,SKIP по-прежнему давала три и
            # ставила ALARM-o3e-blind, то есть остановку контура, ради снятия которой
            # ветка и заведена; а в $ST каждый день заводился нечитаемый никем файл.
            EMPTY\ *|OK\ *) rm -f "$ST/o3e-watch-fail-$day" ;;   # успех обнуляет счётчик подряд
            LOW\ *)
                rm -f "$ST/o3e-watch-fail-$day"          # замер СОСТОЯЛСЯ (см. o3e_blind_count)
                # НОРМАТИВ §8 ТРЕБУЕТ СОКРАЩЕНИЯ В ТУ ЖЕ СЕССИЮ (тридцать первый круг, №1).
                # Прежде вахта только писала ALARM — и этим же ALARM запирала любой запуск,
                # который мог бы книгу сократить: обнаружение работало, предписанное
                # действие не выполнялось НИКОГДА. Книга уходила в ночь около 2x ровно в
                # тот день, когда запас уже пробит. Сокращение возможно только внутри
                # торгового окна; за его краем заявка висела бы GTC до чужой сессии,
                # поэтому там остаётся честная тревога с прямым указанием, что сокращение
                # НЕ выполнено. Тревога ставится в обоих исходах: О-5 незыблем.
                _cut_note='сокращение НЕ выполнено'
                if [ "$(chicago %H%M)" -lt "$(trade_till)" ]; then
                    # И ЗДЕСЬ ТОЖЕ (44-й круг, №14): ответы шлюза при аварийном срезе —
                    # единственное свидетельство того, что происходило с маржой.
                    _cut_out=$(cd "$LIVE" && timeout -k 60 900 "$PY" session.py --o3e --route E 2>&1)
                    _cut_rc=$?
                    echo "$_cut_out" >> "$LOG"
                    # КОД ВОЗВРАТА НЕ ОТЛИЧАЕТ «СОКРАТИЛ» ОТ «НЕ ПОТРЕБОВАЛОСЬ»
                    # (тридцать второй круг, №10). Между замером LOW и запуском Python
                    # запас может восстановиться: do_o3e_cut печатает «сокращение не
                    # требуется», возвращает None и выходит с нулём — а тревога объявляла
                    # книгу СОКРАЩЁННОЙ. Оператор получал ложное подтверждение L=1 при
                    # книге около 2x. Читаем ФАКТ из вывода, а не из кода возврата.
                    if [ $_cut_rc -eq 0 ] && printf '%s' "$_cut_out" | grep -q 'книга сокращена в ту же сессию'; then
                        _cut_note='книга СОКРАЩЕНА в ту же сессию по §8'
                    elif [ $_cut_rc -eq 0 ]; then
                        _cut_note="сокращение НЕ потребовалось (запас восстановился к моменту запуска): $_cut_out"
                    else
                        _cut_note="сокращение ОТКАЗАНО (код $_cut_rc): $_cut_out"
                    fi
                else
                    _cut_note='окно маршрута Е закрыто — сокращение в эту сессию невозможно'
                fi
                alarm_write "$ST/ALARM-o3e-intraday-$day.txt" "ADDFUT-ПРИЧИНА: O3E-ПРОБИТ
внутридневной запас О-3-Е упал: $_cw (порог 1.40) — О-5; $_cut_note" \
                    || log "КРИТИЧНО: тревога О-3-Е не записана"
                (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-o3e-intraday-$day.txt" >> "$ST/ALARM-o3e-intraday-$day.txt" 2>&1) || true
                log "ТРЕВОГА: внутридневной запас О-3-Е ($_cw) ниже порога — $_cut_note; автопилот остановлен" ;;
            *)  o3e_blind_count "$ST/o3e-watch-fail-$day" "$_cw" "внутридневная" "$day" ;;
        esac
    fi
    # БАРЬЕР ПЕРЕЧИТЫВАЕТСЯ ПЕРЕД ПОСЛЕДНЕЙ ИЗМЕНЯЮЩЕЙ ОПЕРАЦИЕЙ ТИКА (тридцать восьмой
    # круг, №9). В 37-м круге я добавил повторную проверку ALARM/STOP ПОСЛЕ run_trade и счёл
    # вопрос закрытым. Но между нею и замыканием стоит вахта О-3-Е, и она САМА способна
    # поставить STOP: при отказе тревоги, при незаписавшемся счётчике слепоты, изнутри
    # session.py --o3e. Для маршрута Е это реальный путь после 10:35. Замыкание — операция
    # ИЗМЕНЯЮЩАЯ: оно фиксирует плечо закрытия (триггер капа §1 следующей сессии), снимает
    # backup и WORM-якорь. Под STOP оно происходить не должно.
    # ЗАМЫКАНИЕ ПРИ ОБЫЧНОЙ ТРЕВОГЕ по-прежнему РАЗРЕШЕНО (правило 22-го круга, №7): без
    # него книга уходит в ночь без триггера капа, и следующая сессия отказывает. Запрещает
    # его именно STOP — признак того, что барьер поставить НЕ УДАЛОСЬ, то есть состояние
    # контура недоказуемо.
    if [ -e "$ST/autopilot.STOP" ]; then
        log "STOP появился в этом тике — замыкание не выполняется до ручного разбора"
    elif [ "$hm" -ge "$(close_after)" ] && traded_today "$day" && [ ! -e "$ST/closed-$day" ]; then
        ensure_gw && run_close "$day"
    fi
    # УБОРКА ПО ДАТЕ В ИМЕНИ, А НЕ ПО ВРЕМЕНИ ФАЙЛА (найдено саморецензией 42-го круга,
    # угол «от семьи»). Отметки traded-/closed- удалялись по -mtime, то есть по
    # ИЗМЕНЯЕМОЙ величине — тот же класс, что ротация архивов и выбор последнего якоря,
    # только в третьем месте и никем не названный. Восстановление каталога состояния из
    # копии с сохранением времён, перенос на другую машину или скачок часов делают
    # СВЕЖУЮ отметку «старой», и уборка сносит её. Для traded-$day это барьер повторной
    # торговли дня; спасает только второй путь traded_today (чтение книги), то есть
    # защита остаётся одноногой там, где задумана двойной.
    # Дата стоит В ИМЕНИ (traded-ГГГГ-ММ-ДД) и неизменяема — по ней и убираем.
    _cut_day=$(date -d "$(chicago %F) -14 days" +%Y-%m-%d 2>/dev/null || echo '')
    if [ -n "$_cut_day" ]; then
        for _mk in "$ST"/traded-* "$ST"/closed-*; do
            [ -e "$_mk" ] || continue
            # ДАТА БЕРЁТСЯ ПО ПЕРВОМУ ДЕФИСУ, А НЕ ПО ПОСЛЕДНЕМУ «-2» (27.08.2026,
            # находка №12 сплошного аудита). Здесь стояло `${_mk##*-2}`, то есть срез по
            # САМОМУ ДЛИННОМУ префиксу, кончающемуся на «-2». Для traded-2026-08-27 это
            # срезало всё до «-2» перед семёркой и оставляло «27»; шаблон даты такое не
            # принимал, и уборщик молча пропускал КАЖДУЮ отметку с днём 20-29 — треть
            # входа. Измерено: 2026-08-27, 2026-12-25, 2026-11-20 пропускались,
            # 2026-08-15 и 2026-08-03 разбирались. Отметки этих дней копились бы вечно,
            # а уборщик при этом не сообщал НИЧЕГО — он не падал, он просто не работал.
            # Имя устроено как «traded-ГГГГ-ММ-ДД» либо «closed-ГГГГ-ММ-ДД», поэтому
            # правильный срез — до ПЕРВОГО дефиса, и он одинаков для обоих префиксов.
            _base=${_mk##*/}; _d=${_base#*-}            # хвост ГГГГ-ММ-ДД из имени
            case "$_d" in
                [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
                *) continue ;;                          # чужое имя не трогаем
            esac
            if [ "$_d" \< "$_cut_day" ]; then unlink "$_mk" 2>/dev/null || true; fi
        done
    fi
    # АРХИВ НАМЕРЕНИЙ (двадцатый круг, №16): снятое намерение не удаляется, а
    # переименовывается — оно единственное говорит, что НАМЕЧАЛОСЬ. Хранится две недели,
    # как отметки торговли: дольше оно не нужно, а расти без предела не должно.
    # МАСКА ПО РЕАЛЬНОМУ ИМЕНИ (двадцать первый круг, №17): файл называется
    # book-F.json.intent-done-<ts>.json, и прежняя маска 'intent-*-done-*' не совпадала
    # с ним НИКОГДА — уборка была декоративной, архив рос без предела.
    # ТО ЖЕ ДЛЯ АРХИВА НАМЕРЕНИЙ: имя несёт epoch (intent-done-<секунды>), величину
    # неизменяемую, — сравниваем её, а не время файла.
    _cut_ep=$(( $(date +%s) - 14*86400 ))
    for _it in "$ST"/*intent-done-*; do
        [ -e "$_it" ] || continue
        # СУФФИКС УНИКАЛЬНОСТИ НЕ ДЕЛАЕТ ФАЙЛ ВЕЧНЫМ (сорок третий круг, №11). clear_intent
        # НАРОЧНО создаёт intent-done-<epoch>-1.json, когда два снятия попали в одну секунду.
        # Мой уборщик извлекал «epoch-1», требовал только цифры и делал continue — то есть
        # ровно те файлы, ради которых введена уникализация, выпадали из двухнедельной
        # уборки НАВСЕГДА. При повторениях каталог состояния растёт до ENOSPC, а тогда
        # перестают писаться намерение, книга, отметки и ТРЕВОГИ. Берём epoch до первого
        # дефиса: он и есть время снятия.
        _ep=${_it##*intent-done-}; _ep=${_ep%%.*}; _ep=${_ep%%-*}
        case "$_ep" in
            ''|*[!0-9]*) continue ;;
        esac
        if [ "$_ep" -lt "$_cut_ep" ]; then unlink "$_it" 2>/dev/null || true; fi
    done
}

backup_state() {
    # РЕЗЕРВНАЯ КОПИЯ МАШИННОГО СОСТОЯНИЯ после каждого замыкания: книга, журнал §7, живой
    # ряд сигналов и уровни. СЕКРЕТЫ (ibgw.env) НЕ КОПИРУЮТСЯ. Храним 30 последних.
    # УНИКАЛЬНОЕ ИМЯ И АТОМАРНАЯ ПУБЛИКАЦИЯ (тринадцатый круг, №10): повторное событие
    # той же даты (замыкание после перехода) не затирает предыдущий снимок, падение tar не
    # оставляет усечённый архив под рабочим именем.
    local day=$1 bdir=$HOME/.addfut-backups stamp
    stamp=$(date -u +%H%M%S)
    mkdir -p "$bdir"
    # СОГЛАСОВАННЫЙ СНИМОК ПОД ЗАМКОМ КНИГИ (восемнадцатый круг, №19) + WORM-якорь того же
    # поколения (№18: state.load, действующие пути, атомарная запись, git с проверкой).
    if wa=$(cd "$LIVE" && "$PY" worm_anchor.py --snap "$day" "$bdir" 2>&1); then
        log "снимок+WORM: $wa"
        # ВНЕШНЯЯ ВЫГРУЗКА ПОД ПРОВЕРКОЙ (пятнадцатый круг, №7): разовый сбой сети — не
        # тревога (локальная копия есть, догонит следующим замыканием), но три подряд
        # означают, что внешних копий давно нет, — стоим до ручного разбора.
        if timeout -k 30 180 /bin/bash /home/alex/claude-projects/vol-down12/tools/backup_push.sh >>"$LOG" 2>&1; then
            rm -f "$ST/push-fails"
        else
            local pf=0
            # ЧЕРЕЗ counter_read, КАК И ОСТАЛЬНЫЕ (сорок второй круг, №7): «все счётчики
            # читаются через counter_read» было неверно — этот остался прямым, и мусор в
            # файле убивал shell до тревоги и до closed-$day.
            [ -f "$ST/push-fails" ] && pf=$(counter_read "$ST/push-fails")
            pf=$((pf + 1))
            # СЧЁТЧИК ОБЯЗАН ЗАПИСАТЬСЯ (тридцать четвёртый круг, №10): иначе порог трёх
            # отказов подряд недостижим, и отсутствие внешних копий не станет тревогой.
            if ! echo "$pf" > "$ST/push-fails" || [ ! -s "$ST/push-fails" ]; then
                alarm_write "$ST/ALARM-push.txt" "счётчик неудачных выгрузок не записывается — порог недостижим (О-5)" \
                    || : > "$ST/autopilot.STOP" 2>/dev/null || true
            fi
            log "внешняя выгрузка копий не удалась ($pf подряд)"
            if [ "$pf" -ge 3 ]; then
                # ЗАПИСЬ ТРЕВОГИ ПРОВЕРЯЕТСЯ (тридцать четвёртый круг, №10):
                # голый echo при ENOSPC/ACL оставлял ветку без тревоги и без STOP.
                alarm_write "$ST/ALARM-push.txt" "backup_push.sh не удаётся $pf замыканий подряд — внешних копий нет" \
                    || : > "$ST/autopilot.STOP" 2>/dev/null || true
                (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-push.txt" >> "$ST/ALARM-push.txt" 2>&1) || true
                log "ТРЕВОГА: внешние копии не выгружаются — автопилот остановлен"
                return 1
            fi
        fi
    else
        # ЗАПИСЬ ТРЕВОГИ ПРОВЕРЯЕТСЯ (тридцать четвёртый круг, №10):
        # голый echo при ENOSPC/ACL оставлял ветку без тревоги и без STOP.
        alarm_write "$ST/ALARM-backup-$day.txt" "снимок состояния/WORM за $day не создан: $wa" \
            || : > "$ST/autopilot.STOP" 2>/dev/null || true
        (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-backup-$day.txt" >> "$ST/ALARM-backup-$day.txt" 2>&1) || true
        log "ТРЕВОГА: резервная копия $day не создана — автопилот остановлен"
        return 1
    fi
    # РОТАЦИЯ ПО ПОКОЛЕНИЮ, А НЕ ПО ВРЕМЕНИ ФАЙЛА (сорок второй круг, №9). Здесь стояла
    # сортировка `ls -1t`, то есть по mtime — величине ИЗМЕНЯЕМОЙ: touch, checkout,
    # восстановление каталога или копирование с сохранением времени переставляют порядок,
    # и уборка способна снести ФАКТИЧЕСКИ последнее поколение, оставив старое. Тот же
    # класс, что «последний якорь по mtime» в 41-м круге: я починил соседний файл и не
    # тронул этот — семья снова исправлена наполовину. Имя addfut-ГГГГ-ММ-ДД-ЧЧММСС
    # лексикографически совпадает с хронологией и неизменяемо: сортируем по нему.
    ls -1 "$bdir"/addfut-*.tgz 2>/dev/null | sort -r | tail -n +61 | xargs -r rm -f
}

status() {
    local day; day=$(chicago %F)
    echo "Чикаго: $(chicago '%F %H:%M %Z'); торговый день: $(is_trade_day && echo да || echo нет)"
    echo "сегодня: торговля $( traded_today "$day" && echo сделана || echo нет ), \
замыкание $( [ -e "$ST/closed-$day" ] && echo сделано || echo нет )"
    [ -e "$ST/autopilot.STOP" ] && echo "СТОП-ФАЙЛ: $ST/autopilot.STOP (тревогу записать не удалось)"
    ls "$ST"/ALARM-*.txt 2>/dev/null && echo "^^^ ТРЕВОГА: автопилот стоит" \
        || { [ -e "$ST/autopilot.STOP" ] && echo "^^^ автопилот стоит по СТОП-файлу" || echo "тревог нет"; }
    tail -5 "$LOG" 2>/dev/null
}

guard_manual() {
    # РУЧНОЙ ВХОД ЧИТАЕТ СТОП-ФАЙЛ (двадцать девятый круг, №11). STOP ставится именно тогда,
    # когда ALARM записать НЕ удалось — то есть в самом тяжёлом состоянии, а ручные команды
    # его не смотрели и спокойно торговали. Он же не показывался в status/diagnose, и
    # оператор видел «тревог нет».
    [ -e "$ST/autopilot.STOP" ] && { echo "стоит СТОП-ФАЙЛ $ST/autopilot.STOP — сначала разбор"; return 1; }
    # РУЧНОЙ ВХОД ПРОХОДИТ ТЕ ЖЕ ВОРОТА (четырнадцатый круг, №10): вызов trade в 15:00 по
    # маршруту Е отправил бы GTC на закрытую Европу, а без sigup — торговлю без сигнала.
    ls "$ST"/ALARM-*.txt >/dev/null 2>&1 && { echo "стоит ТРЕВОГА — сначала разбор"; return 1; }
    is_trade_day; [ $? -eq 0 ] || { echo "не торговый день маршрута $(route)"; return 1; }
    return 0
}

case "${1:-tick}" in
    tick)   env_guard && tick ;;
    trade)
        env_guard || exit 1
        guard_manual || exit 1
        hm=$(chicago %H%M); day=$(chicago %F)
        { [ "$hm" -ge "$(trade_from)" ] && [ "$hm" -lt "$(trade_till)" ]; } \
            || { echo "вне торгового окна маршрута $(route)"; exit 1; }
        mon=$(chicago %Y-%m)
        [ -e "$ST/sigup-$mon" ] || { echo "сигнал месяца не обновлён (sigup-$mon)"; exit 1; }
        ensure_gw && run_trade "$day" ;;
    close)
        env_guard || exit 1
        # ЗАМЫКАНИЕ ОТТОРГОВАННОГО ДНЯ РАЗРЕШЕНО И ПОД ТРЕВОГОЙ (двадцать второй круг,
        # №7): guard_manual запрещал close после тревоги О-3-Е, и книга с исполненными
        # заявками не могла зафиксировать триггер капа — тупик на самой опасной книге.
        # Замыкание заявок не подаёт; торговый вход по-прежнему под полным guard_manual.
        day=$(chicago %F)
        # СТОП-ФАЙЛ ЧИТАЕТСЯ ПЕРВЫМ И ЗДЕСЬ (тридцать третий круг, №9). guard_manual его
        # проверяет, но при существующем ALARM ветка close guard_manual не звала вовсе — то
        # есть STOP обходился ровно тогда, когда он и ставится: прошлую критическую тревогу
        # записать НЕ удалось, исход неизвестен. tick STOP-ом запрещает и торговлю, и
        # замыкание; ручной вход обязан вести себя так же, иначе close финализирует книгу и
        # снимет backup/WORM с состояния, которое может быть устаревшим.
        if [ -e "$ST/autopilot.STOP" ]; then
            echo "стоит СТОП-ФАЙЛ $ST/autopilot.STOP — замыкание запрещено до разбора"; exit 1
        fi
        if ls "$ST"/ALARM-*.txt >/dev/null 2>&1; then
            if traded_today "$day" && [ ! -e "$ST/closed-$day" ]; then
                echo "тревога стоит, но день $day отторгован и не замкнут — замыкаю (только запись цен/NLV)"
            else
                echo "стоит ТРЕВОГА — сначала разбор"; exit 1
            fi
        else
            guard_manual || exit 1
        fi
        hm=$(chicago %H%M)
        [ "$hm" -ge "$(close_after)" ] || { echo "до окна замыкания маршрута $(route)"; exit 1; }
        ensure_gw && run_close "$day" ;;
    diagnose)
        found=0
        for f in "$ST"/ALARM-*.txt; do
            [ -e "$f" ] || continue
            found=1
            echo "=== $f ==="
            (cd "$LIVE" && "$PY" diagnose.py "$f") || true
        done
        # СТОП-ФАЙЛ ВИДЕН ДИАГНОСТУ (тридцать первый круг, №15). STOP ставится ИМЕННО
        # тогда, когда ALARM записать не удалось, то есть в самом тяжёлом состоянии — а
        # diagnose перебирал только ALARM-*.txt и объявлял контур здоровым. Оператор не
        # замечал, что ни ребаланса, ни ролла нет, вплоть до поставочной зоны.
        if [ -e "$ST/autopilot.STOP" ]; then
            found=1
            echo "=== $ST/autopilot.STOP ==="
            cat "$ST/autopilot.STOP" 2>/dev/null || echo "(пусто)"
            (cd "$LIVE" && "$PY" diagnose.py "$ST/autopilot.STOP") || true
        fi
        [ "$found" = 1 ] || echo "тревог нет"
        ;;
    status) status ;;
    *) echo "команды: tick|trade|close|status"; exit 1 ;;
esac
