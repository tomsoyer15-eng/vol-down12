ensure_gw() {
    # СНОВА ТОТ ЖЕ EXEC (тридцать восьмой круг, №10). В 37-м круге я починил ТОЛЬКО
    # строку открытия fd 9 и объявил дефект устранённым, а здесь и ниже остались такие
    # же `exec ... 2>/dev/null`: `exec` без команды применяет перенаправление к самой
    # оболочке НАВСЕГДА, поэтому на КАЖДОМ здоровом вызове ensure_gw весь последующий
    # stderr тика снова исчезал — ни bash-сбоя, ни «command not found» в письме cron.
    # Проба порта не обязана быть `exec`: делаем её в подоболочке, где перенаправление
    # умирает вместе с ней.
    if ( exec 3<>/dev/tcp/127.0.0.1/4002 ) 2>/dev/null; then
        # закрывать нечего: сокет жил и умер в подоболочке (см. выше про exec)
        # ПОРТ — ТОЛЬКО ПОВОД ПОЖАТЬ РУКУ (одиннадцатый круг, №7): полуживой шлюз с
        # открытым сокетом прежде допускался к торговле в обход заявленной проверки API.
        if "$PY" - <<'HS0'
