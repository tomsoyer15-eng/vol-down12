        # неудачной записи он всё равно делал exit 0. При ACL «существующий замок открывать
        # можно, новый ALARM создавать нельзя» каждый cron выглядел успешным, а ни ребаланса,
        # ни ролла не было — и status показывал «тревог нет».
        alarm_write "$ST/ALARM-lock.txt" "замок занят, $why; владелец замка (fuser): $(fuser -v "$ST/autopilot.lock" 2>&1 | tail -3)" \
            || : > "$ST/autopilot.STOP" 2>/dev/null || true
        (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-lock.txt" >> "$ST/ALARM-lock.txt" 2>&1) || true
        echo "$(date '+%F %T %Z') | ТРЕВОГА: замок автопилота завис (${age}с)" >> "$LOG"
