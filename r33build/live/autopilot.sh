verdict() {
    # ВЕРДИКТ ИЗВЛЕКАЕТСЯ ПО МЕТКЕ, А НЕ «ВЕСЬ ОТВЕТ НАЧИНАЕТСЯ С LOW» (45-й круг, №1, P0).
    # Пробы запускаются с 2>&1 — и правильно: ответы шлюза нужны в журнале (урок 18.08, где
    # разгадка пустого whatIf лежала в строке класса 10349). Но ib_insync пишет туда же свои
    # диагностические строки («Error 2104 … farm connection is OK»), и они встают ПЕРЕД
    # маркером. Тогда `case` по началу строки уходил в `*)`: замер прочитан, запас LOW, а
    # предписанный §8 срез В ТУ ЖЕ СЕССИЮ не запускался — только счётчик слепоты, тревога
    # через три тика, и сокращение уже пропущено. Метка снимает двусмысленность целиком:
    # ищем ПОСЛЕДНЮЮ строку с меткой, всё прочее — шум для журнала.
    # ПЕРВАЯ МЕТКА В СТРОКЕ, А НЕ ПОСЛЕДНЯЯ (разбор /code-review 45-го круга). `sed
    # 's/.*ADDFUT-VERDICT //'` жаден: из строки `SKIP OSError("ADDFUT-VERDICT OK 9.9")`
    # он выдавал `OK 9.9")`, и ветка `OK\ *)` объявляла счёт здоровым, стирая счётчик
    # слепоты, — отказ замера превращался в успех ЧУЖИМ ТЕКСТОМ внутри repr исключения.
    # awk match() берёт ПЕРВОЕ вхождение, поэтому подделать вердикт содержимым нельзя;
    # правило «последняя СТРОКА с меткой побеждает» сохранено. Заодно один процесс
    # вместо трёх.
    # ПУСТОЙ ХВОСТ НЕ СТИРАЕТ УЖЕ ПРОЧИТАННЫЙ ВЕРДИКТ (разбор /code-review 21.08).
    # Проба печатает маркер БЕЗ завершающего перевода строки, а stderr свёрнут в тот же
    # поток: строка ib_insync, легшая после маркера и сама содержащая метку с пустым
    # хвостом, обнуляла v — успешный замер превращался в «метки нет», то есть в счётчик
    # слепоты и тревогу через три тика. Правило прежнее: побеждает последняя строка с
    # меткой, но только если она что-то СООБЩАЕТ.
    printf '%s\n' "$1" | awk 'match($0, /ADDFUT-VERDICT /) { r = substr($0, RSTART + RLENGTH); if (r != "") v = r } END { if (v != "") print v }'
}

o3e_blind_count() {
    # СЧЁТ СЛЕПОТЫ ВАХТЫ — ОДНОЙ ФУНКЦИЕЙ НА ВСЕ ТРИ ВАХТЫ (разбор /code-review 21.08).
    # Реакция на неудачный замер жила тремя копиями по семнадцать строк, различаясь лишь
    # именем файла-счётчика и словами в журнале. Этот круг уже дважды чинил их поодиночке
    # (ветка EMPTY обнуляла имя, которого в скрипте нет; праздничная вахта на успехе не
    # обнуляла счётчик вовсе) — то есть класс дефекта воспроизводится копированием.
    # $1 — файл счётчика, $2 — сырой ответ пробы, $3 — как назвать вахту в тревоге,
    # $4 — дата дня. ДАТА ПЕРЕДАЁТСЯ ЯВНО, а не берётся из области видимости вызывающего:
    # помощник обязан работать одинаково из любой вахты, а не полагаться на то, что рядом
    # оказалась переменная с нужным именем (и под `set -u` падать, если не оказалась).
    local _f="$1" _ans="$2" _lbl="$3" _day="$4" _n
    _n=$(( $(counter_read "$_f") + 1 ))
    # СЧЁТЧИК ОБЯЗАН ЗАПИСАТЬСЯ (тридцать второй круг, №15): при недоступном файле каждый
    # тик снова считал 1, порог трёх отказов был недостижим, и маржинальная книга Е
    # оставалась без наблюдения сколь угодно долго.
    if ! echo "$_n" > "$_f" || [ ! -s "$_f" ]; then
        alarm_write "$ST/ALARM-o3e-blind-$_day.txt" \
