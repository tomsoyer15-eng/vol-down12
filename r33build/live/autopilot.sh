hb_write() {
    # СЕРДЦЕБИЕНИЕ ПИШЕТСЯ АТОМАРНО (СОРОК ЧЕТВЁРТЫЙ КРУГ, №12). Прежде оно писалось как
    # `date +%s > файл`: усечение и запись — два шага, и читатель мог законно застать файл
    # ПУСТЫМ. Пока пустое содержимое молча уводило сторожа на mtime, это было незаметно;
    # как только чтение стало строгим, незаметное стало ложной тревогой. Поэтому строгость
    # и атомарность вводятся ПАРОЙ: сперва писатель перестаёт мигать пустотой, и только
    # тогда читатель вправе считать пустоту поломкой.
    # ИМЯ ВРЕМЕННОГО — ПОСТОЯННОЕ, А НЕ С PID (рецензия 20.08). `$f.tmp.$$` — файл, которого
    # нет в белом списке selfcheck (_DISPATCH сверяет ТОЧНЫЕ имена): тик, попавший внутрь
    # часового прогона, ронял проверку «стенды не тронули машинное состояние» и БЛОКИРОВАЛ
    # выпуск, а убитый между записью и mv тик оставлял сироту навсегда. Тики сериализованы
    # общим flock, поэтому постоянное имя безопасно, а список исключений закрывает его раз и
    # навсегда. Сироту прошлого убитого тика перезаписываем, а не накапливаем.
    local f=$1 tmp
    tmp="$f.tmp"
    if date +%s > "$tmp" 2>/dev/null && mv -f "$tmp" "$f" 2>/dev/null; then
        return 0
    fi
    unlink "$tmp" 2>/dev/null || true
    return 1
}

hb_age() {
    # ВОЗРАСТ ОТМЕТКИ — ТОЛЬКО ПО СОДЕРЖИМОМУ (СОРОК ЧЕТВЁРТЫЙ КРУГ, №12). Здесь стоял
    # откат на `stat -c %Y` при пустом или нечисловом файле — то есть ровно на изменяемую
    # величину, ради ухода от которой правка и делалась: touch, восстановление каталога из
    # копии или перенос на другую машину делали ЗАВИСШЕЕ сердцебиение «свежим», сторож
    # молчал, контур оставался слеп, ролл пропускался. Семья «порядок по изменяемой
    # величине» была объявлена закрытой трижды и трижды оказывалась незакрытой — на этот
    # раз запасного пути НЕТ вовсе: непрочитанная отметка это поломка, а не ноль.
    # МЕТКА ИЗ БУДУЩЕГО — ТОЖЕ ПОЛОМКА (тот же №12): прежде отрицательный возраст
    # принудительно обнулялся, и тревога не могла возникнуть до наступления записанного
    # времени — сторож выключался ровно тем, от чего сторожит.
    # Печатает возраст в секундах и возвращает 0; иначе печатает причину и возвращает 1.
    local f=$1 now v
    now=$(date +%s)
    v=$(counter_read "$f")
    if [ "$v" = 0 ]; then
        echo "НЕЧИТАЕМО"
        return 1
    fi
    # ДЛИНА ЧИСЛА ПРОВЕРЯЕТСЯ ДО АРИФМЕТИКИ (рецензия 20.08). counter_read пропускает любую
    # строку из цифр, а сравнение `[ "$v" -gt … ]` на двадцатизначном числе ПАДАЕТ («integer
    # expression expected») — и падение здесь же заглушено `2>/dev/null`, поэтому ветка
    # «БУДУЩЕЕ» просто пропускалась. Дальше `$(( now - v ))` заворачивало значение в
    # огромное ОТРИЦАТЕЛЬНОЕ, оно возвращалось как штатный возраст с rc=0, и сравнение с
    # порогом было ложным ВСЕГДА: сторож зависшего замка выключался ровно тем состоянием,
    # от которого сторожит. Epoch не бывает длиннее десяти знаков ещё двести лет.
    if [ "${#v}" -gt 11 ]; then
        echo "ВНЕ-ДИАПАЗОНА"
        return 1
    fi
    if [ "$v" -gt "$now" ]; then
        echo "БУДУЩЕЕ"
        return 1
    fi
    echo $(( now - v ))
    return 0
}


