        # epoch лежит ВНУТРИ файла, а читался он через stat -c %Y — через изменяемую метку.
        # Восстановление каталога состояния из копии, перенос на другую машину или touch
        # делают зависшее сердцебиение «свежим»: сторож замка молчит, контур слеп, ролл
        # пропущен. Это то же семейство «порядок по изменяемой величине», которое я объявил
