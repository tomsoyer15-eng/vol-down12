        alarm_write "$ST/ALARM-trade-$day.txt" "$out" || {
            # ОТКАЗ ЗАПИСИ ТРЕВОГИ — ОТКАЗ КОНТУРА (двадцать пятый круг, №11). Я сам
            # обесценил защиту припиской "|| true": файл не появлялся, тик заканчивался
            # нулём, следующий cron снова торговал поверх неизвестного исхода.
            # ОТМЕТКА ДНЯ НЕ СНИМАЕТСЯ (тридцатый круг, №14). Прежде здесь стояло
            # rm -f traded-$day: но к этому моменту книга и брокер УЖЕ относятся к
            # сегодняшней сессии. Снятая отметка означает, что день нельзя замкнуть
            # (замыкание под тревогой требует маркер), а следующий тик снова входит в
            # торговый путь. Уничтожать доказательство состоявшейся сессии, чтобы
            # обозначить сбой ЗАПИСИ тревоги, — лечить симптом порчей состояния.
            # Межпроцессный барьер — это STOP-файл, он и ставится.
            log "КРИТИЧНО: тревога не записана — ставлю STOP, отметка дня сохранена"
            : > "$ST/autopilot.STOP" 2>/dev/null || log "КРИТИЧНО: и STOP не записан"
            return 1
        }
        (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-trade-$day.txt" >> "$ST/ALARM-trade-$day.txt" 2>&1) || true
        log "ТРЕВОГА торговли $day (код $rc) — автопилот остановлен до ручного разбора"
        return 1
    fi
}

run_close() {
    local day=$1 out rc
    # ТО ЖЕ И ПРИ ЗАМЫКАНИИ (44-й круг, №14): ответы шлюза сохраняются целиком, код
    # возврата — питона, а не grep.
    out=$(cd "$LIVE" && timeout -k 30 400 "$PY" session.py --close --route "$(route)" 2>&1); rc=$?
    echo "$out" >> "$LOG"
    _closed_ok=0
    # ПРИЧИНА ОТКАЗА ЧИТАЕТСЯ И ЗДЕСЬ (двадцать четвёртый круг, №6): «книга уже замкнута»
    # объявляло успехом ЛЮБОЙ ненулевой код, включая поздний fill, расхождение с брокером
    # и открытую заявку — плечо закрытия оставалось посчитанным по ложной книге, ставился
    # closed-$day, тревоги не было.
    # ПОЛОЖИТЕЛЬНЫЙ ПРИЗНАК, А НЕ ЧЁРНЫЙ СПИСОК (двадцать восьмой круг, №10). Перечень
    # запрещённых слов не может быть полным: любая НОВАЯ формулировка отказа автоматически
    # объявляла бы замыкание штатным повтором. Требуем, чтобы сессия САМА назвала причину —
    # «уже замкнута»; всё прочее идёт веткой тревоги.
    if [ $rc -ne 0 ] \
       && printf '%s' "$out" | grep -qE 'уже замкнута'; then
        (cd "$LIVE" && "$PY" - "$day" <<'BK2' >/dev/null 2>&1
import sys
from pathlib import Path
import daily, state as ST
rt = Path.home() / '.addfut' / 'route.txt'
route = rt.read_text().strip() if rt.exists() else 'F'
cls = daily.BookE if route == 'E' else daily.Book
b, _, _ = ST.load(ST.book_path(route), cls)   # digest + ДАТА: чужой день не «уже замкнут»
sys.exit(0 if (b is not None and b.last_session == sys.argv[1]
               and b.close_provisional is False) else 1)
BK2
        ) && _closed_ok=1
    fi
    if [ $rc -eq 0 ] || [ "$_closed_ok" = 1 ]; then
        # РЕЗЕРВНАЯ КОПИЯ РАНЬШЕ ОТМЕТКИ (двадцать седьмой круг, №23): closed-$day
        # объявляет день завершённым, и следующий тик на него опирается. Если backup_state
        # падал ПОСЛЕ отметки, день считался закрытым без копии состояния — восстановление
        # после аварии теряло бы именно замкнутую книгу.
        if backup_state "$day"; then
            # МАРКЕР ПРОВЕРЯЕТСЯ (тридцатый круг, №20). Непроверенный touch при ACL или
            # ENOSPC давал журнал «ок» без диспетчерского состояния: замыкание и WORM
            # повторялись бы каждым тиком, накапливая архивы и коммиты.
            if touch "$ST/closed-$day" 2>/dev/null && [ -e "$ST/closed-$day" ]; then
                log "замыкание $day: ок (копия состояния снята)"
            else
                # ИМЯ ТРЕВОГИ — В КАТАЛОГЕ СОСТОЯНИЯ И ПО ШАБЛОНУ ГЛОБА (тридцать первый
                # круг, №14). Здесь стояло относительное "close-marker-$day": файл ложился
                # в текущий каталог, alarm_write возвращал УСПЕХ, а glob $ST/ALARM-*.txt
                # его не видел никогда — оператор получал «тревог нет» при повреждённом
                # состоянии маркеров.
                alarm_write "$ST/ALARM-close-marker-$day.txt" "замыкание $day прошло, но отметку closed-$day записать НЕ удалось — следующий тик повторил бы замыкание и WORM" \
                    || log "КРИТИЧНО: тревога маркера замыкания не записана"
                : > "$ST/autopilot.STOP" 2>/dev/null || true
                log "КРИТИЧНО: отметка closed-$day не записана"
                return 1
            fi
        else
            alarm_keep "$ST/ALARM-backup-$day.txt" \
                "замыкание $day прошло, но резервная копия состояния НЕ снята — отметка
closed-$day не ставится (О-5)" || log "КРИТИЧНО: тревога копии не записана"
            log "ТРЕВОГА: копия состояния не снята — день не отмечен закрытым"
            return 1
        fi
    else
        alarm_write "$ST/ALARM-close-$day.txt" "$out" || {
            log "КРИТИЧНО: тревога замыкания не записана — контур останавливается"
            return 1
        }
        (cd "$LIVE" && "$PY" diagnose.py "$ST/ALARM-close-$day.txt" >> "$ST/ALARM-close-$day.txt" 2>&1) || true
        log "ТРЕВОГА замыкания $day (код $rc)"
        return 1
    fi
}

tick() {
    local day hm
    day=$(chicago %F); hm=$(chicago %H%M)
    # ТРЕВОГА ОСТАНАВЛИВАЕТ ТОРГОВЛЮ, НО НЕ ЗАМЫКАНИЕ ОТТОРГОВАННОГО ДНЯ (двадцать
    # второй круг, №7). Прежний полный стоп создавал тупик ровно на опасной книге: тревога
    # О-3-Е ставится ПОСЛЕ исполненных заявок, отметка traded уже стоит — и замыкание
    # запрещалось той же строкой; назавтра do_close отказывал по чужой дате книги, и книга
    # с низким запасом застревала close_provisional НАВСЕГДА, а обещанное сокращение
    # следующей сессией не могло даже начаться (для него нужен триггер капа замыкания).
    # Замыкание НЕ подаёт заявок — это запись фактических цен и NLV, то есть наблюдение;
    # О-5 не нарушается: лечить по-прежнему нечем и некому.
    # СТОП-ФАЙЛ ЧИТАЕТСЯ ПЕРВЫМ (№9): он ставится, когда тревогу записать НЕ удалось.
    if [ -e "$ST/autopilot.STOP" ]; then
        log "СТОП-ФАЙЛ — торговля и замыкание запрещены до ручного разбора"
        return 0
    fi
    if ls "$ST"/ALARM-*.txt >/dev/null 2>&1; then
        local _d0
        _d0=$(chicago %F)
        if traded_today "$_d0" && [ ! -e "$ST/closed-$_d0" ] \
           && [ "$(chicago %H%M)" -ge "$(close_after)" ]; then
            log "тревога стоит, но день $_d0 отторгован и не замкнут — выполняю ТОЛЬКО замыкание"
            ensure_gw && run_close "$_d0"
        fi
        # НАБЛЮДЕНИЕ ЗА ЗАПАСОМ НЕ ОТКЛЮЧАЕТСЯ ТРЕВОГОЙ (двадцать восьмой круг, №13).
        # Любой ALARM выводил тик ДО вахты О-3-Е, а тревога может стоять сутками до ручного
        # разбора: именно тогда маржинальная книга Е и остаётся без единого замера. Тревога
        # запрещает ДЕЙСТВИЯ (заявки), а не измерения — то же разделение, что и в
        # неторговый день. Замер не подаёт заявок и не меняет состояние.
        if [ "$(route)" = E ] && [ ! -e "$ST/ALARM-o3e-blind-$_d0.txt" ]; then
            _cwa=$(o3e_probe 96)
            case "$(verdict "$_cwa")" in
                # ИЗМЕРЕННЫЙ ЗАПАС — УСПЕХ ЛЮБОГО ЗНАКА (разбор /code-review 21.08). Ветка
                # LOW счётчик слепоты НЕ обнуляла, хотя замер состоялся: последовательность
                # SKIP, LOW, SKIP давала три и ставила ALARM-o3e-blind с текстом «не
                # измеряется три тика подряд» — ложным, — а эта тревога сама же ГЛУШИТ
                # вахту до конца дня, ровно когда запас уже известен низким.
                LOW\ *)
                    rm -f "$ST/o3e-alarm-fail-$_d0"
                    log "ВНИМАНИЕ под тревогой: запас О-3-Е $_cwa ниже порога" ;;
                OK\ *|EMPTY\ *) rm -f "$ST/o3e-alarm-fail-$_d0" ;;
                *)  o3e_blind_count "$ST/o3e-alarm-fail-$_d0" "$_cwa" "под тревогой" "$_d0" ;;
            esac
        fi
        return 0                                         # торговли под тревогой нет
    fi
    # ГОРИЗОНТ КАЛЕНДАРЯ (двадцать первый круг, №12): таблицы праздников продлеваются
    # вручную, и обрыв обнаруживался в тот день, когда торговать уже нельзя — у маршрута Е
    # таблица кончается 2026 годом. Это ПРЕДУПРЕЖДЕНИЕ, а не тревога: ALARM-* останавливает
    # контур целиком, а за три месяца до обрыва останавливать нечего. Раз в день.
    local _wd="$ST/WARN-calendar-horizon-$(chicago %Y-%m).txt"
    if [ ! -e "$_wd" ]; then
