# (подстрока отказа, вероятная причина, что проверить человеку)
def _lines(body):
    """Тело тревоги — это СТРОКИ, а не одно полотно (разбор /code-review 45-го круга).

    Тревоги контура составные: run_trade кладёт в файл ВЕСЬ вывод сессии, а alarm_keep
    дописывает туда же следующие причины и вывод самого диагноста. Поэтому проверка «в теле
    есть X и есть Y» ничего не говорит о соседстве: X может стоять в строке про здоровый
    запас, Y — в строке про капитал. Соседство проверяется в пределах ОДНОЙ строки.
    """
    return [l for l in str(body).splitlines() if l.strip()]


def _kapital_nizhe_poroga(body):
    """Отличить отказ ПОЛИТИКИ по капиталу от маржинального отказа О-3-Е (45-й круг, №12).

    Обе тревоги упоминают §8: сокращение О-3-Е делается ПО нормативу §8, а порог капитала —
    это §8 сам по себе. Подстрока «§8» их не различает, и одна тревога получала две
    противоположные причины сразу. Различает соседство: у капитального отказа §8 стоит рядом
    с NLV или со словом «порог», и в ЭТОЙ ЖЕ строке нет признаков маржинального разбора.

    ПОСТРОЧНО, А НЕ ПО ВСЕМУ ТЕЛУ (разбор /code-review). В первой редакции обе половины
    проверялись по целому файлу, и вето «в теле есть слово запас» отменяло ВЕРНЫЙ диагноз
    от одной здоровой информационной строки вида «запас О-3-Е 2.10x не ниже 1.4 —
    сокращение не требуется». Оператор получал зеркально противоположную причину: книгу
    сокращают, хотя маржа здорова, а капитал в это время ниже порога маршрута. Инверсия
    ровно того дефекта, ради которого функция и заведена.
    """
    for l in _lines(body):
        if '§8' not in l:
            continue
        if 'О-3-Е' in l or 'запас' in l:
            continue                      # ЭТА строка про маржу, а не про капитал
        # ПОЛОЖИТЕЛЬНОЕ УТВЕРЖДЕНИЕ О ПРОБОЕ, А НЕ ПРОСТО СОСЕДСТВО (разбор /code-review
        # 21.08). Снятое вето по всему телу оставило признак «§8 рядом с NLV или словом
        # порог» — а такую строку печатает КАЖДАЯ штатная сессия бумажного этапа:
        # «БУМАЖНЫЙ ЭТАП: порог §8 (3,000,000) не применён при NLV 989,197». Полный вывод
        # сессии лежит в теле любой тревоги, поэтому ложная причина «капитал ниже порога»
        # приписывалась бы ко всякому отказу — в том числе к маржинальному, вытесняя из
        # трёх печатаемых причин верную.
        if any(n in l for n in ('не применён', 'не применяется', 'не относится')):
            continue
        if 'ниже порога' in l:
            return True
    return False


# ПРИЗНАКИ ПРОБИТОГО ЗАПАСА И ЕГО ОТРИЦАНИЯ — СПИСКАМИ, ВЗЯТЫМИ У ПРОИЗВОДИТЕЛЕЙ
# (разбор /code-review 21.08). Первая редакция вычитала из «строка упоминает О-3-Е» три
# фразы здорового замера — и потому объявляла «запас ниже норматива, книга сокращается» на
# трёх РАЗНЫХ по смыслу телах: на тревоге СЛЕПОТЫ («запас О-3-Е не измеряется 3 тика
# подряд»), на неизвестном запасе («ПОСЛЕ исполнений НЕИЗВЕСТЕН») и на успешном срезе
# («ПОСЛЕ исполнений 2.10x (порог 1.4)»). Во всех трёх ничего не сокращалось, а в первых
# двух запас вообще не был измерен. Белый список отрицаний по построению отстаёт от
# производителей; поэтому правило теперь ПОЛОЖИТЕЛЬНОЕ: причина называется, только если в
# строке есть прямое утверждение о пробое.
_O3E_ПРОБОЙ = ('ниже', 'упал', 'пробит', 'сокращена', 'сокращение до')
_O3E_НЕ_ПРОБОЙ = ('не ниже', 'не требуется', 'недоступ', 'неизвест', 'НЕИЗВЕСТ',
                  'непровер', 'не измеряется', 'не считается')


def _zapas_nizhe_o3e(body):
    """Маржинальный отказ О-3-Е — прямое утверждение о ПРОБОЕ в строке отказа.

    Голая подстрока «О-3-Е» ловила и здоровый замер, и слепоту, и «запас неизвестен».
    Отдельная причина «брокер не отдаёт живой запас» разбирается СВОЕЙ строкой таблицы, а
    слепота вахты — своей; здесь ни та, ни другая не дублируются.
    """
    for l in _lines(body):
        if 'О-3-Е' not in l:
            continue
        if any(n in l for n in _O3E_НЕ_ПРОБОЙ):
            continue
        if any(p in l for p in _O3E_ПРОБОЙ):
            return True
    return False


def _vahta_oslepla(body):
    """Вахта О-3-Е не смогла измерить запас N тиков подряд (autopilot.sh).

    Тревога слепоты говорит ПРОТИВОПОЛОЖНОЕ пробою: запас не измерен ни разу, книга не
    сокращалась, и оператору нужен шлюз, а не деньги. Своя строка таблицы — чтобы это
    состояние не приходилось выуживать отрицаниями из чужого правила.
    """
    for l in _lines(body):
        if 'О-3-Е' in l and ('не измеряется' in l or 'счётчик слепоты' in l):
            return True
    return False


