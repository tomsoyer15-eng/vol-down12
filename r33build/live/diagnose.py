class _StopFacts(Exception):
    """Маршрут неизвестен: факты по книге не показываются (32-й круг, №17)."""


def facts():
    out = []
    try:
        import pandas as pd
        now = pd.Timestamp.now(tz='America/Chicago')
        out.append(f'Чикаго {now:%Y-%m-%d %H:%M}')
    except Exception as ex:
        out.append(f'время: недоступно ({ex})')
    try:
        import daily
        import state as ST
        # МАРШРУТ — ЧЕРЕЗ ОБЩУЮ ФУНКЦИЮ, БЕЗ УМОЛЧАНИЯ (тридцать второй круг, №17).
        # Здесь стояло `route = ... if rt.exists() else 'F'` — ровно то молчаливое
        # умолчание, которое в бою уже отменено (state.active_route отказывает громко, а
        # инцидент 16.08 показал, к чему оно приводит). После перехода Ф→Е потеря route.txt
        # заставила бы диагноста приложить факты по СТАРОЙ book-F.json и назвать её
        # действующей: оператор, доверившись разбору, открыл бы фьючерсы поверх CSPX/CBU0.
        # Диагност не смеет угадывать сильнее, чем торговый вход.
        try:
            route = ST.active_route()
        except Exception as _exr:
            out.append(f'маршрут: НЕИЗВЕСТЕН ({_exr}) — route.txt утрачен или журнал МР '
                       f'недоступен; книга НЕ показывается, чтобы не выдать неактивную '
                       f'за действующую (О-5)')
            raise _StopFacts
        cls = daily.BookE if route == 'E' else daily.Book
        b, sess, _ = ST.load(ST.book_path(route), cls)
        if b is None:
            out.append(f'книга {route}: отсутствует')
        else:
            out.append(f'книга {route}: сессия {sess} за {b.last_session}, '
                       f'замкнута={"нет" if b.close_provisional else "да"}')
    except _StopFacts:
        pass                       # маршрут неизвестен — факт уже назван выше
    except Exception as ex:
        out.append(f'книга: НЕ ЧИТАЕТСЯ ({type(ex).__name__}: {ex}) — само по себе улика')
    try:
        s = socket.create_connection(('127.0.0.1', 4002), timeout=3)
        s.close()
        out.append('порт шлюза 4002: отвечает')
    except OSError:
        out.append('порт шлюза 4002: НЕ отвечает')
    st = Path.home() / '.addfut'
    alarms = sorted(p.name for p in st.glob('ALARM-*.txt'))
    out.append(f'тревог всего: {len(alarms)} {alarms[:4]}')
    # STOP ВИДЕН ДИАГНОСТИКЕ (тридцатый круг, №19). Перебирались только ALARM-*.txt, и при
    # одном STOP печаталось «тревог нет». Но STOP ставится ИМЕННО ТОГДА, когда записать
    # ALARM не удалось, то есть в самом опасном состоянии: исход прошлой заявки неизвестен,
    # а оператор получает ложное подтверждение здоровья.
    _stop = st / 'autopilot.STOP'
    if _stop.exists():
        _txt = _stop.read_text(encoding='utf-8', errors='replace').strip()[:120]
        out.append(f'СТОП-ФАЙЛ autopilot.STOP ЕСТЬ — контур остановлен: {_txt or "без текста"}')
    else:
        out.append('стоп-файла нет')
    log = st / 'autopilot.log'
    if log.exists():
        tail = log.read_text(encoding='utf-8', errors='replace').splitlines()[-3:]
        out.extend(f'лог: {t}' for t in tail)
    return out


def main(path):
    body = Path(path).read_text(encoding='utf-8', errors='replace')
    hits = [(cause, todo) for sig, cause, todo in SIGNS if sig in body]
    lines = ['', '── ДИАГНОСТ (автоматический разбор; О-5: ничего не чинилось) ──']
    if hits:
        for i, (cause, todo) in enumerate(hits[:3], 1):
            lines.append(f'Вероятная причина {i}: {cause}')
            lines.append(f'  проверить: {todo}')
    else:
        lines.append('Причина не классифицирована — сигнатура отказа не в таблице; '
                     'читать сырой вывод выше, он полный.')
    lines.append('── Факты ──')
    lines.extend('  ' + f for f in facts())
    print('\n'.join(lines))
    return 0


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print('вызов: diagnose.py <ALARM-файл>')
        sys.exit(2)
    sys.exit(main(sys.argv[1]))
