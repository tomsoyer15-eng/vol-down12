def classify(body):
    """ПРИЧИНЫ ПО ТЕЛУ ТРЕВОГИ — ОДНОЙ ФУНКЦИЕЙ ДЛЯ БОЯ И ДЛЯ СТЕНДА (разбор /code-review).

    Отбор жил внутри main() вместе с печатью, поэтому стенд его ПЕРЕСКАЗЫВАЛ своим
    выражением — то есть проверял копию правила, а не правило. Тот же класс, что и два
    читателя журнала §7, починенный этим же кругом. Теперь точка одна.

    ФИЛЬТРА «ЧАСТНОЕ ВЫТЕСНЯЕТ ОБЩЕЕ» ЗДЕСЬ БОЛЬШЕ НЕТ. Он вводился ради пары «О-3-Е» ⊂
    «запас О-3-Е недоступен», но тем же кругом общий якорь стал ФУНКЦИЕЙ, которая сама
    пропускает строки с «недоступ», — и механическая сверка всех девятнадцати строковых
    якорей друг с другом дала НОЛЬ пар вложения. То есть фильтр не мог сработать ни на
    одном входе: инертная защита, чей рабочий режим не испытан вовсе. Правило проекта для
    неоднозначного якоря — предикат-функция, и оно применено дважды; держать рядом ещё и
    недостижимый O(n^2) обход значит выдавать за защиту то, что ею не является.
    """
    return [(cause, todo) for sig, cause, todo in SIGNS
            if (sig(body) if callable(sig) else sig in body)]


