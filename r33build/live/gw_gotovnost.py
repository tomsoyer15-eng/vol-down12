#!/usr/bin/env python3
"""Готовность шлюза IBKR: дождаться прогрева короткими пробами, а не слепым повтором.

ОТКУДА (31.08.2026, перечинка по рецензии правки e854d26). Первая редакция лечила гонку
прогрева повтором подключения внутри session._connect и была дефектна четырьмя способами,
каждый доказан исполнением или трассировкой исходников ib_insync:
  * ловила только TimeoutError — мёртвый порт даёт ConnectionRefusedError, обрыв на
    прогреве даёт ConnectionError, и обе формы той же гонки шли в тревогу без повтора;
  * повторяла ТЕМ ЖЕ объектом IB: неудачное подключение не сбрасывает Wrapper (клиент
    чистит _apiReady раньше связного connection_lost, и wrapper.reset() пропускается) —
    вторая попытка наследовала кэш позиций и заявок мёртвой первой;
  * повторяла ТЕМ ЖЕ clientId через 30 с — могла столкнуться со своим же полумёртвым
    предшественником (ib_insync сам печатает «clientId already in use?»);
  * закрывала одного потребителя из трёх: signal_update идёт по тику РАНЬШЕ сессии.

ЗДЕСЬ ИНАЧЕ. Пробуем короткими ПОЛНЫМИ подключениями (СВЕЖИЙ объект каждый раз,
ОДНОРАЗОВЫЙ clientId, малый таймаут) до успеха или бюджета. Успех пробы = шлюз прогрет,
дальше боевое подключение делается КАК И ПРЕЖДЕ — один раз, своим clientId. Провал
бюджета печатает машинный код причины (ворота 8в-3: причины — по коду, а не по прозе) и
НЕ мешает боевому подключению попытаться: честная тревога лучше молчания.
Все три потребителя зовут одно и то же: session, signal_update, ensure_gw (оболочка —
только вызов, правило 8д).
"""
import socket
import sys
import time

КОД_ПРИЧИНЫ = 'ADDFUT-ПРИЧИНА: ШЛЮЗ-НЕ-ПРОГРЕЛСЯ'
ПРОБНЫЙ_CLIENT_ID = 98          # одноразовый, боевые: сессия 33, сигнал 37, пробы 94-97


def дождаться(host='127.0.0.1', port=4002, бюджет_с=120, шаг_с=5, таймаут_пробы_с=10):
    """True — шлюз прогрет (полная проба прошла); False — бюджет вышел, код напечатан."""
    предел = time.monotonic() + бюджет_с
    попытка = 0
    while time.monotonic() < предел:
        попытка += 1
        # Порт молчит — шлюз ещё поднимается; это тоже ожидание, а не другая болезнь.
        try:
            с = socket.create_connection((host, port), timeout=3)
            с.close()
        except OSError:
            time.sleep(шаг_с)
            continue
        try:
            import ib_insync                       # лениво: стендам подменяемо
            ib = ib_insync.IB()                    # СВЕЖИЙ объект на каждую пробу
            ib.connect(host, port, clientId=ПРОБНЫЙ_CLIENT_ID, timeout=таймаут_пробы_с)
            ib.disconnect()
            print(f'шлюз прогрет (проба {попытка})', flush=True)
            return True
        except Exception as ошибка:
            print(f'проба {попытка}: шлюз не готов ({type(ошибка).__name__})', flush=True)
            time.sleep(шаг_с)
    print(f'{КОД_ПРИЧИНЫ}; полное подключение не прошло за {бюджет_с} с '
          f'({попытка} проб) — боевое подключение пойдёт как есть', flush=True)
    return False


if __name__ == '__main__':
    _б = int(sys.argv[1]) if len(sys.argv) > 1 else 120
    raise SystemExit(0 if дождаться(бюджет_с=_б) else 1)
