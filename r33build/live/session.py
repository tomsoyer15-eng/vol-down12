def _account_pin():
    """ТОРГОВЫЙ СЧЁТ ПИНУЕТСЯ ЯВНО (двадцатый круг, №5).

    Пин в адаптере существовал, но в бою был МЁРТВ: ADDFUT_ACCOUNT не задавался нигде —
    ни в ibgw.env (там только логин и пароль), ни в autopilot.sh, ни в crontab. При одном
    managedAccount адаптер молча принимал тот счёт, который дал шлюз, поэтому вход в
    ДРУГОЙ счёт (правка ibgw.env, другой paper от IBKR) прошёл бы сверку с пустой книгой и
    получил полную позицию 2х, а ~/.addfut стал бы состоянием чужого счёта. Заодно
    оживают проверки, опирающиеся на этот же пин: счёт замера маржи (_live_margins) и
    фильтры чужих заявок и исполнений в адаптере.

    Источник — окружение либо файл счёта в ТОМ ЖЕ каталоге состояния, где книга и замок
    (один namespace путей, девятнадцатый круг, №17). Отсутствие пина — ОТКАЗ сессии, а не
    молчаливое «возьмём что дали»: это торговый вход, и он обязан знать свой счёт.
    """
    import state as ST
    pin = (os.environ.get('ADDFUT_ACCOUNT') or '').strip()
    if pin:
        return pin
    p = ST.lock_dir() / 'account.txt'
    try:
        pin = p.read_text(encoding='utf-8').strip()
    except OSError as ex:
        raise Refused(f'торговый счёт не пинован: нет ADDFUT_ACCOUNT и не читается {p} '
                      f'({ex}) — сессия запрещена (двадцатый круг, №5)')
    if not pin:
        raise Refused(f'торговый счёт не пинован: {p} пуст — сессия запрещена')
    return pin


def do_close(ib, route):
    """Замкнуть сессию по факту закрытия: фактические цены закрытия и фактический NLV.

    ВСЁ ПОД ОДНОЙ БЛОКИРОВКОЙ, И КНИГА ПЕРЕЧИТЫВАЕТСЯ ПЕРЕД ЗАПИСЬЮ. Прежняя редакция
    читала книгу, ходила к брокеру за NLV и ценами и только потом брала замок: между
    чтением и записью переходный исполнитель успевал перевести маршрут и сохранить новую
    книгу, а замыкание затирало её старой — классическая потерянная запись при фактической
    позиции уже на другом маршруте.

    ЗАМЫКАЕТСЯ ИМЕННО ТА СЕССИЯ, КОТОРАЯ ТОРГОВАЛА. Проверяется, что замыкание ещё не
    выполнялось и что дата книги совпадает с сегодняшней биржевой: иначе пропущенное в
    понедельник замыкание, запущенное во вторник, посчитало бы триггер капа по вторничным
    ценам для понедельничной книги, а повторный запуск переписал бы его ещё раз.
    """
    import state as ST
    br = IBB.IBBroker(ib, account=_account_pin())
    # признак реального времени доходит до адаптера (№15): без него px_order_live всегда
    # False, и §7 не начал бы набирать выборку даже при купленной подписке
    br.realtime_md = (os.environ.get('ADDFUT_REALTIME_MD') == '1')
    bp = _book_path(route)
    cls = DL.BookE if route == 'E' else DL.Book
    with ST.hold_book_lock():
        book, sess, saved = ST.load(bp, cls)
        if book is None:
            raise Refused('нет сохранённой книги — замыкать нечего')
        if saved != route:
            raise Refused(f'книга записана для маршрута {saved}, запрошен {route}')
        if not getattr(book, 'close_provisional', False):
            raise Refused(f'сессия №{sess} уже замкнута (плечо закрытия '
                             f'{book.prev_close_lev:.4f}); повторное замыкание переписало бы '
                             f'триггер капа §1 по ценам другой сессии')
        today = FD.exchange_today().strftime('%Y-%m-%d')
        if book.last_session and book.last_session != today:
            raise Refused(
                f'книга относится к сессии {book.last_session}, а сегодня {today}: замкнуть '
                f'её сегодняшними ценами значит посчитать триггер капа §1 по чужому '
                f'закрытию. Требуется ручной разбор (О-5)')
        # СВЕРКА С БРОКЕРОМ ПЕРЕД ФИКСАЦИЕЙ ПЛЕЧА (№9): поздний фил, чужая позиция или
        # живая заявка не должны попадать в триггер капа как «чистое закрытие».
        # БАРЬЕР НЕЗАВЕРШЁННОЙ ПЕРЕДАЧИ И ДЛЯ ЗАМЫКАНИЯ (двадцать пятый круг, №13). Метку
        # проверяла только торговая сессия: после смерти перехода между публикацией книги и
        # TRANSITION_COMPLETE замыкание успешно финализировало книгу, ставило closed-*,
        # делало backup и WORM-якорь — то есть заверяло «замкнутое» состояние НЕЗАВЕРШЁННОГО
        # перехода, пока нормативный журнал держал TRANSITION_OPEN.
        _hf = ST.lock_dir() / f'handover-inflight-{route}.txt'
        if _hf.exists():
            raise Refused(
                f'{_hf}: передача книги начата, но COMPLETE не записан — замыкать '
                f'незавершённый переход нельзя, плечо закрытия относилось бы к книге '
                f'без нормативного подтверждения (О-5)')
        # СОГЛАСОВАННЫЙ СНИМОК (двадцать четвёртый круг, №6): обе сверки замыкания читали
        # позиции, затем заявки — та же гонка, что в run_session. Поздний fill между
        # вызовами делал сверку ложной, и плечо закрытия фиксировалось по книге, которой
        # у брокера уже нет.
        import daily as _DLc
        _pos_c, _oo_c = _DLc._snapshot_consistent(br)
        diff = ST.reconcile(book, route, _pos_c, open_orders=_oo_c)
        if diff:
            raise Refused('замыкание отменено — книга расходится с брокером:\n  '
                          + '\n  '.join(diff))
        px_eq, dref, px_bd, src = FD.closing_values(ib, route, book)
        # NLV — ПОСЛЕ цен закрытия (тринадцатый круг, №3): триггер капа обязан делить цены
        # и капитал ОДНОГО момента; ранний NAV с поздними ценами искажал prev_close_lev.
        nav = br.net_liquidation()
        # ПОВТОРНАЯ СВЕРКА ПОСЛЕ ДОЛГИХ ЗАПРОСОВ (десятый круг, №11): поздний фил или новая
        # заявка в окне запросов цен не должны попадать в триггер капа незамеченными.
        _pos_c2, _oo_c2 = _DLc._snapshot_consistent(br)
        diff2 = ST.reconcile(book, route, _pos_c2, open_orders=_oo_c2)
        if diff2:
            raise Refused('замыкание отменено — брокер изменился за время запросов:\n  '
                          + '\n  '.join(diff2))
        book2, sess2, saved2 = ST.load(bp, cls)
        if (vars(book2) != vars(book)) or sess2 != sess or saved2 != saved:
            raise Refused('книга изменилась, пока снимались цены закрытия — замыкание '
                             'отменено во избежание потерянной записи')
        closed = DL.finalize_close(book, px_eq, dref, nav, route=route, px_bd_close=px_bd)
        ST.save(bp, closed, route, sess, note='замыкание сессии по факту закрытия')
    print(f'замкнуто: NLV закрытия {nav:,.2f}, вход {src}')
    print(f'плечо закрытия {closed.prev_close_lev:.4f} — триггер капа следующей сессии')
    return closed


def _alarm_o3e(day, reason, src):
    """ТРЕВОГА О-3-Е ФАЙЛОМ, ДОЛГОВЕЧНО (тридцать третий круг, №6).

    Ставится ДО сохранения книги и записи итога §7: иначе обрыв питания между итогом и
    тревогой оставляет состояние, неотличимое от штатно завершённой сессии, и причина
    аварийного сокращения не разбирается никем. fsync файла И каталога — тревога обязана
    пережить ровно тот сбой, ради которого её пишут.
    """
    _af = state_dir() / f'ALARM-o3e-{day}.txt'
    _msg = (f'{reason}. Вход: {src}. Сокращение выполнено автоматикой по нормативу §8, '
            f'но причина провала запаса НЕ разобрана: контур под этой тревогой не торгует '
            f'до ручного снятия (О-5)\n')
    try:
        with open(_af, 'w', encoding='utf-8') as _fh:
            _fh.write(_msg); _fh.flush(); os.fsync(_fh.fileno())
        _dfd = os.open(str(_af.parent), os.O_DIRECTORY)
        try:
            os.fsync(_dfd)
        finally:
            os.close(_dfd)
        if not _af.exists() or not _af.stat().st_size:
            raise OSError('файл тревоги пуст после записи')
    except Exception as _exa:
        try:
            (state_dir() / 'autopilot.STOP').write_text(
                f'не удалось записать ALARM-o3e-{day}: {_exa}\n', encoding='utf-8')
        except Exception:
            pass
        raise Refused(f'тревога О-3-Е НЕ записана ({_exa}) — поставлен STOP; заявки среза '
                      f'уже исполнены, немедленный ручной разбор (О-5)')


def do_o3e_cut(ib, route):
    """СОКРАЩЕНИЕ О-3-Е В УЖЕ ОТТОРГОВАННОЙ СЕССИИ (тридцать первый круг, №1).

    Норматив §8: «live-отношение <1,40 — сокращение до L=1 В ТУ ЖЕ СЕССИЮ». Тридцатый круг
    закрыл это для момента исполнения заявок (run_session сокращает книгу сразу после
    сверки), но ВНУТРИДНЕВНАЯ вахта автопилота осталась только наблюдателем: обнаружив
    провал запаса после traded-*, она писала ALARM — и этим же ALARM запрещала запуск,
    который мог бы книгу сократить. Книга уходила в ночь около 2x именно в тот день, когда
    запас уже пробит; небольшой следующий ход даёт margin call.

    Это НЕ самолечение против О-5: сокращение до L=1 — предписанное нормой действие с
    известной целью, а не «починка» расхождения с брокером. Тревога ставится в любом
    исходе, торговля дальше не продолжается, причину разбирает человек.

    Путь узкий намеренно: только маршрут Е, только сегодняшняя отторгованная и ещё не
    замкнутая окончательно книга, только СОКРАЩЕНИЕ (o3e_reduce ограничен min(..., n0) и
    нарастить не может), только внутри торгового окна. Всё остальное — отказ.
    """
    import state as ST
    import journal as J
    from dataclasses import replace as _rep

    if route != 'E':
        raise Refused(f'О-3-Е относится к маршруту Е, запрошен {route}')
    # ВОРОТА PAPER/LIVE — И ЗДЕСЬ (тридцать второй круг, №3). do_trade зовёт paper_mode()
    # и через него проверяет СОЧЕТАНИЕ порта и типа счёта плюс ADDFUT_LIVE_OK; этот вход
    # такой проверки не имел вовсе. Живой Gateway, ошибочно поднятый на 4002, запрещал бы
    # обычную торговлю — и при этом --o3e автоматически продал бы настоящие CSPX/CBU0 до
    # L=1. Аварийность действия не отменяет того, чьи это деньги.
    paper_mode()
    _wb = FD.trading_window_ok(route)          # №4: тот же вход, те же ворота дня и окна
    if _wb:
        raise Refused(f'срез О-3-Е вне окна маршрута {route}: {_wb} — заявка висела бы GTC')
    _active = ST.active_route()
    if _active != route:
        raise Refused(f'запрошен маршрут {route}, а действующий — {_active}')
    br = IBB.IBBroker(ib, account=_account_pin())
    br.realtime_md = (os.environ.get('ADDFUT_REALTIME_MD') == '1')
    bp = _book_path(route)
    today = FD.exchange_today().strftime('%Y-%m-%d')
    with ST.hold_book_lock():
        book, sess, saved = ST.load(bp, DL.BookE)
        if book is None:
            raise Refused('нет сохранённой книги — сокращать нечего')
        if saved != route:
            raise Refused(f'книга записана для маршрута {saved}, запрошен {route}')
        if book.last_session != today:
            raise Refused(f'книга относится к сессии {book.last_session}, а сегодня '
                          f'{today}: сокращение «в ту же сессию» неприменимо (О-5)')
        if not getattr(book, 'close_provisional', False):
            raise Refused(f'сессия №{sess} уже замкнута окончательно — заявки после '
                          f'фиксации плеча закрытия переписали бы триггер капа §1')
        _hf = ST.lock_dir() / f'handover-inflight-{route}.txt'
        if _hf.exists():
            raise Refused(f'{_hf}: передача книги не завершена — заявки запрещены (О-5)')
        if ST.load_intent(bp) is not None:
            raise Refused('на диске осталось намерение прошлого запуска — сокращение '
                          'поверх неразобранного обрыва запрещено (О-5)')
        # СВЕРКА ДО ЛЮБОГО РЕШЕНИЯ: считать сокращение от книги, которой у брокера нет,
        # значит подать заявку в пустоту либо оставить short.
        _pos, _oo = DL._snapshot_consistent(br)
        _diff = ST.reconcile(book, route, _pos, open_orders=_oo)
        if _diff:
            raise Refused('книга расходится с брокером — сокращение отменено:\n  '
                          + '\n  '.join(_diff))
        _pc = br.margin_cushion()
        if _pc is None:
            raise Refused('живой запас О-3-Е недоступен при существующей книге — '
                          'сокращение считалось бы по выдуманному числу (О-5)')
        if float(_pc) >= DL.O3E_MIN:
            print(f'запас О-3-Е {float(_pc):.2f}x не ниже {DL.O3E_MIN} — сокращение не требуется')
            return None
        jp = state_dir() / f'journal-{route}.csv'
        try:
            J.verify(jp)
        except Exception as ex:
            raise Refused(f'журнал §7 повреждён: {ex} — заявки запрещены (О-5)')
        # ПОТЕРЯ ЖУРНАЛА НЕ РОЖДАЕТ НОВЫЙ GENESIS (тридцать второй круг, №11; тот же класс,
        # что двадцать второй круг, №16). verify() отсутствующего или header-only файла
        # возвращает 0 БЕЗ ошибки, и первая же строка среза начала бы новую цепочку — вся
        # прежняя история исполнений исчезла бы без видимого разрыва, а WORM заверил бы
        # формально корректный журнал. Торговавшая книга обязана иметь непустой журнал,
        # закрытый итоговой строкой: иначе неизвестно, что записалось, а что нет.
        _jr = J.read(jp) if jp.exists() else []
        if not _jr:
            raise Refused(f'{jp}: журнал §7 пуст, а книга несёт сессию №{sess} от '
                          f'{book.last_session} — журнал утрачен или подменён; срез начал '
                          f'бы новую цепочку (О-5)')
        if not str(_jr[-1].get('note', '')).startswith('итог сессии'):
            raise Refused('журнал §7 не закрыт итоговой строкой — часть строк исполнения '
                          'могла не записаться; срез запрещён до разбора (О-5)')
        m, src = FD.build_market(ib, FD.exchange_today(), book, route=route)
        refs = FD.reference_prices(ib, route=route)
        refs = {k: v for k, v in refs.items() if not k.startswith('ОРИЕНТИР-НЕТ:')}
        _n0e, _n0b = book.n_eq, book.n_bd
        _share = 1.0 / max(float(m.st_eq) + float(m.st_bd), 1.0)
        _nlv = float(br.net_liquidation())
        _ne, _nb, _ = DL.o3e_reduce(_nlv, m, m.px_eq_prev, m.px_bd_prev,
                                    _n0e, _n0b, _n0e, _n0b, _share)
        _orders = [(i, q) for i, q in (('CSPX', _ne - _n0e), ('CBU0', _nb - _n0b)) if q]
        if not _orders:
            raise Refused(
                f'запас О-3-Е {float(_pc):.2f}x ниже {DL.O3E_MIN}, но цель сокращения '
                f'совпала с книгой ({_n0e}/{_n0b}) — норматив требует L=1, а арифметика '
                f'его уже даёт: провал запаса вызван не размером книги. Ручной разбор (О-5)')
        _deadline = FD.trade_deadline(route)
        _cut = _rep(book, n_eq=_ne, n_bd=_nb)
        # СВЕРКА НЕПОСРЕДСТВЕННО ПЕРЕД ПЕРВОЙ ЗАЯВКОЙ (тридцать третий круг, №5). Первая
        # сверка стоит ДО замера запаса, проверки журнала, build_market, ориентиров и NLV —
        # это секунды и десятки секунд, за которые поздний fill меняет фактическую позицию.
        # Объём среза при этом остался бы посчитанным от СТАРОЙ книги: запоздавшая продажа
        # −100 плюс срез −500 от прежней тысячи оставят 400 вместо цели 500. Отказ здесь
        # ничего не стоит: ни одной заявки ещё не подано.
        _pos1, _oo1 = DL._snapshot_consistent(br)
        _diff1 = ST.reconcile(book, route, _pos1, open_orders=_oo1)
        if _diff1:
            raise Refused('книга изменилась между расчётом среза и подачей заявок — '
                          'объём среза считался по устаревшему счёту:\n  '
                          + '\n  '.join(_diff1))
        ST.save_intent(bp, route, sess, book, _cut, _orders, session_date=today)
        _placed = []

        def _cut_fail(_inst, _qty, _what):
            """СБОЙ СРЕЗА ИДЁТ ЧЕРЕЗ ВОССТАНОВЛЕНИЕ (тридцать второй круг, №1).

            Первая редакция просто поднимала Refused: ни restore_to, ни снятия живых
            заявок. Если CSPX продан, а CBU0 отвергнут, книга у брокера одноногая —
            дыра порядка половины NLV, — на диске лежит досрезная книга, и следующий
            запуск не может ни принять состояние, ни доказуемо его вернуть. Возврат
            всё равно недоказуем без входной сверки следующей сессии, поэтому исход
            остаётся О-5; но попытка обязана быть сделана и названа."""
            try:
                for _oid in (br.open_orders() or []):
                    try:
                        br.cancel_order(_oid)
                    except Exception:
                        pass
            except Exception:
                pass                  # аварийная уборка не смеет маскировать причину
            try:
                _ok, _have, _stuck = DL.restore_to(br, book, route)
                _late = [x for x in _stuck if 'ЗА КРАЕМ' in str(x)]
                _n = ('книга ПО ДОСТУПНЫМ ДАННЫМ возвращена к досрезной (подтверждение — '
                      'входной сверкой следующей сессии)' if _ok else
                      f'ВОССТАНОВИТЬ НЕ УДАЛОСЬ: у брокера {_have}, неснятых заявок '
                      f'{len(_stuck)}')
                if _late:
                    _n += ' | ' + '; '.join(_late)
            except Exception as _ex2:
                _n = f'восстановление НЕ ВЫПОЛНЕНО ({_ex2})'
            return Refused(f'О-3-Е (вахта): {_inst} {_qty:+g} {_what} — книга в '
                           f'промежуточном состоянии, состояние НЕ сохранено; {_n}; '
                           f'ручной разбор (О-5)')

        for _inst, _qty in _orders:
            # ВОРОТА ОКНА — ВНУТРИ try (№1): закрытие окна ПОСЛЕ первой исполненной ноги
            # поднимало WindowClosed мимо разбора, и восстановление не запускалось вовсе.
            try:
                DL._window_gate(_deadline, what=f'О-3-Е (вахта) {_inst} {_qty:+g}')
                _rec = br.place(_inst, _qty, refs.get(_inst))
            except DL.WindowClosed as ex:
                # ЕДИНСТВЕННЫЙ СЛУЧАЙ, КОГДА КНИГА ТОЧНО НЕ ТРОНУТА (тридцать третий круг,
                # №1): ворота окна отказывают ДО подачи, заявки не было по построению.
                if not _placed:
                    # ЧИСТЫЙ ОТКАЗ УБИРАЕТ НАМЕРЕНИЕ ЗА СОБОЙ (тридцать четвёртый круг,
                    # №7): намерение пишется ДО цикла заявок, и оставленный след
                    # несуществующей заявки блокировал бы и следующий --o3e, и обычную
                    # сессию после снятия тревоги — книга осталась бы несокращённой, а
                    # ближайший ролл заблокированным разбором того, чего не было.
                    ST.clear_intent(bp)
                    raise Refused(f'О-3-Е (вахта): {_inst} {_qty:+g} не подано ({ex}) — '
                                  f'ворота окна отказали до подачи, книга не тронута, '
                                  f'намерение снято')
                raise _cut_fail(_inst, _qty, f'ворота окна закрылись посреди среза ({ex})')
            except BaseException as ex:
                # ОТСУТСТВИЕ ПОДТВЕРЖДЕНИЯ — НЕ ОТСУТСТВИЕ СДЕЛКИ (тридцать третий круг,
                # №1). Здесь стояло «ни одной заявки не исполнено, книга не тронута» при
                # пустом _placed. Но пустой _placed означает лишь, что place() не ВЕРНУЛ
                # запись: по контракту адаптера исключение после подачи — исход
                # НЕИЗВЕСТНЫЙ (правило проекта 7). Продажа CSPX могла состояться, отчёт
                # потеряться, а CBU0 остаться открытым: одноногая дыра порядка половины
                # NLV при досрезной книге на диске. Разбор одинаков независимо от того,
                # успела ли первая нога подтвердиться.
                raise _cut_fail(_inst, _qty, f'не подано ({ex}, исход НЕИЗВЕСТЕН, '
                                             f'повтор не выполняется)')
            _placed.append(_rec)
            if not DL._filled(_rec, _qty):
                raise _cut_fail(_inst, _qty, f'исполнено {_rec.get("filled")}')
        # ФИНАЛЬНЫЕ СВЕРКИ — ТОЖЕ ПОД РАЗБОРОМ (тридцать третий круг, №5): сбой снимка или
        # расхождение книги поднимались НАПРЯМУЮ, минуя _cut_fail, то есть без отмены живых
        # заявок и без попытки возврата — при уже исполненных заявках среза.
        try:
            _pos2, _oo2 = DL._snapshot_consistent(br)
            _after = ST.reconcile(_cut, route, _pos2, open_orders=_oo2)
        except BaseException as _exs:
            raise _cut_fail(_orders[-1][0], _orders[-1][1],
                            f'снимок счёта после среза недоступен ({_exs})')
        if _after:
            raise _cut_fail(_orders[-1][0], _orders[-1][1],
                            'книга брокера не совпала с намеченной: ' + '; '.join(_after))
        # ЖУРНАЛ §7: строки исполнения плюс ИТОГ, ЯВНО исключающий дату из выборки
        # издержек. Строки ложатся ПОСЛЕ итога торговой сессии, значит её счётчик «строк N»
        # перестал сходиться — дата и без пометки выпала бы из выборки, но молчаливое
        # исключение оператору ничего не объясняет.
        # ЦЕЛЬ СЧИТАНА ПО МОДЕЛЬНЫМ ЦЕНАМ — РЕЗУЛЬТАТ МЕРЯЕТСЯ ПО ЖИВОМУ (32-й круг, №5).
        # o3e_reduce размеряет книгу по закрытиям предыдущей сессии (конвенция §1 и
        # замороженного движка), а триггер и требование маржи — живые. При внутридневном
        # движении цен «сокращено до L=1» может фактически означать 1,05-1,10x, и книга
        # продолжит давить на маржу, пока все считают норматив выполненным. Перечитываем
        # запас ПОСЛЕ исполнений и говорим правду в журнале и в тревоге.
        try:
            _pc2 = br.margin_cushion()
        except Exception as _exp2:
            _pc2 = None
            _ach = f'проверить результат не удалось ({_exp2})'
        else:
            _ach = (f'запас после среза {float(_pc2):.2f}×'
                    if _pc2 is not None else 'запас после среза НЕИЗВЕСТЕН')
        _norm_ok = (_pc2 is not None and float(_pc2) >= DL.O3E_MIN)
        from types import SimpleNamespace as _SNS
        _reason = (f'О-3-Е ВНУТРИДНЕВНАЯ ВАХТА: запас {float(_pc):.2f}× ниже {DL.O3E_MIN} — '
                   f'книга сокращена в ту же сессию {_n0e}/{_n0b} -> {_ne}/{_nb} (§8); '
                   f'{_ach}'
                   + ('' if _norm_ok else
                      ' — НОРМАТИВ НЕ ДОСТИГНУТ ОДНИМ СРЕЗОМ: цель считана по модельным '
                      'ценам предыдущего закрытия, а требование живое; нужен ручной '
                      'разбор (О-5)'))
        _dec = _SNS(date=m.date, leverage=float(book.prev_close_lev or 0.0),
                    reasons=[_reason], refusals=[], roll_pairs=[])
        _delayed31 = []
        _rows31 = J.rows_from_decision(_dec, _nlv, _orders,
                                       {r['instrument']: r for r in _placed},
                                       delayed_out=_delayed31)
        for _row in _rows31:
            J.append(jp, _row)
        # СНАЧАЛА СОСТОЯНИЕ, ПОТОМ ИТОГ (тридцать второй круг, №12). Прежде ИТОГ ложился
        # ДО ST.save: сбой записи книги (ENOSPC/ACL) оставлял журнал, объявляющий операцию
        # завершённой, при досрезной книге на диске и сокращённом брокере — ручное
        # восстановление шло бы по ложному состоянию. В run_session порядок именно такой
        # (двадцать пятый круг, №12), и здесь он обязан совпадать.
        # ТРЕВОГА СТАВИТСЯ ДО ДОЛГОВЕЧНОГО ЗАВЕРШЕНИЯ (тридцать третий круг, №6). Прежде
        # книга сохранялась, намерение снималось, итог §7 писался — и только потом
        # создавался ALARM. Потеря питания в этом зазоре оставляла состояние, которое
        # автопилот считает ШТАТНЫМ повтором («не новее последней завершённой»), ставит
        # traded-* и идёт дальше: аварийное сокращение прошло, причина не разобрана, а
        # следующая сессия полосой возвращает книгу к 2x. Заявки уже исполнены, отменить
        # ничего нельзя — единственный порядок, который не теряет тревогу, это «сначала
        # тревога, потом состояние».
        _alarm_o3e(today, _reason, src)
        _closed = _rep(DL.close_out_e(_cut, m.px_eq_today, m.px_bd_today, _nlv),
                       last_session=today, close_provisional=True)
        ST.save(bp, _closed, route, sess, note=_reason)
        ST.clear_intent(bp)
        # ИТОГОВАЯ СТРОКА НАЧИНАЕТСЯ С «итог сессии» (тридцать второй круг, №9). Следующая
        # торговая сессия требует ровно этого префикса у ПОСЛЕДНЕЙ строки журнала
        # (daily.run_session): прежний текст «О-3-Е сокращение после итога…» её
        # детерминированно останавливал — после снятия тревоги контур не мог вернуть книгу
        # к цели, а на ролловой дате старая серия ушла бы к поставке. Пометка исключения
        # из выборки §7 остаётся: её ловит подстрока «исключ».
        J.append(jp, dict(
            date=today, leg='', instrument='ИТОГ', qty=0, px_order='-', px_fill='',
            commission='', reason='', nav=_nlv, leverage='', roll_spread_near='',
            roll_spread_far='',
            note=f'итог сессии {sess} (О-3-Е вахта, строк {len(_rows31)}): дата ИСКЛЮЧЕНА '
                 f'из выборки издержек §7 — {_reason}'))
    print(f'{_reason} (тревога поставлена ДО записи состояния)')
    return _closed


def do_trade(ib, route, dry):
    import state as ST

    br = IBB.IBBroker(ib, account=_account_pin())
    # признак реального времени доходит до адаптера (№15): без него px_order_live всегда
    # False, и §7 не начал бы набирать выборку даже при купленной подписке
    br.realtime_md = (os.environ.get('ADDFUT_REALTIME_MD') == '1')
    nlv = br.net_liquidation()
    pos = br.net_positions()
    alien = [k for k in pos if k.startswith('НЕИЗВЕСТНЫЙ')]
    if alien:
        raise Refused(f'на счёте посторонние позиции {alien} — сессия не считается')

    # АКТИВНЫЙ МАРШРУТ СВЕРЯЕТСЯ (двадцать седьмой круг, №1). Маршрут брался из аргумента
    # и не проверялся НИЧЕМ: `--route E` при действующем Ф открывал book-E.json или
    # создавал пустую BookE и торговал её — до 2x CSPX/CBU0 в обход OWNER_APPROVE и всего
    # переходного исполнителя. Источников истины два, и оба обязаны совпасть: route.txt
    # (его читает автопилот) и маршрут нормативного журнала МР.
    _active = ST.active_route()
    if _active != route:
        raise Refused(
            f'запрошен маршрут {route}, а действующий — {_active}: смена маршрута идёт '
            f'ТОЛЬКО через transition.py с одобрением заказчика, а не ключом сессии')
    bp = _book_path(route)
    cls = DL.BookE if route == 'E' else DL.Book
    book, sess, _ = ST.load(bp, cls)
    book = book or cls()

    # НЕЗАМКНУТАЯ ПРЕДЫДУЩАЯ СЕССИЯ — ОТКАЗ, А НЕ ПРЕДУПРЕЖДЕНИЕ. Плечо закрытия в такой
    # книге посчитано по ценам открытия и утреннему NLV, то есть триггер капа §1 заведомо
    # неверен. Торговать по нему хуже, чем пропустить сессию.
    # БЕЗ условия sess>0: книга, принятая от перехода, приходит с провизорным замыканием и
    # обязана его пройти; прежняя проверка «if sess and ...» на ней отключалась.
    if getattr(book, 'close_provisional', False) and book.last_session and not dry:
        raise Refused(f'сессия №{sess} не замкнута: плечо закрытия предварительное, '
                         f'триггер капа §1 недостоверен. Выполнить: session.py --close')

    # ТОРГОВЫЙ ДЕНЬ И НАЧАЛО ОКНА ПРОВЕРЯЮТСЯ ЗДЕСЬ (тридцать второй круг, №4). Верхний
    # край окна держал _window_gate, а выходной, праздник и запуск ДО 08:45 отсекала только
    # оболочка автопилота — при том что session.py --live самостоятельный торговый вход.
    # В субботу prev_session() вернёт пятницу, проверка пропущенного дня пройдёт, дедлайн
    # будет субботним, и заявки уйдут GTC до понедельника; состояние запишется субботней
    # датой и в понедельник заблокирует само себя. Наблюдение (--dry) не ограничиваем.
    if not dry:
        _wb = FD.trading_window_ok(route)
        if _wb:
            raise Refused(f'торговый вход вне окна маршрута {route}: {_wb}')

    # ДАТА СЕССИИ — БИРЖЕВАЯ. По часам машины запуск около полуночи UTC пометил бы
    # сделку соседней датой, и last_session либо заблокировал бы правильный запуск,
    # либо допустил второй под другой локальной датой.
    m, src = FD.build_market(ib, FD.exchange_today(), book, route=route)
    print(f'счёт {br.account}: NAV {nlv:,.2f}; позиции {pos or "нет"}; сессия №{sess + 1}')
    print('вход: ' + ', '.join(f'{k}={v}' for k, v in src.items()))

    # ПОРОГ §8 НЕ ОТКЛЮЧАЕТСЯ, А ЯВНО ИСКЛЮЧАЕТСЯ НА БУМАЖНОМ ЭТАПЕ, и это пишется в
    # журнал: молчаливый обход политики был бы ровно тем, ради чего этап и заведён.
    # ЦЕНЫ-ОРИЕНТИРЫ СНИМАЮТСЯ ДО ЗАЯВОК: без них журнал §7 не накапливает наблюдений.
    refs = FD.reference_prices(ib, route=route)
    _miss = {k: v for k, v in refs.items() if k.startswith('ОРИЕНТИР-НЕТ:')}
    refs = {k: v for k, v in refs.items() if not k.startswith('ОРИЕНТИР-НЕТ:')}
    print('ориентиры:', {k: round(v, 4) for k, v in refs.items()})
    for _k, _v in _miss.items():
        print(f'  {_k}: {_v}')
    kw = {}
    if route == 'E':
        # ЖИВОЙ ЗАПАС О-3-Е — ОТ БРОКЕРА (десятый круг, №2): расчётная прокси при капе 2,00
        # не опускается ниже порога, и аварийное сокращение было недостижимо в бою.
        _lc = br.margin_cushion()
        # СУЖДЕНИЕ ПО КНИГЕ, А НЕ ПО РАННЕМУ СНИМКУ (двадцать третий круг, №19). Отказ
        # зависел от any(pos.values()) — снимка позиций, взятого РАНЬШЕ и, возможно,
        # пустого или устаревшего; загруженная book при этом не использовалась вовсе.
        # Если снимок пуст, а книга несёт позиции, step_e получал live_cushion=None и
        # переключался на расчётную прокси, недостижимую при капе 2,00 — то есть на
        # сессии без заявок пост-трейд проверка не выполнялась бы вообще.
        _book_live = bool(book is not None and (getattr(book, 'n_eq', 0) or
                                                getattr(book, 'n_bd', 0)))
        if _lc is None and (_book_live or any(v for v in (pos or {}).values())):
            # НУЛЕВОЕ/ОТСУТСТВУЮЩЕЕ ТРЕБОВАНИЕ ПРИ СУЩЕСТВУЮЩИХ ПОЗИЦИЯХ (семнадцатый
            # круг, №7) — неполный ответ брокера, а не «позиций нет»: прокси 25% дала бы
            # запас 2,0 и оставила бы полную позицию вместо аварийного сокращения.
            raise Refused('живой запас О-3-Е недоступен при существующих позициях — '
                          'торговля Е запрещена до восстановления данных брокера')
        # ЗАПАС ЧИТАЕТСЯ ВНУТРИ СЕССИИ, А НЕ ЗАРАНЕЕ (двадцать четвёртый круг, №11).
        # Прежде live_cushion снимался ДО книжного замка и до согласованного снимка, а
        # затем передавался готовой константой; NLV при этом перечитывался внутри
        # run_session. Между чтениями маржа могла упасть, и step_e не выполнил бы
        # обязательное сокращение — вахта потом лишь ставила ALARM, но в ту же сессию не
        # сокращала. Передаём ФУНКЦИЮ: run_session вызовет её под замком, рядом с NLV.
        kw['live_cushion'] = _lc
        kw['live_cushion_fn'] = br.margin_cushion
        # ТРЕВОГА ПИШЕТСЯ ИЗНУТРИ СЕССИИ, ДО СОХРАНЕНИЯ КНИГИ (тридцать третий круг, №6):
        # снаружи она неизбежно опаздывала за долговечным завершением операции.
        if not dry:
            kw['o3e_alarm_fn'] = (lambda _r, _d=f'{m.date:%Y-%m-%d}':
                                  _alarm_o3e(_d, _r, src))
    # NLV НЕ ПЕРЕДАЁТСЯ снаружи (тринадцатый круг, №2): между ранним чтением и заявками —
    # серия долгих запросов; run_session сам читает NLV ПОД ЗАМКОМ прямо перед решением.
    dec, orders, diff = DL.run_session(
        br, m, dirpath=str(state_dir()), route=route, capital=None, closing_nav=None,
        journal_path=str(state_dir() / f'journal-{route}.csv'), dry_run=dry,
        paper=paper_mode(),
        ref_prices=refs, book_path=str(bp), series_a=src.get('series'),
        # КРАЙ ТОРГОВОГО ОКНА ВНУТРЬ СЕССИИ (двадцатый круг, №6): один источник с
        # автопилотом (feed.trade_till), проверяется перед КАЖДОЙ заявкой.
        deadline=(None if dry else FD.trade_deadline(route)), **kw)
    # СОСТОЯВШЕЕСЯ СОКРАЩЕНИЕ О-3-Е — САМО ПО СЕБЕ СОБЫТИЕ ДЛЯ ТРЕВОГИ (тридцать первый
    # круг, №2). Условие входа было `dec.trade and orders`, а тревога ставилась только
    # если ПОВТОРНЫЙ замер всё ещё ниже 1,40. Но удачный срез поднимает запас ВЫШЕ порога —
    # значит в штатном исходе тревоги не возникало вовсе, и ветка «КНИГА СОКРАЩЕНА В ТУ ЖЕ
    # СЕССИЮ» была практически недостижима. Следствие денежное: аварийное сокращение до
    # L=1 прошло, причина не разобрана, а следующая сессия полосой наращивает книгу обратно
    # к 2x. Плюс срез возможен и в сессии БЕЗ первоначального ребаланса (orders пуст) —
    # такой день в эту ветку не заходил совсем.
    _cut0 = getattr(dec, 'o3e_cut', None)
    if route == 'E' and not dry and (bool(_cut0) or (dec.trade and orders)):
        # ЗАПАС ПОСЛЕ ИСПОЛНЕНИЙ (восемнадцатый круг, №1): предторговый замер относится к
        # СТАРОЙ книге; удвоение позиции могло увести фактический запас под порог, а
        # состояние сохранялось успешным. Пост-фактум сокращать нельзя (повторная торговля
        # в тот же запуск запрещена) — ставится ТРЕВОГА ФАЙЛОМ: ворота автопилота её видят
        # независимо от кода возврата, benign-ветка «день отторгован» её не подавляет.
        _pc = br.margin_cushion()
        # None НЕ ГЛОТАЕТСЯ (девятнадцатый круг, №10): неизвестный запас при живой книге —
        # такая же тревога, как известно-низкий; иначе обход всей пост-трейд починки.
        if post_o3e_alarm(_pc, dec.book_after, _cut0):
            _day = f'{m.date:%Y-%m-%d}'
            _af = state_dir() / f'ALARM-o3e-{_day}.txt'
            # ТЕКСТ НЕ ОБЪЯВЛЯЕТ НИЗКИМ ТО, ЧТО ИЗМЕРЕНО ВЫСОКИМ (№2): после удачного среза
            # повторный замер штатно ВЫШЕ порога, и прежняя формулировка «X ниже 1,40» была
            # бы прямой ложью в файле тревоги.
            _txt = (f'запас О-3-Е ПОСЛЕ исполнений НЕИЗВЕСТЕН (брокер не вернул '
                    f'требование при живой книге)' if _pc is None else
                    (f'запас О-3-Е ПОСЛЕ исполнений {_pc:.2f}x ниже {DL.O3E_MIN}'
                     if float(_pc) < DL.O3E_MIN else
                     f'запас О-3-Е ПОСЛЕ исполнений {_pc:.2f}x (порог {DL.O3E_MIN})'))
            # ТЕКСТ НЕ ОБЕЩАЕТ ТОГО, ЧТО САМ ЖЕ ЗАПРЕЩАЕТ (двадцать девятый круг, №4).
            # Прежняя формулировка «сокращение обязано пройти следующей сессией» ложна:
            # под этим самым ALARM контур НЕ ТОРГУЕТ, значит сокращение не произойдёт ни
            # следующей сессией, ни вообще — пока человек не снимет тревогу. По правилу О-5
            # автоматика не лечит сама, и это верно; неверно было обещать автоматическое
            # продолжение. Оператор должен знать: сокращение требует ЕГО действия.
            # ТЕКСТ ОПИСЫВАЕТ ФАКТ, А НЕ НАМЕРЕНИЕ (тридцатый круг, №1). Норматив §8
            # требует сокращения В ТУ ЖЕ СЕССИЮ, и оно теперь выполняется в run_session.
            # Здесь тревога сообщает, СОСТОЯЛОСЬ ли оно: без этого различия оператор не
            # может отличить сокращённую книгу от двухкратной, а это разные ночи.
            _cut = getattr(dec, 'o3e_cut', None)
            if _cut:
                _msg = (f'{_txt}. КНИГА СОКРАЩЕНА В ТУ ЖЕ СЕССИЮ по нормативу §8: '
                        f'{_cut[1]}/{_cut[2]} -> {_cut[3]}/{_cut[4]} (запас на момент '
                        f'замера {_cut[0]:.2f}×). Сокращение выполнено автоматикой, но '
                        f'ПРИЧИНА не разобрана: контур под этой тревогой не торгует до '
                        f'ручного снятия (О-5)\n')
            else:
                _msg = (f'{_txt} — книга сохранена, СОКРАЩЕНИЕ НЕ ВЫПОЛНЕНО (запас '
                        f'неизвестен либо книга пуста). ВНИМАНИЕ: под этой тревогой контур '
                        f'НЕ ТОРГУЕТ, поэтому сокращение до L=1 САМО НЕ ПРОИЗОЙДЁТ. '
                        f'Порядок: разобрать причину, при необходимости сократить вручную, '
                        f'затем снять тревогу (О-5)\n')
            try:
                _af.write_text(_msg, encoding='utf-8')
                if not _af.exists() or not _af.stat().st_size:
                    raise OSError('файл тревоги пуст после записи')
            except Exception as _exa:
                # запись тревоги не удалась — это само по себе повод остановить контур
                try:
                    (state_dir() / 'autopilot.STOP').write_text(
                        f'не удалось записать ALARM-o3e-{_day}: {_exa}\n', encoding='utf-8')
                except Exception:
                    pass
                raise Refused(f'запас О-3-Е ниже порога, но тревогу записать не удалось '
                              f'({_exa}) — поставлен СТОП-файл, ручной разбор')
            print(f'ТРЕВОГА: {_txt} — файл {_af.name}')

    print(f'\nрешение: плечо {dec.leverage:.4f}, книга '
          f'{getattr(dec.book_after, "n_e", "-")}/{getattr(dec.book_after, "n_b", "-")}')
    for r in dec.reasons:
        print('  причина:', r)
    for r in dec.refusals:
        print('  ОТКАЗ:', r)
    print('заявки:', orders or 'нет')
    if diff:
        print('РАСХОЖДЕНИЯ:', diff)
    print('режим:', 'наблюдение, заявки НЕ подавались' if dry else 'ЖИВОЙ')
    # ОТКАЗ ДНЯ — ОТКАЗ, А НЕ УСПЕХ (десятый круг, №5): прежде сессия с отказом решения
    # завершалась кодом 0, автопилот ставил «отторговано», и требуемый вход просто
    # отсутствовал при журнале «ок».
    #
    # НО ИСПОЛНЕННОЕ СОКРАЩЕНИЕ — СОСТОЯВШАЯСЯ СЕССИЯ (двадцать второй круг, №8): отказ
    # §8 законно пропускает снижение риска, run_session исполняет заявки и сохраняет книгу
    # с сегодняшней датой — а безусловный Refused после этого не давал автопилоту поставить
    # traded, вешал ALARM и запрещал замыкание; назавтра do_close отказывал по чужой дате.
    # Позиция у брокера изменена, а триггер капа закрытия не фиксировался ВООБЩЕ. День с
    # исполненными заявками завершается штатно (замыкание обязано пройти); отказ без
    # единой заявки — прежний Refused.
    if dec.refusals and not dry:
        if orders:
            print('ОТКАЗ §8 ПРИ ИСПОЛНЕННОМ СОКРАЩЕНИИ: день считается отторгованным, '
                  'замыкание обязательно; причины отказа выше')
        else:
            raise Refused('решение дня отвергнуто: ' + '; '.join(dec.refusals))
    if not dry:
        print('ПОСЛЕ ЗАКРЫТИЯ БИРЖИ выполнить: session.py --close')
    return dec


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--dry', action='store_true', help='считать и сверить, заявок не подавать')
    g.add_argument('--live', action='store_true', help='подать заявки на счёт')
    g.add_argument('--close', action='store_true', help='замкнуть сессию после закрытия биржи')
    # ОТДЕЛЬНЫЙ ВХОД ДЛЯ НОРМАТИВНОГО СОКРАЩЕНИЯ (тридцать первый круг, №1): вахта
    # автопилота обязана не только увидеть провал запаса, но и выполнить предписанное §8
    # сокращение в ту же сессию. Полный торговый путь для этого не годится — день уже
    # отторгован, и повторный ребаланс запрещён.
    g.add_argument('--o3e', action='store_true',
                   help='сократить книгу маршрута Е до L=1 по §8 в уже отторгованной сессии')
    ap.add_argument('--route', default='F', choices=('F', 'E'))
    ap.add_argument('--client-id', type=int, default=33)
    a = ap.parse_args()

    state_dir().mkdir(parents=True, exist_ok=True)
    ib = _connect(a.client_id)
    try:
        if a.close:
            do_close(ib, a.route)
        elif a.o3e:
            do_o3e_cut(ib, a.route)
        else:
            do_trade(ib, a.route, dry=a.dry)
    except Refused as ex:
        print(f'ОТКАЗ: {ex}')
        return 2                      # код возврата ставит ТОЛЬКО точка входа
    finally:
        ib.disconnect()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
