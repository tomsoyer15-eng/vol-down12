class Refused(RuntimeError):
    """Отказ по существу: условие §1/§8 не выполнено, сессия не считается.

    ОТКАЗ — НЕ ЗАВЕРШЕНИЕ ПРОЦЕССА. Прежде do_trade и do_close поднимали SystemExit, и любой
    вызывающий — планировщик, надзорный процесс, стенд проверок — молча УМИРАЛ вместо того,
    чтобы отказ обработать. Обнаружено проверкой последовательности из трёх сессий: стенд
    ловил Exception, SystemExit им не является, и прогон обрывался без единого сообщения.
    Код возврата ставит только main().
    """


HOST = os.environ.get('IB_HOST', '127.0.0.1')
PORT = int(os.environ.get('IB_PORT', '4002'))


def state_dir():
    """Каталог состояния читается ПРИ ВЫЗОВЕ, а не при импорте. Иначе переменная окружения,
    выставленная после импорта модуля, молча игнорируется — и запуск идёт по чужой книге.

    ОДИН NAMESPACE С КНИГОЙ И ЗАМКОМ (девятнадцатый круг, №17): без ADDFUT_DIR каталог
    берётся из state.lock_dir() — того же места, где живут замок и книга. Прежний
    самостоятельный ~/.addfut раздваивал пути: стенд с ADDFUT_LOCK_DIR писал журнал и
    тревогу О-3-Е в машинный каталог, а оператор с ADDFUT_DIR — мимо автопилота."""
    env = os.environ.get('ADDFUT_DIR')
    if env:
        return Path(env)
    import state as ST
    return Path(ST.lock_dir())


def post_o3e_alarm(cushion, book_after):
    """Нужна ли тревога ПОСЛЕ исполнений маршрута Е (девятнадцатый круг, №10).

    None при ЖИВОЙ книге — не «требования нет», а НЕИЗВЕСТНЫЙ запас: сводка брокера могла
    не обновиться после сделки. Прежнее условие «not None and < порога» глотало None и
    оставляло книгу ~2x без тревоги при фактическом запасе, возможно, ниже 1,40. None при
    ПУСТОЙ книге штатен: требования действительно нет."""
    if cushion is None:
        return bool(getattr(book_after, 'n_eq', 0) or getattr(book_after, 'n_bd', 0))
    return cushion < DL.O3E_MIN


def _connect(client_id):
    from ib_insync import IB
    ib = IB()
    ib.connect(HOST, PORT, clientId=client_id, timeout=30)
    # ТИП 3 — ЗАДЕРЖАННЫЕ ДАННЫЕ (~15 минут). Их достаточно для ориентира и для сверки
    # базиса, но НЕ для измерения качества исполнения: за 15 минут рынок проходит больше
    # модельных 5 б.п. (двадцать пятый круг, №15). Адаптер помечает такие строки как
    # НЕ-котировку момента, и §7 их в выборку издержек не берёт.
    ib.reqMarketDataType(3)
    return ib


def paper_mode():
    """Бумажный этап определяется ДВУМЯ независимыми признаками: портом шлюза и ТИПОМ
    СЧЁТА (двадцать третий круг, №6).

    Прежде хватало порта 4002. Но режим шлюза (TRADING_MODE в start.sh) от порта НЕ
    зависит, и API-порт настраивается: живой Gateway на 4002 давал paper=True, после чего
    маршрут Ф строился ниже порога §8 ($3 млн) как будто деньги ненастоящие. Пин счёта
    проверял ИМЯ, но не тип. У IBKR бумажные счета начинаются на DU/DF, боевые — на U/F,
    и это признак самого брокера, а не нашей конфигурации. Расхождение двух признаков —
    отказ: значит либо порт, либо счёт не тот, и угадывать тут нечего.
    """
    acct = (_account_pin() or '').strip().upper()
    acct_paper = acct.startswith(('DU', 'DF'))
    if PORT == 4002 and acct_paper:
        return True
    if PORT == 4002 and acct and not acct_paper:
        raise Refused(f'порт {PORT} бумажный, а счёт {acct} — БОЕВОЙ (не DU/DF): живой '
                      f'шлюз на бумажном порту снял бы порог §8 с настоящих денег')
    if PORT != 4002 and acct_paper:
        raise Refused(f'порт {PORT} не бумажный, а счёт {acct} — бумажный: конфигурация '
                      f'противоречива, торговля запрещена')
    if os.environ.get('ADDFUT_LIVE_OK') == '1':
        return False
    raise Refused(f'порт {PORT} не бумажный, а разрешения ADDFUT_LIVE_OK нет — '
                  f'торговля на живом контуре без явного решения запрещена')


def _book_path(route):
    import state as ST
    return ST.book_path(route)


def _account_pin():
    """ТОРГОВЫЙ СЧЁТ ПИНУЕТСЯ ЯВНО (двадцатый круг, №5).

    Пин в адаптере существовал, но в бою был МЁРТВ: ADDFUT_ACCOUNT не задавался нигде —
    ни в ibgw.env (там только логин и пароль), ни в autopilot.sh, ни в crontab. При одном
    managedAccount адаптер молча принимал тот счёт, который дал шлюз, поэтому вход в
    ДРУГОЙ счёт (правка ibgw.env, другой paper от IBKR) прошёл бы сверку с пустой книгой и
    получил полную позицию 2х, а ~/.addfut стал бы состоянием чужого счёта. Заодно
    оживают проверки, опирающиеся на этот же пин: счёт замера маржи (_live_margins) и
    фильтры чужих заявок и исполнений в адаптере.

    Источник — окружение либо файл счёта в ТОМ ЖЕ каталоге состояния, где книга и замок
    (один namespace путей, девятнадцатый круг, №17). Отсутствие пина — ОТКАЗ сессии, а не
    молчаливое «возьмём что дали»: это торговый вход, и он обязан знать свой счёт.
    """
    import state as ST
    pin = (os.environ.get('ADDFUT_ACCOUNT') or '').strip()
    if pin:
        return pin
    p = ST.lock_dir() / 'account.txt'
    try:
        pin = p.read_text(encoding='utf-8').strip()
    except OSError as ex:
        raise Refused(f'торговый счёт не пинован: нет ADDFUT_ACCOUNT и не читается {p} '
                      f'({ex}) — сессия запрещена (двадцатый круг, №5)')
    if not pin:
        raise Refused(f'торговый счёт не пинован: {p} пуст — сессия запрещена')
    return pin


def do_close(ib, route):
    """Замкнуть сессию по факту закрытия: фактические цены закрытия и фактический NLV.

    ВСЁ ПОД ОДНОЙ БЛОКИРОВКОЙ, И КНИГА ПЕРЕЧИТЫВАЕТСЯ ПЕРЕД ЗАПИСЬЮ. Прежняя редакция
    читала книгу, ходила к брокеру за NLV и ценами и только потом брала замок: между
    чтением и записью переходный исполнитель успевал перевести маршрут и сохранить новую
    книгу, а замыкание затирало её старой — классическая потерянная запись при фактической
    позиции уже на другом маршруте.

    ЗАМЫКАЕТСЯ ИМЕННО ТА СЕССИЯ, КОТОРАЯ ТОРГОВАЛА. Проверяется, что замыкание ещё не
    выполнялось и что дата книги совпадает с сегодняшней биржевой: иначе пропущенное в
    понедельник замыкание, запущенное во вторник, посчитало бы триггер капа по вторничным
    ценам для понедельничной книги, а повторный запуск переписал бы его ещё раз.
    """
    import state as ST
    br = IBB.IBBroker(ib, account=_account_pin())
    bp = _book_path(route)
    cls = DL.BookE if route == 'E' else DL.Book
    with ST.hold_book_lock():
        book, sess, saved = ST.load(bp, cls)
        if book is None:
            raise Refused('нет сохранённой книги — замыкать нечего')
        if saved != route:
            raise Refused(f'книга записана для маршрута {saved}, запрошен {route}')
        if not getattr(book, 'close_provisional', False):
            raise Refused(f'сессия №{sess} уже замкнута (плечо закрытия '
                             f'{book.prev_close_lev:.4f}); повторное замыкание переписало бы '
                             f'триггер капа §1 по ценам другой сессии')
        today = FD.exchange_today().strftime('%Y-%m-%d')
        if book.last_session and book.last_session != today:
            raise Refused(
                f'книга относится к сессии {book.last_session}, а сегодня {today}: замкнуть '
                f'её сегодняшними ценами значит посчитать триггер капа §1 по чужому '
                f'закрытию. Требуется ручной разбор (О-5)')
        # СВЕРКА С БРОКЕРОМ ПЕРЕД ФИКСАЦИЕЙ ПЛЕЧА (№9): поздний фил, чужая позиция или
        # живая заявка не должны попадать в триггер капа как «чистое закрытие».
        # БАРЬЕР НЕЗАВЕРШЁННОЙ ПЕРЕДАЧИ И ДЛЯ ЗАМЫКАНИЯ (двадцать пятый круг, №13). Метку
        # проверяла только торговая сессия: после смерти перехода между публикацией книги и
        # TRANSITION_COMPLETE замыкание успешно финализировало книгу, ставило closed-*,
        # делало backup и WORM-якорь — то есть заверяло «замкнутое» состояние НЕЗАВЕРШЁННОГО
        # перехода, пока нормативный журнал держал TRANSITION_OPEN.
        _hf = ST.lock_dir() / f'handover-inflight-{route}.txt'
        if _hf.exists():
            raise Refused(
                f'{_hf}: передача книги начата, но COMPLETE не записан — замыкать '
                f'незавершённый переход нельзя, плечо закрытия относилось бы к книге '
                f'без нормативного подтверждения (О-5)')
        # СОГЛАСОВАННЫЙ СНИМОК (двадцать четвёртый круг, №6): обе сверки замыкания читали
        # позиции, затем заявки — та же гонка, что в run_session. Поздний fill между
        # вызовами делал сверку ложной, и плечо закрытия фиксировалось по книге, которой
        # у брокера уже нет.
        import daily as _DLc
        _pos_c, _oo_c = _DLc._snapshot_consistent(br)
        diff = ST.reconcile(book, route, _pos_c, open_orders=_oo_c)
        if diff:
            raise Refused('замыкание отменено — книга расходится с брокером:\n  '
                          + '\n  '.join(diff))
        px_eq, dref, px_bd, src = FD.closing_values(ib, route, book)
        # NLV — ПОСЛЕ цен закрытия (тринадцатый круг, №3): триггер капа обязан делить цены
        # и капитал ОДНОГО момента; ранний NAV с поздними ценами искажал prev_close_lev.
        nav = br.net_liquidation()
        # ПОВТОРНАЯ СВЕРКА ПОСЛЕ ДОЛГИХ ЗАПРОСОВ (десятый круг, №11): поздний фил или новая
        # заявка в окне запросов цен не должны попадать в триггер капа незамеченными.
        _pos_c2, _oo_c2 = _DLc._snapshot_consistent(br)
        diff2 = ST.reconcile(book, route, _pos_c2, open_orders=_oo_c2)
        if diff2:
            raise Refused('замыкание отменено — брокер изменился за время запросов:\n  '
                          + '\n  '.join(diff2))
        book2, sess2, saved2 = ST.load(bp, cls)
        if (vars(book2) != vars(book)) or sess2 != sess or saved2 != saved:
            raise Refused('книга изменилась, пока снимались цены закрытия — замыкание '
                             'отменено во избежание потерянной записи')
        closed = DL.finalize_close(book, px_eq, dref, nav, route=route, px_bd_close=px_bd)
        ST.save(bp, closed, route, sess, note='замыкание сессии по факту закрытия')
    print(f'замкнуто: NLV закрытия {nav:,.2f}, вход {src}')
    print(f'плечо закрытия {closed.prev_close_lev:.4f} — триггер капа следующей сессии')
    return closed


def do_trade(ib, route, dry):
    import state as ST

    br = IBB.IBBroker(ib, account=_account_pin())
    nlv = br.net_liquidation()
    pos = br.net_positions()
    alien = [k for k in pos if k.startswith('НЕИЗВЕСТНЫЙ')]
    if alien:
        raise Refused(f'на счёте посторонние позиции {alien} — сессия не считается')

    bp = _book_path(route)
    cls = DL.BookE if route == 'E' else DL.Book
    book, sess, _ = ST.load(bp, cls)
    book = book or cls()

    # НЕЗАМКНУТАЯ ПРЕДЫДУЩАЯ СЕССИЯ — ОТКАЗ, А НЕ ПРЕДУПРЕЖДЕНИЕ. Плечо закрытия в такой
    # книге посчитано по ценам открытия и утреннему NLV, то есть триггер капа §1 заведомо
    # неверен. Торговать по нему хуже, чем пропустить сессию.
    # БЕЗ условия sess>0: книга, принятая от перехода, приходит с провизорным замыканием и
    # обязана его пройти; прежняя проверка «if sess and ...» на ней отключалась.
    if getattr(book, 'close_provisional', False) and book.last_session and not dry:
        raise Refused(f'сессия №{sess} не замкнута: плечо закрытия предварительное, '
                         f'триггер капа §1 недостоверен. Выполнить: session.py --close')

    # ДАТА СЕССИИ — БИРЖЕВАЯ. По часам машины запуск около полуночи UTC пометил бы
    # сделку соседней датой, и last_session либо заблокировал бы правильный запуск,
    # либо допустил второй под другой локальной датой.
    m, src = FD.build_market(ib, FD.exchange_today(), book, route=route)
    print(f'счёт {br.account}: NAV {nlv:,.2f}; позиции {pos or "нет"}; сессия №{sess + 1}')
    print('вход: ' + ', '.join(f'{k}={v}' for k, v in src.items()))

    # ПОРОГ §8 НЕ ОТКЛЮЧАЕТСЯ, А ЯВНО ИСКЛЮЧАЕТСЯ НА БУМАЖНОМ ЭТАПЕ, и это пишется в
    # журнал: молчаливый обход политики был бы ровно тем, ради чего этап и заведён.
    # ЦЕНЫ-ОРИЕНТИРЫ СНИМАЮТСЯ ДО ЗАЯВОК: без них журнал §7 не накапливает наблюдений.
    refs = FD.reference_prices(ib, route=route)
    _miss = {k: v for k, v in refs.items() if k.startswith('ОРИЕНТИР-НЕТ:')}
    refs = {k: v for k, v in refs.items() if not k.startswith('ОРИЕНТИР-НЕТ:')}
    print('ориентиры:', {k: round(v, 4) for k, v in refs.items()})
    for _k, _v in _miss.items():
        print(f'  {_k}: {_v}')
    kw = {}
    if route == 'E':
        # ЖИВОЙ ЗАПАС О-3-Е — ОТ БРОКЕРА (десятый круг, №2): расчётная прокси при капе 2,00
        # не опускается ниже порога, и аварийное сокращение было недостижимо в бою.
        _lc = br.margin_cushion()
        # СУЖДЕНИЕ ПО КНИГЕ, А НЕ ПО РАННЕМУ СНИМКУ (двадцать третий круг, №19). Отказ
        # зависел от any(pos.values()) — снимка позиций, взятого РАНЬШЕ и, возможно,
        # пустого или устаревшего; загруженная book при этом не использовалась вовсе.
        # Если снимок пуст, а книга несёт позиции, step_e получал live_cushion=None и
        # переключался на расчётную прокси, недостижимую при капе 2,00 — то есть на
        # сессии без заявок пост-трейд проверка не выполнялась бы вообще.
        _book_live = bool(book is not None and (getattr(book, 'n_eq', 0) or
                                                getattr(book, 'n_bd', 0)))
        if _lc is None and (_book_live or any(v for v in (pos or {}).values())):
            # НУЛЕВОЕ/ОТСУТСТВУЮЩЕЕ ТРЕБОВАНИЕ ПРИ СУЩЕСТВУЮЩИХ ПОЗИЦИЯХ (семнадцатый
            # круг, №7) — неполный ответ брокера, а не «позиций нет»: прокси 25% дала бы
            # запас 2,0 и оставила бы полную позицию вместо аварийного сокращения.
            raise Refused('живой запас О-3-Е недоступен при существующих позициях — '
                          'торговля Е запрещена до восстановления данных брокера')
        # ЗАПАС ЧИТАЕТСЯ ВНУТРИ СЕССИИ, А НЕ ЗАРАНЕЕ (двадцать четвёртый круг, №11).
        # Прежде live_cushion снимался ДО книжного замка и до согласованного снимка, а
        # затем передавался готовой константой; NLV при этом перечитывался внутри
        # run_session. Между чтениями маржа могла упасть, и step_e не выполнил бы
        # обязательное сокращение — вахта потом лишь ставила ALARM, но в ту же сессию не
        # сокращала. Передаём ФУНКЦИЮ: run_session вызовет её под замком, рядом с NLV.
        kw['live_cushion'] = _lc
        kw['live_cushion_fn'] = br.margin_cushion
    # NLV НЕ ПЕРЕДАЁТСЯ снаружи (тринадцатый круг, №2): между ранним чтением и заявками —
    # серия долгих запросов; run_session сам читает NLV ПОД ЗАМКОМ прямо перед решением.
    dec, orders, diff = DL.run_session(
        br, m, dirpath=str(state_dir()), route=route, capital=None, closing_nav=None,
        journal_path=str(state_dir() / f'journal-{route}.csv'), dry_run=dry,
        paper=paper_mode(),
        ref_prices=refs, book_path=str(bp), series_a=src.get('series'),
        # КРАЙ ТОРГОВОГО ОКНА ВНУТРЬ СЕССИИ (двадцатый круг, №6): один источник с
        # автопилотом (feed.trade_till), проверяется перед КАЖДОЙ заявкой.
        deadline=(None if dry else FD.trade_deadline(route)), **kw)
    if route == 'E' and not dry and dec.trade and orders:
        # ЗАПАС ПОСЛЕ ИСПОЛНЕНИЙ (восемнадцатый круг, №1): предторговый замер относится к
        # СТАРОЙ книге; удвоение позиции могло увести фактический запас под порог, а
        # состояние сохранялось успешным. Пост-фактум сокращать нельзя (повторная торговля
        # в тот же запуск запрещена) — ставится ТРЕВОГА ФАЙЛОМ: ворота автопилота её видят
        # независимо от кода возврата, benign-ветка «день отторгован» её не подавляет.
        _pc = br.margin_cushion()
        # None НЕ ГЛОТАЕТСЯ (девятнадцатый круг, №10): неизвестный запас при живой книге —
        # такая же тревога, как известно-низкий; иначе обход всей пост-трейд починки.
        if post_o3e_alarm(_pc, dec.book_after):
            _day = f'{m.date:%Y-%m-%d}'
            _af = state_dir() / f'ALARM-o3e-{_day}.txt'
            _txt = (f'запас О-3-Е ПОСЛЕ исполнений {_pc:.2f}x ниже {DL.O3E_MIN}'
                    if _pc is not None else
                    f'запас О-3-Е ПОСЛЕ исполнений НЕИЗВЕСТЕН (брокер не вернул '
                    f'требование при живой книге)')
            _af.write_text(f'{_txt} — книга сохранена, сокращение до L=1 обязано пройти '
                           f'следующей сессией; ручной разбор (О-5)\n', encoding='utf-8')
            print(f'ТРЕВОГА: {_txt} — файл {_af.name}')

    print(f'\nрешение: плечо {dec.leverage:.4f}, книга '
          f'{getattr(dec.book_after, "n_e", "-")}/{getattr(dec.book_after, "n_b", "-")}')
    for r in dec.reasons:
        print('  причина:', r)
    for r in dec.refusals:
        print('  ОТКАЗ:', r)
    print('заявки:', orders or 'нет')
    if diff:
        print('РАСХОЖДЕНИЯ:', diff)
    print('режим:', 'наблюдение, заявки НЕ подавались' if dry else 'ЖИВОЙ')
    # ОТКАЗ ДНЯ — ОТКАЗ, А НЕ УСПЕХ (десятый круг, №5): прежде сессия с отказом решения
    # завершалась кодом 0, автопилот ставил «отторговано», и требуемый вход просто
    # отсутствовал при журнале «ок».
    #
    # НО ИСПОЛНЕННОЕ СОКРАЩЕНИЕ — СОСТОЯВШАЯСЯ СЕССИЯ (двадцать второй круг, №8): отказ
    # §8 законно пропускает снижение риска, run_session исполняет заявки и сохраняет книгу
    # с сегодняшней датой — а безусловный Refused после этого не давал автопилоту поставить
    # traded, вешал ALARM и запрещал замыкание; назавтра do_close отказывал по чужой дате.
    # Позиция у брокера изменена, а триггер капа закрытия не фиксировался ВООБЩЕ. День с
    # исполненными заявками завершается штатно (замыкание обязано пройти); отказ без
    # единой заявки — прежний Refused.
    if dec.refusals and not dry:
        if orders:
            print('ОТКАЗ §8 ПРИ ИСПОЛНЕННОМ СОКРАЩЕНИИ: день считается отторгованным, '
                  'замыкание обязательно; причины отказа выше')
        else:
            raise Refused('решение дня отвергнуто: ' + '; '.join(dec.refusals))
    if not dry:
        print('ПОСЛЕ ЗАКРЫТИЯ БИРЖИ выполнить: session.py --close')
    return dec


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--dry', action='store_true', help='считать и сверить, заявок не подавать')
    g.add_argument('--live', action='store_true', help='подать заявки на счёт')
    g.add_argument('--close', action='store_true', help='замкнуть сессию после закрытия биржи')
    ap.add_argument('--route', default='F', choices=('F', 'E'))
    ap.add_argument('--client-id', type=int, default=33)
    a = ap.parse_args()

    state_dir().mkdir(parents=True, exist_ok=True)
    ib = _connect(a.client_id)
    try:
        if a.close:
            do_close(ib, a.route)
        else:
            do_trade(ib, a.route, dry=a.dry)
    except Refused as ex:
        print(f'ОТКАЗ: {ex}')
        return 2                      # код возврата ставит ТОЛЬКО точка входа
    finally:
        ib.disconnect()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
